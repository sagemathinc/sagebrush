"""Writes lib/seaborn/_cm.py: seaborn's own colormaps that Sagebrush's seaborn draws with (rocket, the default of
heatmap, and icefire, its default with center=), each its table of 256 RGB colors exactly as seaborn 0.13.2's
seaborn/cm.py lists them.  Run with a CPython that has seaborn 0.13.2:
    python3 scripts/seaborn_cm_gen.py > lib/seaborn/_cm.py"""
import seaborn
from seaborn import cm

assert seaborn.__version__ == "0.13.2", seaborn.__version__
NAMES = ("rocket", "icefire")
print('"""seaborn 0.13.2\'s colormaps rocket and icefire: each one\'s 256 RGB colors, as seaborn/cm.py lists them.')
print("Generated by scripts/seaborn_cm_gen.py from seaborn run as a black box; seaborn's license (BSD 3-Clause) is in")
print('THIRD-PARTY-NOTICES, under seaborn."""')
print()
print("TABLES = {")
for name in NAMES:
    lut = getattr(cm, "_%s_lut" % name)
    assert len(lut) == 256
    print("    %r: (" % name)
    for c in lut:
        print("        (%r, %r, %r)," % tuple(float(v) for v in c))
    print("    ),")
print("}")
