case("frame.tail-neg", lambda: pd.DataFrame({"a": range(5)}).tail(-2))
case("frame.head-index", lambda: pd.DataFrame({"a": range(10)}).head(3).index)
case("frame.sample", lambda: pd.DataFrame({"a": range(10)}).sample(3, random_state=1))
case("frame.sample-index", lambda: pd.DataFrame({"a": range(10)}).sample(3, random_state=1).index)
case("frame.isna", lambda: pd.DataFrame({"a": [1.0, None], "s": ["x", None]}).isna())
case("frame.notna", lambda: pd.DataFrame({"a": [1.0, None], "s": ["x", None]}).notna())
case("frame.copy-independent", lambda: (lambda c: (c.__setitem__("a", 0), d)[1])(d.copy()))

case("series.name", lambda: s.name)
