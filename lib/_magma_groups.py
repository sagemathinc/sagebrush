"""Magma mode's permutation groups on Sagebrush's group engine (engine/group,
the perm_group operation Sage mode's PermutationGroup uses too):
PermutationGroup< n | ... >, sub< G | ... >, Alt(n), CyclicGroup(n), and the
invariants of any permutation group (Sym(n) and DihedralGroup(n) included):
Order, #, Ngens, G.i, membership and coercion, eq and subset, Orbits, Orbit,
Stabilizer, IsTransitive, IsAbelian, IsSolvable, DerivedSubgroup.

lib/_magma.py's intrinsics call into this module, loaded the first time one
is used, so Magma mode's start doesn't carry it.

What is Magma's and what is Sagebrush's (checked against Magma 2.18-5):
orders, orbits (each point's orbit in the order Magma lists it), and every
yes/no answer are Magma's; so are the generators of PermutationGroup, sub,
Alt(n) and CyclicGroup(n), and when a group prints its order (once Magma
would know it).  The generators of a group Sagebrush computes (Stabilizer,
DerivedSubgroup) are Sagebrush's own: the same group, other generators."""

import _magma as _m
from _magma import MagmaError, MSeq, MSet, _MPerm, _MSymGroup, _MDihedralGroup, _global_name, _order_text

GROUP_TYPES = (_MSymGroup, _MDihedralGroup)


def _chain_bytes(n, gens):
    """The certain part of the engine's stabilizer chain for the group of
    degree n the generators gens give, in bytes: its first level, n slots
    of 48 bytes, and for each point of the orbit of its base point (the
    first point the first generator other than the identity moves, as the
    engine chooses it) an element and its inverse (8n bytes).  Only that is
    charged before the engine is called, whether or not the order is known:
    the engine's own work and the heap decide the rest, as for Sage mode's
    groups (a bound on the other levels would refuse groups that fit: a
    cyclic group of degree 4000 needs one level, about 128 MB)."""
    g = next((g for g in gens if any(g[x - 1] != x for x in range(1, n + 1))), None)
    if g is None:
        return 48 * n
    moved = next(x for x in range(1, n + 1) if g[x - 1] != x)
    return 48 * n + len(_orbit_of(gens, moved)) * 8 * n


def _orbit_of(gens, x):
    """The orbit of the point x under the generators (image tuples on 1 ..
    n), breadth first from x, each point's images under the generators in
    turn: the order Magma lists an orbit in."""
    seen, out, i = {x}, [x], 0
    while i < len(out):
        p = out[i]
        i += 1
        for g in gens:
            q = g[p - 1]
            if q not in seen:
                seen.add(q)
                out.append(q)
    return out


# the operations whose engine work keeps a permutation for every pair of
# generators (Group::derived_subgroup: each pair's commutator, before the
# normal closure); the series repeats it on the subgroup, whose generators
# the engine has reduced to a few
_PAIRWISE = frozenset(("derived_subgroup", "derived_series", "is_solvable"))


def _engine_bytes(n, gens, what=()):
    """What is certain of the engine's memory for an operation on the group
    of degree n the generators gens give: its stabilizer chain's first
    level, the generators it is given (4n bytes each, in a slot of 64), and
    for an operation of _PAIRWISE a permutation for each pair of
    generators."""
    perm, k = 4 * n + 64, len(gens)
    need = _chain_bytes(n, gens) + k * perm
    if _PAIRWISE.intersection(what):
        need += k * (k - 1) // 2 * perm
    return need


def _admit_points(count):
    """The collection guard's refusal before a group's own lists are made:
    count points in all (a group of degree n with k generators keeps k lists
    of n points, and its identity, orbits and elements are lists of n)."""
    if count > _m._COLLECT_MAX:
        raise _m._collect_refusal()


def _admit(n, gens, what=()):
    """The memory guard's refusal, before the engine is called, when the
    operation (its chain, generators and temporaries) may not fit the
    allowance of one computation."""
    need, allow, k = _engine_bytes(n, gens, what), _m._COLLECT_MAX * _m._COLLECT_COST, len(gens)
    if need > allow:
        import _capacity
        e = _m._memory_error(_m._memguard.memory_guard("A permutation group of degree %d with %d generator%s (its stabilizer chain and working space)" % (n, k, "" if k == 1 else "s"), need, allow,
                                                       "one computation", fixed=_m._COLLECT_MAX == 10 ** 6))
        e.capacity = _capacity.capacity()
        raise e


def _call(what, n, gens, **extra):
    """The group engine's answers (points 0 .. n-1) for the group of degree n
    generated by gens (image tuples on 1 .. n), admitted first.  The engine
    is given each distinct generator once, the identity left out: the same
    group."""
    ident = tuple(range(1, n + 1))
    gens = [g for g in dict.fromkeys(tuple(g) for g in gens) if g != ident]
    _admit(n, gens, what)
    from _sagebrush_lib._engine import call
    g = [[x - 1 for x in im] for im in gens] or [list(range(n))]
    return call("perm_group", n=n, gens=g, what=list(what), **extra)


def is_group(x):
    return isinstance(x, GROUP_TYPES) or isinstance(x, MPermGroup)


def gens_of(G):
    """G's generators as image tuples: Magma's own for Sym(n) ((1, ..., n),
    (1, 2)) and DihedralGroup(n)."""
    if isinstance(G, MPermGroup):
        return list(G.gens)
    if isinstance(G, _MDihedralGroup):
        return [p.images for p in G._gens()]
    n = G.n
    if n == 1:
        return []
    if n == 2:
        return [(2, 1)]
    return [tuple(list(range(2, n + 1)) + [1]), tuple([2, 1] + list(range(3, n + 1)))]


def order(G):
    if isinstance(G, MPermGroup):
        return G._order_value()
    return G._magma_card()


def _known(G):
    """Magma now knows G's order (it prints it from then on)."""
    if isinstance(G, MPermGroup):
        G._order_value()


class _MapNotModelled:
    """The map PermutationGroup< ... > and sub< ... > also return (Magma
    prints it after the group when the constructor is printed): not
    modelled, so printing or using it is refused."""

    def __init__(self, name):
        self.name = name

    def _refuse(self, *args):
        raise MagmaError("printing %s< ... > itself (Magma prints its second value, a map, with it) is not supported yet: assign it, "
                         "G := %s< ... >" % (self.name, self.name), "%s< ... >" % self.name)

    __repr__ = __str__ = __call__ = _refuse


class MPermGroup:
    """A permutation group of degree n given by generators (GrpPerm); its
    elements are _MPerm's of it.  Its order is computed by the engine when
    first needed and printed from then on, as Magma's is."""

    _lazy_magma_type = "GrpPerm"
    _lazy_ext_type = "GrpPerm"

    def __init__(self, n, gens, order=None, kind="Permutation group"):
        self.n, self.gens, self._order, self.kind = n, [tuple(g) for g in gens], order, kind

    def __repr__(self):
        name = _global_name(self)
        # (once its order is known to be n!, Magma names it the symmetric group)
        kind = "Symmetric group" if self._order is not None and self._order == _m._math.factorial(self.n) else self.kind
        lines = ["%s %sacting on a set of cardinality %d" % (kind, name + " " if name else "", self.n)]
        if self._order is not None:
            lines.append(_order_text(self._order))
        for g in self.gens:
            t = repr(_MPerm(self, g))
            if len(t) + 4 > _m.WIDTH - 1:
                # (Magma wraps a long generator, in a layout not modelled)
                raise MagmaError("printing a permutation group whose generators are longer than a line is not supported yet")
            lines.append("    " + t)
        return "\n".join(lines)

    def __hash__(self):
        return hash(("GrpPerm", self.n))

    def _order_value(self):
        if self._order is None:
            self._order = int(_call(["order"], self.n, self.gens)["order"])
        return self._order

    def _magma_card(self):
        return self._order_value()

    def _identity(self):
        return _MPerm(self, tuple(range(1, self.n + 1)))

    def _magma_gen(self, i):
        k = len(self.gens)
        if isinstance(i, bool) or not isinstance(i, int) or not -k <= i <= k:
            raise MagmaError("Argument 2 (%s) should be in the range [%d .. %d]" % (i, -k, k), "'.'", True)
        if i == 0:
            return self._identity()
        g = _MPerm(self, self.gens[abs(i) - 1])
        return g if i > 0 else g._inverse()

    def _has(self, images):
        return bool(_call(["contains"], self.n, self.gens, g=[x - 1 for x in images])["contains"])

    def _magma_contains(self, x):
        if isinstance(x, (_m.MTuple, _m._MCycles)):
            # (cycles alone, (1, 2)(3, 4) in G: Magma has no group to make them in)
            raise MagmaError("No permutation group context in which to create cycle", "elt< ... >", True)
        if not isinstance(x, _MPerm) or x.G.n != self.n:
            raise MagmaError("Bad argument types\nArgument types given: %s, GrpPerm" % _m._ext_type(x), "'in'", True)
        if x.G is self:
            return True
        _known(self)
        return self._has(x.images)

    def _magma_coerce(self, x):
        p = x if isinstance(x, _MPerm) else _MSymGroup(self.n)._magma_coerce(x)
        if p.G is self:
            return p
        if p.G.n != self.n:
            raise _m._no_covering_group()
        _known(self)
        if self._has(p.images):
            return _MPerm(self, p.images)
        raise MagmaError("Illegal coercion\nLHS: GrpPerm\nRHS: GrpPermElt", "'!'", False)


def contains_all(G, H):
    """Whether every generator of H is in G (H a subgroup of G)."""
    if G is H or isinstance(G, _MSymGroup):
        return True
    return all(_has(G, g) for g in gens_of(H))


def _has(G, images):
    if isinstance(G, MPermGroup):
        return G._has(images)
    if isinstance(G, _MDihedralGroup):
        return G._has(images)
    return True


class GroupKey:
    """A permutation group as a set or dictionary key: equal groups (the
    same degree and elements, eq) are one key, as Magma's {Alt(4), Alt(4)}
    has one element.  Being a key makes the group's order known, as in
    Magma."""

    __slots__ = ("G", "_h")

    def __init__(self, G):
        _known(G)
        self.G, self._h = G, hash(("GrpPerm", G.n, order(G)))

    def __hash__(self):
        return self._h

    def __eq__(self, other):
        return isinstance(other, GroupKey) and equal(self.G, other.G)


def subset(H, G):
    """H subset G for permutation groups of one degree."""
    if H.n != G.n:
        raise MagmaError("Bad argument types\nArgument types given: GrpPerm, GrpPerm", "'subset'", True)
    _known(G)
    return contains_all(G, H)


def equal(G, H):
    if G is H:
        return True
    if G.n != H.n:
        return False
    _known(G)
    _known(H)
    return order(G) == order(H) and contains_all(G, H)


def construct(n, gens, pos=None):
    """PermutationGroup< n | gens >: each generator a permutation (of a group
    of degree n), cycles or a sequence of images."""
    if isinstance(n, bool) or not isinstance(n, int):
        raise MagmaError("Bad argument types", "PermutationGroup< ... >", True, pos)
    if n < 1:
        # (Magma's words: the group's universe, Sym(n), can't be made)
        raise MagmaError("Argument 1 (%d) should be >= 1" % n, "'SymmetricGroup'", True, pos)
    # (its generators and its identity are lists of n points: admitted
    # first, as one collection, before any is made)
    _admit_points((len(gens) + 1) * n)
    S = _MSymGroup(n)
    ims = [(g if isinstance(g, _MPerm) and g.G.n == n else S._magma_coerce(g)).images for g in gens]
    return _m._multi([MPermGroup(n, ims), _MapNotModelled("PermutationGroup")])


def sub(G, gens, pos=None):
    """sub< G | gens >: the subgroup of G they generate, each coerced into
    G (an element not in G is Magma's Illegal coercion)."""
    if not is_group(G):
        raise MagmaError("sub< ... > of this structure is not supported yet", "sub< ... >", True, pos)
    _admit_points((len(gens) + 1) * G.n)
    ims = []
    for g in gens:
        try:
            ims.append(G._magma_coerce(g).images)
        except MagmaError as e:
            if "Illegal coercion" not in str(e):
                raise
            # (an element not in G: Magma's words)
            raise MagmaError("Can not build a generator from the arguments given", "sub< ... >", True, pos)
    return _m._multi([MPermGroup(G.n, ims), _MapNotModelled("sub")])


def alt(n):
    """Alt(n) with Magma's generators: (3, 4, ..., n) and (1, 2, 3) for odd
    n, (1, 2)(3, 4, ..., n) and (1, 2, 3) for even n; (1, 2, 3) alone for
    n = 3; none for n < 3, whose groups print without their order, as
    Magma's do."""
    if n < 3:
        return MPermGroup(n, [])
    if n == 3:
        return MPermGroup(3, [(2, 3, 1)], 3)
    rest = list(range(4, n + 1)) + [3]
    if n % 2:
        a = (1, 2) + tuple(rest)
    else:
        a = (2, 1) + tuple(rest)
    return MPermGroup(n, [a, (2, 3, 1) + tuple(range(4, n + 1))], _m._math.factorial(n) // 2)


def cyclic(n):
    """CyclicGroup(n): generated by (1, 2, ..., n); CyclicGroup(1) and (2)
    are Sym(1) and Sym(2), as Magma's are."""
    if n <= 2:
        return _MSymGroup(n)
    return MPermGroup(n, [tuple(list(range(2, n + 1)) + [1])], n)


def _gset(points):
    return GSet(points, "indexed")


class GSet(MSet):
    """An orbit (GSetIndx): printed GSet{@ ... @}."""
    __slots__ = ()
    _gset = True


def _orbit_points(G, x):
    """The orbit of x in the order Magma lists it: breadth first from x,
    each point's images under the generators in turn."""
    return _orbit_of(gens_of(G), x)


def orbit(G, x):
    if isinstance(x, bool) or not isinstance(x, int) or not 1 <= x <= G.n:
        raise MagmaError("Cannot apply permutation to this object", "'Orbit'", True, _m._call_pos("Orbit"))
    return _gset(_orbit_points(G, x))


def orbits(G):
    """Magma's order: by size, then by the least point, each from its least
    point."""
    seen, orbs = set(), []
    for x in range(1, G.n + 1):
        if x not in seen:
            o = _orbit_points(G, x)
            seen.update(o)
            orbs.append(o)
    orbs.sort(key=lambda o: (len(o), o[0]))
    return MSeq([_gset(o) for o in orbs])


def is_transitive(G):
    return len(_orbit_points(G, 1)) == G.n


def _engine_group(G, what, **extra):
    return _call([what], G.n, gens_of(G), **extra)[what]


def stabilizer(G, x):
    if isinstance(x, bool) or not isinstance(x, int) or not 1 <= x <= G.n:
        raise MagmaError("Cannot compute stabilizer of this object", "'Stabilizer'", True, _m._call_pos("Stabilizer"))
    _known(G)
    r = _engine_group(G, "stabilizer", point=x - 1)
    return MPermGroup(G.n, [tuple(y + 1 for y in g) for g in r["gens"]], int(r["order"]))


def derived_subgroup(G):
    _known(G)
    r = _engine_group(G, "derived_subgroup")
    return MPermGroup(G.n, [tuple(y + 1 for y in g) for g in r["gens"]], int(r["order"]))


def is_abelian(G):
    return bool(_engine_group(G, "is_abelian"))


def is_solvable(G):
    _known(G)
    return bool(_engine_group(G, "is_solvable"))


def ngens(G):
    return len(gens_of(G)) if not isinstance(G, _MSymGroup) or G.n > 2 else (1 if G.n == 2 else 0)
