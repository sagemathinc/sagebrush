% Linear algebra.  Results that depend on the order of floating-point
% operations (LAPACK's) are rounded to 10 significant digits.
r = @(x) round(x * 1e10) / 1e10 + 0;  % (+ 0: no -0 from rounding noise)
A = [4 -2; 1 1];
b = [2; 3];
show(r(A \ b));
show(r(b' / A));
show(r(inv(A)));
show(r(det(A)));
show(det(magic(3)));
show(rank(magic(4)));
show(rank(eye(3)));
show(trace(A));
show(r(norm([3 4])));
show(norm([1 2; 3 4], 1));
show(norm([1 2; 3 4], Inf));
show(r(norm([1 2; 3 4], 'fro')));
show(r(norm([1 2; 3 4])));
show(r(eig([2 0; 0 3])));
show(r(eig([2 1; 1 2])));
show(r(sort(eig(magic(3)))));
[V, D] = eig([2 0; 0 5]);
show(r(abs(V)));
show(r(D));
S = [4 1; 1 3];
[V2, D2] = eig(S);
show(r(abs(S * V2 - V2 * D2)) < 1e-9);
show(r(svd([3 0; 0 4])));
x = [1 2 3; 4 5 6; 7 8 10] \ [1; 2; 3];
show(r(x));
show(r([1 2; 3 4] * inv([1 2; 3 4])));
show([1 2; 3 4] .* [1 0; 0 1]);
show([1 2 3] * [4; 5; 6]);
show([1; 2] * [3 4]);
show(r([1 2; 3 4] ^ -1));
show(r(pinv([1 2; 2 4]) * 50));
L = chol([4 2; 2 3]);
show(r(L' * L));
[Q, R] = qr([1 2; 3 4]);
show(r(abs(Q * R - [1 2; 3 4])) < 1e-12);
show(r(expm(zeros(2))));
show(r(expm([0 1; 0 0])));
show(r(roots([1 -3 2])));
show(r(poly([1 2])));
show(kron(eye(2), [1 2]));
show(r(null([1 1])' * [1; 1]));
show(r(cond([1 0; 0 2])));
x2 = [2 1; 1 3] \ [3; 5];
show(r(x2));
y = [1 2; 3 4; 5 6] \ [1; 2; 3];
show(r(y));
show(r(lu([4 3; 6 3])));
[L2, U2, P2] = lu([1 2; 3 4]);
show(r(L2));
show(r(U2));
show(P2);
