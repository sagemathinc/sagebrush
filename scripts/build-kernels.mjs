// Build the Rust WebAssembly kernels (kernels/) and embed them as base64 in
// src/runtime/kernels_wasm.ts, which is committed so that building
// sagebrush does not require Rust.  Run: node scripts/build-kernels.mjs
// (--check: compare with the committed file instead of writing it)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// the main module (simd128), and exp/log with relaxed SIMD (kernels/relaxed)
function build(dir, name, features) {
  execFileSync("cargo", ["build", "--release", "--target", "wasm32-unknown-unknown"], {
    cwd: join(root, dir),
    stdio: "inherit",
    env: { ...process.env, RUSTFLAGS: `-C target-feature=${features}` },
  });
  const wasm = readFileSync(join(root, dir, `target/wasm32-unknown-unknown/release/${name}.wasm`));
  new WebAssembly.Module(wasm); // validate
  return wasm;
}
// With --check, nothing is written: the build is compared with the committed
// file, and a difference fails (CI's kernels-fresh job; the toolchain is
// kernels/rust-toolchain.toml's, so a fresh build is byte for byte the same).
const check = process.argv.includes("--check");
const main = build("kernels", "sagebrush_kernels", "+simd128");
const relaxed = build("kernels/relaxed", "sagebrush_kernels_relaxed", "+simd128,+relaxed-simd");
// (a module that names this machine's home or Cargo home would differ on every
// other machine: refused, whether checking or writing)
for (const [name, wasm] of [["kernels", main], ["relaxed", relaxed]]) {
  for (const dir of [process.env.CARGO_HOME, process.env.HOME]) {
    if (dir && dir.length > 1 && wasm.includes(Buffer.from(dir))) {
      console.error(`build-kernels: the ${name} module names a local directory (${dir}); it would not build the same elsewhere`);
      process.exit(1);
    }
  }
}
const literal = (wasm) => wasm.toString("base64").match(/.{1,100}/g).map((l) => `  "${l}"`).join(" +\n");
const out = join(root, "src/runtime/kernels_wasm.ts");
const text =
  `// Generated by scripts/build-kernels.mjs from kernels/; do not edit.\n` +
  `export const KERNELS_WASM =\n${literal(main)};\n` +
  `export const KERNELS_RELAXED_WASM =\n${literal(relaxed)};\n`;
console.log(`kernels: ${main.length} bytes; relaxed: ${relaxed.length} bytes`);
if (check) {
  if (readFileSync(out, "utf8") !== text) {
    console.error("build-kernels --check: src/runtime/kernels_wasm.ts differs from a fresh build of kernels/; run node scripts/build-kernels.mjs and commit the result");
    process.exit(1);
  }
  console.log("build-kernels --check: src/runtime/kernels_wasm.ts is a fresh build");
} else {
  writeFileSync(out, text);
}
