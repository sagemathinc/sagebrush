#!/usr/bin/env node
// Curated PyPI packages as Sagebrush packages (packages/pypi-<name>/): the
// Python files of one pinned pure-Python wheel, unchanged and committed, so
// a build loads only bytes a reviewer has seen, and offline.  The wheel's
// URL and SHA-256 are recorded in the package's sagebrush.json ("source"),
// and this script re-derives the committed tree from that wheel: --check
// fails if anything differs (CI).
//
//   node scripts/pypi-import.mjs PROJECT VERSION [SPDX]   import (or re-import) one, from PyPI
//   (SPDX: its license, when PyPI's metadata does not say it exactly; the
//   license file is read before it is given)
//   node scripts/pypi-import.mjs --check           re-derive every packages/pypi-*/ and compare
//   (wheels are cached by their SHA-256 in $SAGEBRUSH_WHEEL_CACHE, else ~/.cache/sagebrush/wheels)
//
// A wheel is accepted only if it is pure Python (Root-Is-Purelib, every tag
// *-none-any), every file has the SHA-256 its RECORD gives, and its
// importable files are Python sources: a top-level package or module of
// top_level.txt (else of the wheel's own layout).  Type stubs (.pyi) and
// py.typed markers are left out and listed; any other file in a package is
// refused, as a C extension or data file would be.  Its license files
// (*.dist-info/LICENSE*, licenses/*) become the package's LICENSE files and
// its section of NOTICE.md (between the pypi-packages markers), which
// scripts/third-party-notices.mjs puts in each package that carries the
// library.  Then run node scripts/packages.mjs (the registry).
//
// A wheel is untrusted input until its files are checked: every size and
// count below is a fixed ceiling, checked before the work it bounds (the
// download while it streams, the archive's directory before anything is
// inflated), and every name must be a canonical relative path, every file
// written or read proved to stay under its package's directory.
import { createHash } from "node:crypto";
import { existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { crc32, inflateRawSync } from "node:zlib";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sha256 = (b) => createHash("sha256").update(b).digest("hex");
const cacheDir = process.env.SAGEBRUSH_WHEEL_CACHE || join(homedir(), ".cache", "sagebrush", "wheels");
const NOTICE_BEGIN = "<!-- pypi-packages: generated by scripts/pypi-import.mjs; do not edit -->";
const NOTICE_END = "<!-- /pypi-packages -->";
// (the licenses a curated package may have: permissive, no copyleft)
const LICENSES = new Set(["MIT", "BSD-2-Clause", "BSD-3-Clause", "Apache-2.0", "ISC", "PSF-2.0"]);
// (the ceilings: a wheel, as downloaded or cached; its entries; one entry
// and all of them, uncompressed; an entry's compression ratio, past
// ratioFrom bytes; PyPI's JSON for one release. A pure-Python wheel is far
// below each: sortedcontainers' is 29 KB, 11 entries, 230 KB inflated.)
export const LIMITS = Object.freeze({
  wheelBytes: 32 << 20,
  entries: 4096,
  entryBytes: 16 << 20,
  totalBytes: 64 << 20,
  ratio: 100,
  ratioFrom: 1 << 20,
  jsonBytes: 8 << 20,
});
const FETCH_TIMEOUT_MS = 120_000;

/** A zip entry's name, if it is a canonical relative POSIX path (a
 * directory's with its one trailing "/"): no empty, "." or ".." component,
 * no backslash, NUL or other control character, not absolute, no drive. */
export function archivePath(name) {
  const body = name.endsWith("/") ? name.slice(0, -1) : name;
  const why =
    !body ? "is empty" :
    /[\x00-\x1f\x7f]/.test(name) ? "has a control character (NUL included)" :
    name.includes("\\") ? "has a backslash" :
    name.startsWith("/") ? "is absolute" :
    /^[A-Za-z]:/.test(name) ? "names a drive" :
    body.split("/").some((c) => c === "" || c === "." || c === "..") ? "has an empty, \".\" or \"..\" component" :
    null;
  if (why !== null) throw new Error(`zip entry ${JSON.stringify(name)} ${why}`);
  return name;
}

/** rel under base, resolved, proved not to leave it (and base itself must
 * not be a symbolic link, nor anything on the way that exists). */
export function within(base, rel) {
  const b = resolve(base), p = resolve(b, rel);
  if (p === b || !p.startsWith(b + sep)) throw new Error(`${rel}: outside ${base}`);
  for (let q = p; q !== dirname(b); q = dirname(q)) {
    let st = null;
    try { st = lstatSync(q); } catch { /* (not there yet: made below) */ }
    if (st?.isSymbolicLink()) throw new Error(`${relative(root, q) || q}: a symbolic link`);
  }
  return p;
}

/** The files of a zip archive: name -> bytes (each CRC-checked). Every
 * record is bounds-checked, and every size and count is checked against
 * limits before anything is inflated; ZIP64, encrypted and multi-disk
 * archives are refused. */
export function unzip(buf, limits = LIMITS) {
  const bad = (why) => { throw new Error(`bad zip archive: ${why}`); };
  if (buf.length > limits.wheelBytes) bad(`${buf.length} bytes, past the ${limits.wheelBytes} allowed`);
  if (buf.length < 22) bad("too short");
  let eocd = -1;
  for (let i = buf.length - 22; i >= Math.max(0, buf.length - 65557); i--) if (buf.readUInt32LE(i) === 0x06054b50) { eocd = i; break; }
  if (eocd < 0) bad("no end of central directory");
  const disk = buf.readUInt16LE(eocd + 4), cdDisk = buf.readUInt16LE(eocd + 6), here = buf.readUInt16LE(eocd + 8), count = buf.readUInt16LE(eocd + 10);
  const cdSize = buf.readUInt32LE(eocd + 12), cdOffset = buf.readUInt32LE(eocd + 16);
  if (count === 0xffff || cdSize === 0xffffffff || cdOffset === 0xffffffff) bad("ZIP64");
  if (disk !== 0 || cdDisk !== 0 || here !== count) bad("several disks");
  if (count > limits.entries) bad(`${count} entries, past the ${limits.entries} allowed`);
  const cdEnd = cdOffset + cdSize;
  if (cdEnd > eocd) bad("the central directory is outside the archive");
  // (the directory first: every entry's record, name and sizes, before any inflating)
  const entries = [];
  let p = cdOffset, total = 0;
  for (let k = 0; k < count; k++) {
    if (p + 46 > cdEnd || buf.readUInt32LE(p) !== 0x02014b50) bad(`central directory entry ${k} is truncated or missing`);
    const flags = buf.readUInt16LE(p + 8), method = buf.readUInt16LE(p + 10), crc = buf.readUInt32LE(p + 16), csize = buf.readUInt32LE(p + 20), usize = buf.readUInt32LE(p + 24);
    const nlen = buf.readUInt16LE(p + 28), xlen = buf.readUInt16LE(p + 30), clen = buf.readUInt16LE(p + 32), local = buf.readUInt32LE(p + 42);
    if (p + 46 + nlen + xlen + clen > cdEnd) bad(`central directory entry ${k} is truncated`);
    let name;
    try { name = new TextDecoder("utf-8", { fatal: true }).decode(buf.subarray(p + 46, p + 46 + nlen)); } catch { bad(`entry ${k}'s name is not UTF-8`); }
    archivePath(name);
    p += 46 + nlen + xlen + clen;
    if (flags & 1) bad(`${name}: encrypted`);
    if (csize === 0xffffffff || usize === 0xffffffff || local === 0xffffffff) bad(`${name}: ZIP64`);
    if (method !== 0 && method !== 8) bad(`${name}: compression method ${method}`);
    if (method === 0 && csize !== usize) bad(`${name}: stored, but ${csize} bytes for ${usize}`);
    if (usize > limits.entryBytes) bad(`${name}: ${usize} bytes uncompressed, past the ${limits.entryBytes} allowed`);
    if (usize > limits.ratioFrom && usize > csize * limits.ratio) bad(`${name}: compressed ${Math.round(usize / Math.max(csize, 1))} to 1, past the ${limits.ratio} allowed`);
    total += usize;
    if (total > limits.totalBytes) bad(`past the ${limits.totalBytes} bytes allowed uncompressed in all`);
    if (local + 30 > cdOffset || buf.readUInt32LE(local) !== 0x04034b50) bad(`${name}: its local header is truncated or missing`);
    const lnlen = buf.readUInt16LE(local + 26), lxlen = buf.readUInt16LE(local + 28);
    if (!buf.subarray(local + 30, local + 30 + lnlen).equals(buf.subarray(p - nlen - xlen - clen, p - xlen - clen))) bad(`${name}: its local header names another file`);
    const start = local + 30 + lnlen + lxlen;
    if (start + csize > cdOffset) bad(`${name}: its data is outside the archive`);
    entries.push({ name, method, crc, usize, start, csize });
  }
  if (p !== cdEnd) bad("the central directory's size is not its entries'");
  const out = new Map();
  for (const { name, method, crc, usize, start, csize } of entries) {
    if (name.endsWith("/")) continue;
    if (out.has(name)) bad(`${name}: twice in the archive`);
    const raw = buf.subarray(start, start + csize);
    let data;
    // (inflating stops at the declared size: a bomb's output is never allocated)
    try { data = method === 0 ? Buffer.from(raw) : inflateRawSync(raw, { maxOutputLength: Math.max(usize, 1) }); } catch (e) { bad(`${name}: ${e.code === "ERR_BUFFER_TOO_LARGE" ? "inflates past its declared size" : "does not inflate"}`); }
    if (data.length !== usize || crc32(data) !== crc) bad(`${name}: corrupt (size or CRC)`);
    out.set(name, data);
  }
  return out;
}

/** A response's body, refused once past max bytes, as it streams (and
 * before, if Content-Length says so). */
export async function boundedBody(r, max, what) {
  const declared = Number(r.headers.get("content-length"));
  if (declared > max) {
    await r.body?.cancel?.().catch(() => {});
    throw new Error(`${what}: ${declared} bytes, past the ${max} allowed`);
  }
  const chunks = [];
  let n = 0;
  for await (const c of r.body ?? []) {
    n += c.length;
    if (n > max) {
      await r.body.cancel?.().catch(() => {});
      throw new Error(`${what}: past the ${max} bytes allowed`);
    }
    chunks.push(c);
  }
  return Buffer.concat(chunks);
}
const fetchBounded = async (url, max) => {
  const r = await fetch(url, { signal: AbortSignal.timeout(FETCH_TIMEOUT_MS), redirect: "follow" });
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return boundedBody(r, max, url);
};

// (a name as PyPI normalizes it, PEP 503)
const normalize = (n) => n.toLowerCase().replace(/[-_.]+/g, "-");
const IDENT = /^[A-Za-z_][A-Za-z0-9_]*$/;

/** What a pinned wheel becomes: {files: path -> bytes (the package's
 * directory), manifest (sagebrush.json), notice (its NOTICE.md section)}. */
export function derive(source, wheel) {
  if (sha256(wheel) !== source.sha256) throw new Error(`${source.filename}: its SHA-256 is ${sha256(wheel)}, not the pinned ${source.sha256}`);
  const dir = "pypi-" + normalize(source.project);
  if (!/^pypi-[a-z0-9]+(-[a-z0-9]+)*$/.test(dir)) throw new Error(`${source.project}: not a project name this can make a directory of`);
  const z = unzip(wheel);
  const names = [...z.keys()];
  const distInfo = [...new Set(names.filter((n) => /^[^/]+\.dist-info\//.test(n)).map((n) => n.split("/")[0]))];
  if (distInfo.length !== 1) throw new Error(`${source.filename}: ${distInfo.length} .dist-info directories`);
  const di = distInfo[0];
  const text = (n) => (z.has(n) ? z.get(n).toString("utf8") : null);
  // (pure Python only)
  const wheelMeta = text(`${di}/WHEEL`) ?? "";
  if (!/^Root-Is-Purelib:\s*true\s*$/m.test(wheelMeta)) throw new Error(`${source.filename}: not a pure-Python wheel (Root-Is-Purelib)`);
  const tags = [...wheelMeta.matchAll(/^Tag:\s*(\S+)\s*$/gm)].map((m) => m[1]);
  if (!tags.length || !tags.every((t) => /-none-any$/.test(t))) throw new Error(`${source.filename}: tags ${tags.join(", ")} (only *-none-any)`);
  // (every file as RECORD says)
  const record = new Map();
  for (const line of (text(`${di}/RECORD`) ?? "").split(/\r?\n/)) {
    if (!line.trim()) continue;
    const [path, hash] = line.split(",");
    record.set(path, hash);
  }
  for (const n of names) {
    if (n === `${di}/RECORD`) continue;
    const h = record.get(n);
    if (!h || !h.startsWith("sha256=")) throw new Error(`${source.filename}: ${n} has no SHA-256 in RECORD`);
    if (createHash("sha256").update(z.get(n)).digest("base64url") !== h.slice(7)) throw new Error(`${source.filename}: ${n} is not the file RECORD gives`);
  }
  // (the importable top-level names)
  const metadata = text(`${di}/METADATA`) ?? "";
  const field = (k) => metadata.match(new RegExp(`^${k}:\\s*(.+)$`, "mi"))?.[1].trim();
  if (normalize(field("Name") ?? "") !== normalize(source.project) || field("Version") !== source.version) throw new Error(`${source.filename}: METADATA is ${field("Name")} ${field("Version")}, not ${source.project} ${source.version}`);
  const others = names.filter((n) => !n.startsWith(di + "/"));
  if (others.some((n) => /^[^/]+\.data\//.test(n))) throw new Error(`${source.filename}: has a .data directory (scripts or data outside the package)`);
  const tops = (text(`${di}/top_level.txt`) ?? "").split(/\r?\n/).map((s) => s.trim()).filter(Boolean);
  const top = tops.length ? tops : [...new Set(others.map((n) => n.split("/")[0].replace(/\.py$/, "")))];
  for (const t of top) if (!IDENT.test(t)) throw new Error(`${source.filename}: top-level name ${JSON.stringify(t)}`);
  const files = new Map(), skipped = [];
  for (const n of others.sort()) {
    const t = n.split("/")[0].replace(/\.py$/, "");
    if (!top.includes(t)) throw new Error(`${source.filename}: ${n} is outside its top-level names (${top.join(", ")})`);
    if (/\.pyi$|(^|\/)py\.typed$/.test(n)) { skipped.push(n); continue; }
    if (!n.endsWith(".py")) throw new Error(`${source.filename}: ${n} is not Python source (only .py files are supported)`);
    files.set("py/" + n, z.get(n));
  }
  for (const t of top) if (!files.has(`py/${t}.py`) && !files.has(`py/${t}/__init__.py`)) throw new Error(`${source.filename}: no file for ${t}`);
  // (its license files, and its license)
  const licenseFiles = names.filter((n) => n.startsWith(di + "/") && (/\/LICEN[CS]E[^/]*$|\/COPYING[^/]*$/.test(n) || n.startsWith(di + "/licenses/"))).sort();
  if (!licenseFiles.length) throw new Error(`${source.filename}: no license file`);
  if (!LICENSES.has(source.license)) throw new Error(`${source.filename}: license ${source.license} is not on the list (${[...LICENSES].join(", ")})`);
  licenseFiles.forEach((n, i) => files.set(licenseFiles.length === 1 ? "LICENSE" : `LICENSE-${i + 1}`, z.get(n)));
  for (const f of files.keys()) archivePath(f);
  if (!/^\d+\.\d+\.\d+$/.test(source.version)) throw new Error(`${source.project} ${source.version}: a version MAJOR.MINOR.PATCH is needed`);
  const manifest = {
    name: `@sagebrush/${dir}`,
    version: source.version,
    sagebrush: ">=0.5 <0.6",
    modes: ["python"],
    python: { root: "py", modules: [...top].sort() },
    files: Object.fromEntries([...files].filter(([p]) => p.startsWith("py/")).map(([p, b]) => [p, sha256(b)])),
    requires: [],
    catalog: null,
    source: { pypi: { project: source.project, version: source.version, filename: source.filename, url: source.url, sha256: source.sha256, license: source.license, ...(skipped.length ? { skipped } : {}) } },
  };
  const licText = licenseFiles.map((n) => z.get(n).toString("utf8").replace(/\r\n/g, "\n").trimEnd()).join("\n\n");
  const notice = `### ${source.project} ${source.version} (${source.license}), from PyPI\n\n` +
    `\`packages/${dir}/py/\` is the Python source of ${source.project} ${source.version}'s wheel, unchanged:\n` +
    `${source.url}\n(SHA-256 ${source.sha256}). Its license:\n\n` + licText.split("\n").map((l) => (l ? "    " + l : "")).join("\n") +
    // (a license whose text the wheel only refers to: the text, from the repository)
    (source.license === "Apache-2.0" ? "\n\nThe Apache License 2.0's full text is LICENSE-APACHE, in the repository and in each package\nthat carries this code." : "");
  return { dir, files, manifest, notice };
}

async function wheelBytes(source) {
  if (!/^[0-9a-f]{64}$/.test(source.sha256 ?? "")) throw new Error(`${source.filename}: SHA-256 ${JSON.stringify(source.sha256)}`);
  const cached = join(cacheDir, source.sha256 + ".whl");
  if (existsSync(cached)) {
    const st = lstatSync(cached);
    if (!st.isFile() || st.size > LIMITS.wheelBytes) throw new Error(`${cached}: not a file of at most ${LIMITS.wheelBytes} bytes`);
    return readFileSync(cached);
  }
  if (!source.url?.startsWith("https://files.pythonhosted.org/")) throw new Error(`${source.url}: not on files.pythonhosted.org`);
  const b = await fetchBounded(source.url, LIMITS.wheelBytes);
  if (sha256(b) !== source.sha256) throw new Error(`${source.url}: SHA-256 ${sha256(b)}, not the pinned ${source.sha256}`);
  mkdirSync(cacheDir, { recursive: true });
  writeFileSync(cached, b);
  return b;
}

const manifestText = (m) => JSON.stringify(m, null, 2) + "\n";
// (NOTICE.md with the generated sections, from every packages/pypi-*/)
function noticeWith(sections) {
  const text = readFileSync(join(root, "NOTICE.md"), "utf8");
  const block = `${NOTICE_BEGIN}\n\n${sections.join("\n\n")}\n\n${NOTICE_END}`;
  const i = text.indexOf(NOTICE_BEGIN), j = text.indexOf(NOTICE_END);
  if (i >= 0 && j > i) return text.slice(0, i) + block + text.slice(j + NOTICE_END.length);
  // (no curated package yet: no section)
  if (!sections.length) return text;
  // (the first time: a section of its own, before "## Data")
  const k = text.indexOf("\n## Data");
  if (k < 0) throw new Error("NOTICE.md has no ## Data section");
  return text.slice(0, k) + `\n## Python packages from PyPI (unchanged, pinned)\n\n${block}\n` + text.slice(k);
}
const pypiDirs = () => readdirSync(join(root, "packages")).filter((d) => d.startsWith("pypi-") && existsSync(join(root, "packages", d, "sagebrush.json"))).sort();
const sourceOf = (d) => JSON.parse(readFileSync(within(join(root, "packages"), join(d, "sagebrush.json")), "utf8")).source?.pypi;
// (a package directory's files, refusing symbolic links and anything not a
// file or directory, as scripts/packages.mjs does)
function walk(dir, base = dir, out = []) {
  for (const f of readdirSync(dir).sort()) {
    const p = join(dir, f), st = lstatSync(p);
    if (st.isSymbolicLink()) throw new Error(`${relative(root, p)}: a symbolic link`);
    if (st.isDirectory()) walk(p, base, out);
    else if (st.isFile()) out.push(relative(base, p).split(sep).join("/"));
    else throw new Error(`${relative(root, p)}: not a file`);
  }
  return out;
}

/** What --check finds wrong with packages/<d> (under packagesDir), given
 * what its wheel derives to: every path proved under the directory first. */
export function compareTree(packagesDir, d, files, manifest) {
  const bad = [];
  const at = within(packagesDir, d);
  const want = new Map([...files, ["sagebrush.json", Buffer.from(manifestText(manifest))]]);
  // (README.md and known.json are the package's own, not the wheel's)
  const have = walk(at).filter((f) => !/(^|\/)__pycache__\//.test(f) && f !== "README.md" && f !== "known.json");
  for (const f of have) if (!want.has(f)) bad.push(`packages/${d}/${f}: not in the wheel`);
  for (const [f, b] of want) {
    const p = within(at, archivePath(f));
    if (!existsSync(p)) bad.push(`packages/${d}/${f}: missing`);
    else if (!readFileSync(p).equals(b)) bad.push(`packages/${d}/${f}: not as the pinned wheel has it`);
  }
  return bad;
}

/** Writes packages/<dir> (under packagesDir) as its wheel derives to,
 * keeping known.json and README.md: every path proved under it first. */
export function writeTree(packagesDir, dir, files, manifest) {
  const at = within(packagesDir, dir);
  for (const f of files.keys()) within(at, archivePath(f));
  const keep = ["known.json", "README.md"].filter((f) => existsSync(within(at, f))).map((f) => [f, readFileSync(within(at, f))]);
  rmSync(at, { recursive: true, force: true });
  mkdirSync(at, { recursive: true });
  for (const [f, b] of keep) writeFileSync(within(at, f), b);
  for (const [f, b] of files) {
    const p = within(at, f);
    mkdirSync(dirname(p), { recursive: true });
    within(at, f);
    writeFileSync(p, b);
  }
  writeFileSync(within(at, "sagebrush.json"), manifestText(manifest));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  try {
    if (args[0] === "--check") {
      const bad = [], sections = [];
      for (const d of pypiDirs()) {
        const src = sourceOf(d);
        if (!src) { bad.push(`packages/${d}: no source.pypi in sagebrush.json`); continue; }
        const { dir, files, manifest, notice } = derive(src, await wheelBytes(src));
        sections.push(notice);
        if (dir !== d) bad.push(`packages/${d}: is ${src.project}'s, whose directory is packages/${dir}`);
        bad.push(...compareTree(join(root, "packages"), d, files, manifest));
      }
      // (the agents' page names each one with its version)
      const llms = readFileSync(join(root, "web", "llms.txt"), "utf8");
      for (const d of pypiDirs()) { const src = sourceOf(d); if (src && !llms.includes("`" + src.project + "` " + src.version)) bad.push(`web/llms.txt does not name \`${src.project}\` ${src.version} among the curated PyPI packages`); }
      if (readFileSync(join(root, "NOTICE.md"), "utf8") !== noticeWith(sections)) bad.push("NOTICE.md: its PyPI packages' section is out of date (node scripts/pypi-import.mjs PROJECT VERSION)");
      if (bad.length) { console.error(bad.join("\n")); process.exit(1); }
      console.log(`${pypiDirs().length} PyPI packages, each as its pinned wheel has it`);
    } else {
      const [project, version, spdx] = args;
      if (!project || !version) throw new Error("usage: node scripts/pypi-import.mjs PROJECT VERSION | --check");
      const info = JSON.parse((await fetchBounded(`https://pypi.org/pypi/${encodeURIComponent(project)}/${encodeURIComponent(version)}/json`, LIMITS.jsonBytes)).toString("utf8"));
      const whl = (info.urls ?? []).filter((u) => u.packagetype === "bdist_wheel" && /-none-any\.whl$/.test(u.filename));
      if (whl.length !== 1) throw new Error(`${project} ${version}: ${whl.length} pure-Python wheels on PyPI`);
      const lic = info.info.license_expression || info.info.license || "";
      // (only unambiguous names; anything else needs SPDX, chosen by reading the license file)
      const license = spdx ?? { "Apache 2.0": "Apache-2.0", "Apache-2.0": "Apache-2.0", "Apache License 2.0": "Apache-2.0", MIT: "MIT", "MIT License": "MIT" }[lic.trim()] ?? lic.trim();
      const source = { project: info.info.name, version, filename: whl[0].filename, url: whl[0].url, sha256: whl[0].digests.sha256, license };
      const { dir, files, manifest } = derive(source, await wheelBytes(source));
      writeTree(join(root, "packages"), dir, files, manifest);
      const sections = [];
      for (const d of pypiDirs()) { const s = sourceOf(d); sections.push(derive(s, await wheelBytes(s)).notice); }
      writeFileSync(join(root, "NOTICE.md"), noticeWith(sections));
      console.log(`packages/${dir}: ${source.project} ${version} (${license}), ${files.size} files; now run node scripts/packages.mjs`);
    }
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
