#!/usr/bin/env python3
"""Generates lib/_rill/uchar.py, Rill's table of how R prints each character, from
rill-tests/print/uchar-sweep.txt: R 4.5.3's own answers, recorded black-box by
rill-tests/print/uchar-sweep.R (for every code point, nchar(type = "width") and
whether encodeString escapes it).  No Unicode database is consulted, so Rill
pads and escapes exactly as that R does, Unicode version included.

    python3 scripts/rill-uchar.py           write lib/_rill/uchar.py
    python3 scripts/rill-uchar.py --check   exit 1 if the file isn't what the sweep gives
"""
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SWEEP = os.path.join(ROOT, "rill-tests", "print", "uchar-sweep.txt")
OUT = os.path.join(ROOT, "lib", "_rill", "uchar.py")
# 64 digits for a base-32 varint (the upper 32 mark a continuation); no quote or backslash
ALPHABET = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ!#"

HEAD = '''"""How R 4.5.3 prints each character (generated by scripts/rill-uchar.py from
rill-tests/print/uchar-sweep.txt, R's own nchar(type = "width") and
encodeString answers for every code point; don't edit by hand).

klass(cp): 0, 1 or 2, the columns print() pads the character to; 3, printed
escaped (\\\\u%04x below U+10000, \\\\U{%06x} above).  Loaded only when a
string has a character past ASCII.
"""

_A = "@ALPHABET@"
_T = "%s"
''' 

TAIL = '''

def _decode():
    starts, classes = [], []
    n = shift = pos = 0
    for ch in _T:
        d = _A.index(ch)
        n |= (d & 31) << shift
        shift += 5
        if d < 32:
            pos += n >> 2
            starts.append(pos)
            classes.append(n & 3)
            n = shift = 0
    return starts, classes


_STARTS, _CLASSES = _decode()


def klass(cp):
    """0, 1 or 2 (print's width) or 3 (escaped), by bisection over the ranges."""
    lo, hi = 0, len(_STARTS) - 1
    if cp < _STARTS[0]:
        return 3
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if _STARTS[mid] <= cp:
            lo = mid
        else:
            hi = mid - 1
    return _CLASSES[lo]
'''


def ranges():
    rows = []
    for line in open(SWEEP):
        a, b, w, e = line.split()
        rows.append((int(a, 16), int(b, 16), int(w), int(e)))
    cls = []
    for a, b, w, e in rows:
        # (the backslash: encodeString doubles it; the printer escapes it itself, so it is width 1 here)
        c = 1 if a == b == 0x5C else (3 if e else w)
        if cls and cls[-1][1] + 1 != a:
            cls.append([cls[-1][1] + 1, a - 1, 3])          # (the surrogates: never in a string)
        if cls and cls[-1][2] == c and cls[-1][1] + 1 == a:
            cls[-1][1] = b
        else:
            cls.append([a, b, c])
    # (below U+0020: controls, escaped)
    return [(0, 3)] + [(a, c) for a, b, c in cls]


def varint(n):
    out = []
    while True:
        d = n & 31
        n >>= 5
        out.append(ALPHABET[d + (32 if n else 0)])
        if not n:
            return "".join(out)


def generate():
    prev, enc = 0, []
    for a, c in ranges():
        enc.append(varint(((a - prev) << 2) | c))
        prev = a
    body = "".join(enc)
    lines = [body[i:i + 100] for i in range(0, len(body), 100)]
    table = "(\n    \"" + "\"\n    \"".join(lines) + "\"\n)"
    return HEAD.replace('_T = "%s"', "_T = " + table).replace("@ALPHABET@", ALPHABET) + TAIL


if __name__ == "__main__":
    text = generate()
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == text
        print("lib/_rill/uchar.py is %s" % ("current" if ok else "STALE: run scripts/rill-uchar.py"))
        sys.exit(0 if ok else 1)
    open(OUT, "w").write(text)
    print("wrote", OUT, len(text), "bytes")
