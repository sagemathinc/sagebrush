#!/usr/bin/env node
// The pinned IANA zone data for the browser, which has no zone files of its
// own (tzdata/, read by lib/_pytime.py through web/lib-lazy.ts): the TZif
// files of one pinned wheel of PyPI's "tzdata" project (its packaging
// Apache-2.0; the zone data itself is in the public domain), unchanged and
// committed, so a build serves only bytes a reviewer has seen. The wheel's
// URL and SHA-256 are in tzdata/source.json, and this script re-derives
// tzdata/ from that wheel: --check fails if anything differs (CI).
//
//   node scripts/tzdata-import.mjs VERSION   import (or re-import) one, from PyPI
//   node scripts/tzdata-import.mjs --check   re-derive tzdata/ and compare
//   (wheels are cached by their SHA-256, as scripts/pypi-import.mjs caches them)
//
// The wheel is untrusted input until it is checked: scripts/pypi-import.mjs's
// unzip bounds every size and count before anything is inflated, and every
// name must be a canonical relative path; then every file must have the
// SHA-256 its RECORD gives, the zone list (tzdata/zones in the wheel) must
// name each zone once, each a canonical zone name (components of letters,
// digits, "+", "-" and "_"), each a TZif file of at most MAX_ZONE bytes.
import { createHash } from "node:crypto";
import { existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { LIMITS, boundedBody, unzip, within } from "./pypi-import.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = join(root, "tzdata");
const sha256 = (b) => createHash("sha256").update(b).digest("hex");
const cacheDir = process.env.SAGEBRUSH_WHEEL_CACHE || join(homedir(), ".cache", "sagebrush", "wheels");
const NOTICE_BEGIN = "<!-- tzdata: generated by scripts/tzdata-import.mjs; do not edit -->";
const NOTICE_END = "<!-- /tzdata -->";
// (a zone file is at most a few KB: the largest of 2026.5's is under 3 KB)
export const MAX_ZONE = 64 << 10;
export const MAX_ZONES = 2000;
const ZONE_NAME = /^[A-Za-z0-9_+-]+(\/[A-Za-z0-9_+-]+)*$/;
const FETCH_TIMEOUT_MS = 120_000;

const fetchBounded = async (url, max) => {
  const r = await fetch(url, { signal: AbortSignal.timeout(FETCH_TIMEOUT_MS), redirect: "follow" });
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return boundedBody(r, max, url);
};

async function wheelBytes(source) {
  if (!/^[0-9a-f]{64}$/.test(source.sha256 ?? "")) throw new Error(`${source.filename}: SHA-256 ${JSON.stringify(source.sha256)}`);
  const cached = join(cacheDir, source.sha256 + ".whl");
  if (existsSync(cached)) {
    const st = lstatSync(cached);
    if (!st.isFile() || st.size > LIMITS.wheelBytes) throw new Error(`${cached}: not a file of at most ${LIMITS.wheelBytes} bytes`);
    return readFileSync(cached);
  }
  if (!source.url?.startsWith("https://files.pythonhosted.org/")) throw new Error(`${source.url}: not on files.pythonhosted.org`);
  const b = await fetchBounded(source.url, LIMITS.wheelBytes);
  if (sha256(b) !== source.sha256) throw new Error(`${source.url}: SHA-256 ${sha256(b)}, not the pinned ${source.sha256}`);
  mkdirSync(cacheDir, { recursive: true });
  writeFileSync(cached, b);
  return b;
}

/** What a pinned wheel becomes: {files: path under tzdata/ -> bytes,
 * notice: its NOTICE.md section}. */
export function derive(source, wheel) {
  if (sha256(wheel) !== source.sha256) throw new Error(`${source.filename}: its SHA-256 is ${sha256(wheel)}, not the pinned ${source.sha256}`);
  if (!/^\d{4}\.\d+$/.test(source.version)) throw new Error(`tzdata ${source.version}: a version YEAR.N is needed`);
  const z = unzip(wheel);
  const distInfo = [...new Set([...z.keys()].filter((n) => /^[^/]+\.dist-info\//.test(n)).map((n) => n.split("/")[0]))];
  if (distInfo.length !== 1) throw new Error(`${source.filename}: ${distInfo.length} .dist-info directories`);
  const di = distInfo[0];
  const record = z.get(`${di}/RECORD`)?.toString("utf8");
  if (record === undefined) throw new Error(`${source.filename}: no RECORD`);
  const hashes = new Map();
  for (const line of record.split("\n")) {
    if (!line) continue;
    const [n, h] = line.split(",");
    hashes.set(n, h);
  }
  for (const n of z.keys()) {
    if (n === `${di}/RECORD`) continue;
    const h = hashes.get(n);
    if (!h || !h.startsWith("sha256=")) throw new Error(`${source.filename}: ${n} has no SHA-256 in RECORD`);
    if (createHash("sha256").update(z.get(n)).digest("base64url") !== h.slice(7)) throw new Error(`${source.filename}: ${n} is not the file RECORD gives`);
  }
  const meta = z.get(`${di}/METADATA`)?.toString("utf8") ?? "";
  const field = (f) => meta.match(new RegExp(`^${f}: (.*)$`, "m"))?.[1]?.trim();
  if (field("Name")?.toLowerCase() !== "tzdata" || field("Version") !== source.version) throw new Error(`${source.filename}: METADATA is ${field("Name")} ${field("Version")}, not tzdata ${source.version}`);
  const list = z.get("tzdata/zones")?.toString("utf8");
  if (list === undefined) throw new Error(`${source.filename}: no tzdata/zones`);
  const zones = list.split("\n").filter((l) => l !== "");
  if (zones.length > MAX_ZONES) throw new Error(`${source.filename}: ${zones.length} zones, past the ${MAX_ZONES} allowed`);
  const files = new Map();
  for (const name of zones) {
    if (!ZONE_NAME.test(name) || name.split("/").some((c) => c === "." || c === "..")) throw new Error(`${source.filename}: zone name ${JSON.stringify(name)}`);
    const path = `zoneinfo/${name}`;
    if (files.has(path)) throw new Error(`${source.filename}: ${name} twice in tzdata/zones`);
    const b = z.get(`tzdata/${path}`);
    if (b === undefined) throw new Error(`${source.filename}: no file for zone ${name}`);
    if (b.length > MAX_ZONE || b.subarray(0, 4).toString("latin1") !== "TZif") throw new Error(`${source.filename}: ${name} is not a TZif file of at most ${MAX_ZONE} bytes`);
    files.set(path, b);
  }
  const license = z.get(`${di}/licenses/LICENSE`) ?? z.get(`${di}/LICENSE`);
  if (license === undefined) throw new Error(`${source.filename}: no license file`);
  files.set("LICENSE", license);
  const sourceJson = { project: "tzdata", version: source.version, filename: source.filename, url: source.url, sha256: source.sha256, license: "Apache-2.0", zones: zones.length };
  files.set("source.json", Buffer.from(JSON.stringify(sourceJson, null, 2) + "\n"));
  const notice = `### tzdata ${source.version} (Apache-2.0), from PyPI\n\n` +
    "`tzdata/zoneinfo/` holds the zone files of tzdata " + source.version + "'s wheel, unchanged (the IANA time\n" +
    "zone database, compiled; the data itself is in the public domain), which a browser reads for\n" +
    "its local time:\n" + `${source.url}\n(SHA-256 ${source.sha256}). Its packaging's license is the Apache License 2.0\n` +
    "(tzdata/LICENSE, and LICENSE-APACHE in the repository and in each package that carries the files).";
  return { files, notice };
}

// (tzdata/'s files, refusing symbolic links and anything not a file or directory)
function walk(dir, base = dir, out = []) {
  for (const f of readdirSync(dir).sort()) {
    const p = join(dir, f), st = lstatSync(p);
    if (st.isSymbolicLink()) throw new Error(`${relative(root, p)}: a symbolic link`);
    if (st.isDirectory()) walk(p, base, out);
    else if (st.isFile()) out.push(relative(base, p).split(sep).join("/"));
    else throw new Error(`${relative(root, p)}: not a file`);
  }
  return out;
}

function noticeWith(section) {
  const text = readFileSync(join(root, "NOTICE.md"), "utf8");
  const block = `${NOTICE_BEGIN}\n\n${section}\n\n${NOTICE_END}`;
  const i = text.indexOf(NOTICE_BEGIN), j = text.indexOf(NOTICE_END);
  if (i >= 0 && j > i) return text.slice(0, i) + block + text.slice(j + NOTICE_END.length);
  const k = text.indexOf("\n## Data");
  if (k < 0) throw new Error("NOTICE.md has no ## Data section");
  return text.slice(0, k) + `\n## Time zone data\n\n${block}\n` + text.slice(k);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  try {
    if (args[0] === "--check") {
      const source = JSON.parse(readFileSync(join(dataDir, "source.json"), "utf8"));
      const { files, notice } = derive(source, await wheelBytes(source));
      const bad = [];
      const have = new Set(walk(dataDir));
      for (const [p, b] of files) {
        if (!have.has(p)) bad.push(`tzdata/${p}: missing`);
        else if (!readFileSync(within(dataDir, p)).equals(b)) bad.push(`tzdata/${p}: not the wheel's`);
        have.delete(p);
      }
      for (const p of have) bad.push(`tzdata/${p}: not in the wheel`);
      if (readFileSync(join(root, "NOTICE.md"), "utf8") !== noticeWith(notice)) bad.push("NOTICE.md: its tzdata section is out of date (node scripts/tzdata-import.mjs VERSION)");
      if (bad.length) {
        console.error(bad.slice(0, 20).join("\n"));
        process.exit(1);
      }
      console.log(`tzdata ${source.version}: ${files.size - 2} zones, as the pinned wheel has them`);
    } else {
      const [version] = args;
      if (!version) throw new Error("usage: node scripts/tzdata-import.mjs VERSION | --check");
      const info = JSON.parse((await fetchBounded(`https://pypi.org/pypi/tzdata/${encodeURIComponent(version)}/json`, LIMITS.jsonBytes)).toString("utf8"));
      const whl = (info.urls ?? []).filter((u) => u.packagetype === "bdist_wheel" && /-none-any\.whl$/.test(u.filename));
      if (whl.length !== 1) throw new Error(`tzdata ${version}: ${whl.length} wheels on PyPI`);
      const source = { version, filename: whl[0].filename, url: whl[0].url, sha256: whl[0].digests.sha256 };
      const { files, notice } = derive(source, await wheelBytes(source));
      rmSync(dataDir, { recursive: true, force: true });
      for (const [p, b] of files) {
        const out = within(dataDir, p);
        mkdirSync(dirname(out), { recursive: true });
        writeFileSync(out, b);
      }
      writeFileSync(join(root, "NOTICE.md"), noticeWith(notice));
      console.log(`tzdata ${version}: ${files.size - 2} zones written to tzdata/; now run node scripts/third-party-notices.mjs`);
    }
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
