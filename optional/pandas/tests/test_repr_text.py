# The text reprs of Series, DataFrame and Index at the default options
# (plan-pandas-m1-r1 §4), byte for byte.
import numpy as np
import pandas as pd
from _cases import case

def shown(x):
    return "\n" + repr(x)

case("s.long", lambda: shown(pd.Series(range(100))))
case("s.floats-name", lambda: shown(pd.Series([float(i) / 7 for i in range(70)], name="x")))
case("s.small", lambda: shown(pd.Series([1e-8, 1.0, 2.5])))
case("s.large", lambda: shown(pd.Series([1e7, 1.0, 2.5])))
case("s.too-long", lambda: shown(pd.Series([123456789.123, 1.0])))
case("s.special", lambda: shown(pd.Series([np.inf, -np.inf, np.nan, 0.0, -0.0])))
case("s.neg-zero", lambda: shown(pd.Series([-0.0, 1.5])))
case("s.whole-floats", lambda: shown(pd.Series([1.0, 2.0, 3.0])))
case("s.strings", lambda: shown(pd.Series(["a", "bb\tc", "x" * 60, None])))
case("s.objects", lambda: shown(pd.Series([1, "a", None, 2.5, True, [1, 2], {"k": 1}, (1,)])))
case("s.named-index", lambda: shown(pd.Series([10, 20], index=pd.Index(["r", "s"], name="idx"), name=3.5)))
case("s.bools", lambda: shown(pd.Series([True, False, True])))
case("s.empty-str", lambda: shown(pd.Series([], dtype="str")))
case("s.empty-named", lambda: shown(pd.Series([], dtype=float, name="e")))
case("s.str-of", lambda: str(pd.Series([1, 2])))
case("s.one-of-61", lambda: shown(pd.Series(range(61))))
case("s.exactly-60", lambda: shown(pd.Series(range(60)).tail(3)))
case("s.float-index", lambda: shown(pd.Series([1, 2], index=[0.5, 1.25])))
case("s.unicode", lambda: shown(pd.Series(["é", "日本"], index=["ü", "x"])))
df = pd.DataFrame({"a": range(100), "b": [i * 0.5 for i in range(100)], "c": ["s%d" % i for i in range(100)]})
case("df.long", lambda: shown(df))
case("df.head", lambda: shown(df.head()))
wide = pd.DataFrame({"column_%02d" % i: [i, i * 2.5, i * 100] for i in range(30)})
case("df.wide", lambda: shown(wide))
case("df.wide-ints", lambda: shown(pd.DataFrame(np.arange(300).reshape(10, 30))))
case("df.wide-long", lambda: shown(pd.DataFrame(np.arange(3000).reshape(100, 30))))
case("df.named-index", lambda: shown(pd.DataFrame({"x": [1.5, np.nan], "y": [None, "q"]}, index=pd.Index(["a", "b"], name="key"))))
case("df.empty", lambda: shown(pd.DataFrame()))
case("df.empty-columns", lambda: shown(pd.DataFrame(columns=["a", "b"])))
case("df.empty-rows", lambda: shown(pd.DataFrame({"a": []})))
case("df.long-string", lambda: shown(pd.DataFrame({"long": ["y" * 70, "z"]})))
case("df.mixed-labels", lambda: shown(pd.DataFrame({1: [1], 2.5: [2], "s": [3]})))
case("df.big-floats", lambda: shown(pd.DataFrame({"v": np.arange(1000000, 1000070, dtype="float64") * 1.5})))
case("df.str", lambda: str(pd.DataFrame({"a": [1]})))
case("df.to_string", lambda: pd.DataFrame({"a": [1, 2]}).to_string())
case("df.bool-object", lambda: shown(pd.DataFrame({"b": [True, None], "i": [1, 2]})))
case("df.dtypes", lambda: shown(df.dtypes))
case("index.long", lambda: shown(pd.Index(list(range(200)))))
case("index.strs", lambda: shown(pd.Index(["x%d" % i for i in range(30)])))
case("index.named", lambda: shown(pd.Index(["a", "b"], name="nm")))
case("index.range", lambda: shown(pd.RangeIndex(0, 10, 2, name="r")))
case("index.nan", lambda: shown(pd.Index([1.5, np.nan])))
case("index.mixed", lambda: shown(pd.Index([1, "a"])))
case("index.empty", lambda: shown(pd.Index([])))
case("index.columns", lambda: shown(wide.columns))
