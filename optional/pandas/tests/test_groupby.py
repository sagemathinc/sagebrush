case("float-min-missing", lambda: pd.Series([np.nan, np.nan, 1.0]).groupby(k3).min())
case("mean-all-missing-group", lambda: pd.DataFrame({"k": ["a", "b"], "x": [np.nan, 1.0]}).groupby("k")["x"].mean())
