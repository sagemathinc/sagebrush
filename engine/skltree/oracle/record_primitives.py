"""Record engine/skltree's primitive oracle rows from real scikit-learn (oracle/primitives.rows, a text file
src/oracle_tests.rs reads): its XorShift (`_our_rand_r_py`), its introsort (`_py_simultaneous_sort`, 3-way and 2-way,
float32 and float64) and `_py_swap_array_slices`, on inputs both sides generate the same way (exact integer-derived
values: no rounding can differ).  Each sort row is a hash of the sorted values' and the carried indices' bytes.

Run with the pinned oracle, read-only, and commit the rows; re-recording is a reviewed change:

    $VENV/bin/python -I engine/skltree/oracle/record_primitives.py > engine/skltree/oracle/primitives.rows

where $VENV is a venv with scikit-learn 1.9.1 (the rows' first line names the versions they were recorded with).
"""
import platform
import sys

import numpy as np
import sklearn
from sklearn.tree._partitioner import _py_swap_array_slices
from sklearn.utils._random import _our_rand_r_py
from sklearn.utils._sorting import _py_simultaneous_sort

M64 = (1 << 64) - 1


class Lcg:
    """The inputs' generator (src/oracle_tests.rs has the same): a 64-bit LCG, 31 bits out."""

    def __init__(self, seed):
        self.s = seed & M64

    def next(self):
        self.s = (self.s * 6364136223846793005 + 1442695040888963407) & M64
        return self.s >> 33


def fnv(data):
    h = 0xCBF29CE484222325
    for b in data:
        h = ((h ^ b) * 0x100000001B3) & M64
    return h


# Each kind: the i-th value of n, an integer or an exact multiple of a power of two (so float32 holds it exactly).
def values(kind, n, seed):
    g = Lcg(seed)
    k = n // 2
    if kind == "uniform":
        return [(g.next() % (1 << 20)) * 2.0**-10 for _ in range(n)]
    if kind == "signed":
        return [((g.next() % (1 << 20)) - (1 << 19)) * 2.0**-10 for _ in range(n)]
    if kind == "dup7":
        return [float(g.next() % 7) for _ in range(n)]
    if kind == "dup2":
        return [float(g.next() % 2) for _ in range(n)]
    if kind == "few100":
        return [float(g.next() % 100) for _ in range(n)]
    if kind == "ulps":
        return [1.0 + (g.next() % 3) * 2.0**-23 for _ in range(n)]
    if kind == "equal":
        return [5.0] * n
    if kind == "sorted":
        return [float(i) for i in range(n)]
    if kind == "reversed":
        return [float(n - i) for i in range(n)]
    if kind == "organ":
        return [float(min(i, n - 1 - i)) for i in range(n)]
    if kind == "saw17":
        return [float(i % 17) for i in range(n)]
    if kind == "pipe2":
        return [float(2 * i if i < k else 2 * (n - i) - 1) for i in range(n)]
    if kind == "interleave":
        return [float(i if i % 2 == 0 else n + i) for i in range(n)]
    if kind == "mo3killer":
        return [float((i + 1 if i % 2 == 0 else k + i) if i < k else 2 * (i - k + 1)) for i in range(n)]
    raise ValueError(kind)


KINDS = ["uniform", "signed", "dup7", "dup2", "few100", "ulps", "equal", "sorted", "reversed", "organ", "saw17", "pipe2", "interleave", "mo3killer"]
SIZES = [0, 1, 2, 3, 15, 16, 17, 31, 64, 100, 1000, 4097, 50000]


def sort_row(kind, n, seed, f64, three):
    v = np.array(values(kind, n, seed), dtype=np.float64 if f64 else np.float32)
    ix = np.arange(n, dtype=np.intp)
    if n:
        _py_simultaneous_sort(v, ix, n, use_three_way_partition=three)
    return fnv(v.astype("<f8" if f64 else "<f4").tobytes() + ix.astype("<u8").tobytes())


def xorshift(s):
    """The step whose outputs scikit-learn's rows check (its state, for the chains): independent of the Rust port."""
    if s == 0:
        s = 1
    s ^= (s << 13) & 0xFFFFFFFF
    s ^= s >> 17
    s ^= (s << 5) & 0xFFFFFFFF
    return s


def main():
    out = sys.stdout
    # (one row a line, space-separated; '#' lines are comments; the first non-comment line names the oracle)
    out.write(f"# Generated by engine/skltree/oracle/record_primitives.py; do not edit.  Re-recording is a reviewed change.\n")
    out.write(f"# sort KIND N SEED F64 THREE FNV: FNV-1a of the sorted values' then the indices' little-endian bytes\n")
    out.write(f"# rand SEED DRAW; chain FIRST DRAW...: scikit-learn's draw at each state of the chain; swap LEN START END N F32 FNV\n")
    out.write(f"oracle scikit-learn {sklearn.__version__}, numpy {np.__version__}, CPython {platform.python_version()} {platform.machine()}\n")
    for kind in KINDS:
        seeds = [1, 2] if kind in ("uniform", "signed", "dup7", "dup2", "few100", "ulps") else [1]
        for n in SIZES:
            for seed in seeds:
                for f64 in (0, 1):
                    for three in (1, 0):
                        out.write(f"sort {kind} {n} {seed} {f64} {three} {sort_row(kind, n, seed, bool(f64), bool(three)):016x}\n")
    g = Lcg(2026)
    seeds = [0, 1, 2, 3, 42, 12345, 2**31 - 1, 2**31, 2**31 + 1, 2**32 - 1] + [g.next() * 2 + (g.next() & 1) for _ in range(2000)]
    for s in seeds:
        s &= 0xFFFFFFFF
        out.write(f"rand {s} {_our_rand_r_py(s)}\n")
    for s0 in [0, 1, 42, 2**31 - 1, 2**32 - 1, 3141592653]:
        s, draws = s0, []
        for _ in range(64):
            draws.append(_our_rand_r_py(s))
            s = xorshift(s)
        out.write(f"chain {s0} {' '.join(map(str, draws))}\n")
    for (ln, st, en, n) in [(10, 0, 10, 3), (10, 2, 9, 0), (10, 2, 9, 7), (10, 4, 4, 0), (10, 0, 10, 10), (1, 0, 1, 1), (9000, 1, 8999, 4100), (9000, 0, 9000, 8999), (20000, 3, 19997, 1)]:
        for f32 in (0, 1):
            a = (np.arange(ln, dtype=np.float32) * np.float32(0.5)) if f32 else np.arange(ln, dtype=np.intp)
            _py_swap_array_slices(a, st, en, n)
            h = fnv(a.astype("<f4").tobytes() if f32 else a.astype("<u8").tobytes())
            out.write(f"swap {ln} {st} {en} {n} {f32} {h:016x}\n")


main()
