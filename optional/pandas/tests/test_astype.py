# astype on Series and DataFrame: between int64, float64, bool, str and object; to numpy's smaller integers (int8 to
# int32, uint8 to uint32); a dict of column -> dtype; and the errors (a missing value to an integer, a value that
# isn't a number, a column that isn't there).
import numpy as np
import pandas as pd
from _cases import case, dtypes

i = pd.Series([1, 2, 300], name="i")
f = pd.Series([1.9, -2.5, np.nan])
g = pd.Series([1.9, -2.5, 3.0])
b = pd.Series([True, False, True])
t = pd.Series(["1", "22", None])

case("int-float", lambda: i.astype("float64"))
case("int-str", lambda: i.astype(str))
case("int-object", lambda: i.astype(object))
case("int-bool", lambda: pd.Series([0, 1, 2]).astype(bool))
case("int-int64-copy", lambda: i.astype("int64"))
case("float-int-truncates", lambda: g.astype("int64"))
case("float-nan-int", lambda: f.astype(int))
case("float-str", lambda: f.astype("str"))
case("bool-int", lambda: b.astype(int))
case("bool-float", lambda: b.astype(float))
case("bool-str", lambda: b.astype(str))
case("str-int-missing", lambda: t.astype(int))
case("str-int", lambda: pd.Series(["1", "22", "-3"]).astype(int))
case("str-float", lambda: t.astype(float))
case("str-float-bad", lambda: pd.Series(["1.5", "x"]).astype(float))
case("str-object", lambda: t.astype(object))
case("object-str", lambda: pd.Series([1, "a", 2.5]).astype(str))

for d in ["int8", "int16", "int32", "uint8", "uint16", "uint32", np.uint8, np.int16]:
    case("int-to-%s" % np.dtype(d), lambda d=d: pd.Series([0, 7, 120]).astype(d))
    case("float-to-%s" % np.dtype(d), lambda d=d: pd.Series([0.0, 7.9, 120.5]).astype(d))
    case("bool-to-%s" % np.dtype(d), lambda d=d: b.astype(d))
case("uint8-wraps", lambda: pd.Series([255, 256, -1]).astype("uint8"))
case("int8-wraps", lambda: pd.Series([127, 128, -129]).astype("int8"))
case("uint8-back-to-int64", lambda: pd.Series([1, 2]).astype("uint8").astype("int64"))
case("uint8-dtype", lambda: str(pd.Series([1, 2]).astype(np.uint8).dtype))
case("uint8-sum", lambda: pd.Series([200, 100], dtype="int64").astype("uint8").sum())
case("uint8-max", lambda: pd.Series([200, 100]).astype("uint8").max())
case("uint8-mean", lambda: pd.Series([200, 100]).astype("uint8").mean())
case("int16-to_numpy", lambda: pd.Series([1, -2]).astype("int16").to_numpy().tolist())
case("uint8-nan", lambda: f.astype("uint8"))

df = pd.DataFrame({"sex": ["m", "f", "m"], "age": [22.0, 38.0, 26.5], "fare": [7, 71, 8], "alone": [True, False, True]})
case("frame.float", lambda: df[["age", "fare"]].astype(float))
case("frame.dict", lambda: dtypes(df.astype({"fare": "float64", "alone": "uint8"})))
case("frame.dict-values", lambda: df.astype({"fare": "float64", "alone": "uint8"}))
case("frame.dict-missing-col", lambda: df.astype({"height": "float64"}))
case("frame.all-str", lambda: dtypes(df.astype(str)))
case("frame.all-str-values", lambda: df.astype(str))
case("frame.str-to-float-fails", lambda: df.astype(float))
case("frame.original-kept", lambda: (df.astype({"fare": float}), dtypes(df))[1])
case("frame.uint8", lambda: dtypes(df[["fare", "alone"]].astype(np.uint8)))
case("frame.uint8-values", lambda: df[["fare", "alone"]].astype(np.uint8))
# (a negative float to an unsigned type: pandas' own ValueError, checked before the range; -0.0 is no negative)
case("negative-float64-to-uint8", lambda: pd.Series([-1.0]).astype("uint8"))
case("negative-float32-to-uint8", lambda: pd.Series([-1.0], dtype="float32").astype("uint8"))
case("negative-half-to-uint16", lambda: pd.Series([2.0, -0.5]).astype("uint16"))
case("negative-before-range", lambda: pd.Series([-1.0, 300.0]).astype("uint8"))
case("negative-float32-to-uint32", lambda: pd.Series([2.0, -3.0], dtype="float32").astype("uint32"))
case("negative-zero-to-uint8", lambda: pd.Series([-0.0, 3.0]).astype("uint8"))
case("negative-with-nan-to-uint8", lambda: pd.Series([-1.0, np.nan]).astype("uint8"))
case("negative-to-int8-in-range", lambda: pd.Series([-1.0, -128.0]).astype("int8"))
