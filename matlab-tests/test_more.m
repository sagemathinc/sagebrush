% dec2bin, dec2hex, bin2dec, hex2dec, sub2ind, ind2sub and mat2cell
% (lib/_matlab_more.py): the cases MATLAB's documentation and Octave
% agree on.  (Not here: split and replace, which Octave lacks; text with
% the 0b and 0x prefixes and type suffixes, which Octave does not read;
% dec2bin of a fraction, which Octave truncates towards zero; sub2ind
% with scalar subscripts among arrays: test/matlab-more.test.ts.)
