case("sorted-bool-min", lambda: pd.Series([True, False, True]).groupby(pd.Series([0, 0, 1])).min())
case("block-nan-elsewhere.exact", lambda: pd.DataFrame({"k": [0] * 7, "a": [0.2] * 7, "b": [1.0] * 6 + [np.nan]}).groupby("k").sum().to_numpy().tolist())
case("block-no-nan.exact", lambda: pd.DataFrame({"k": [0] * 7, "a": [0.2] * 7, "b": [1.0] * 7}).groupby("k").sum().to_numpy().tolist())
case("big-count", lambda: big.groupby("g")["v"].count().tolist())
