# float32 columns: built from float32 arrays, dtype="float32" or numpy float32 scalars, or by astype; they keep
# float32 through setting, sorting, filling, concat and diff, reduce as pandas' nanops do in float32 (np.float32
# results), print as pandas formats them, and describe and corr like any number column.
import io
import numpy as np
import pandas as pd
from _cases import case, dtypes

a = np.array([0.1, 1.5, np.nan, -2.25, 3e38], dtype=np.float32)
s = pd.Series(a, name="f")
