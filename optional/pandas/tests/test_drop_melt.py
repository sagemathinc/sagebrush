# drop (rows or columns by label; every row of a repeated label; a missing label a KeyError unless errors="ignore")
# and melt (wide to long: the id columns repeated for each value column, a column of the value columns' labels and
# one of their values end to end).
import numpy as np
import pandas as pd
from _cases import case, dtypes

df = pd.DataFrame({"a": [1, 2, 3], "b": ["x", "y", "z"], "c": [0.5, 1.5, 2.5]})
s = pd.Series([1, 2, 3], index=["p", "q", "r"], name="n")
w = pd.DataFrame({"id": ["s", "t"], "x": [1, 2], "y": [3.5, 4.5]})

case("frame.columns", lambda: df.drop(columns="b"))
case("frame.columns-list", lambda: df.drop(columns=["a", "c"]))
case("frame.axis1", lambda: df.drop("b", axis=1))
case("frame.axis-columns", lambda: df.drop(["a"], axis="columns"))
case("frame.row", lambda: df.drop(0))
case("frame.row.index", lambda: df.drop(0).index)
case("frame.rows-list", lambda: df.drop(index=[0, 2]))
case("frame.all-rows", lambda: df.drop(index=[0, 1, 2]))
case("frame.both", lambda: df.drop(index=1, columns="a"))
case("frame.missing", lambda: df.drop(columns=["z", "q"]))
case("frame.missing-row", lambda: df.drop(5))
case("frame.missing-ignore", lambda: df.drop(columns=["z", "a"], errors="ignore"))
case("frame.str-label-range-index", lambda: df.drop("x"))
case("frame.repeated-label", lambda: pd.DataFrame({"a": [1, 2, 3]}, index=[0, 0, 1]).drop(0))
case("frame.named-index", lambda: pd.DataFrame({"a": [1, 2]}, index=pd.Index([5, 6], name="k")).drop(5))
case("frame.labels-and-index", lambda: df.drop("a", columns="b"))
case("frame.nothing", lambda: df.drop())
case("frame.bad-axis", lambda: df.drop(0, axis=2))
case("frame.original-kept", lambda: (df.drop(columns="a"), df)[1])
case("series.label", lambda: s.drop("q"))
case("series.list", lambda: s.drop(["p", "r"]))
case("series.index", lambda: s.drop(index="p"))
case("series.missing", lambda: s.drop(["z"]))
case("series.missing-ignore", lambda: s.drop(["z", "p"], errors="ignore"))
case("series.tuple-is-one-label", lambda: s.drop(("p", "q")))
case("series.columns-ignored", lambda: s.drop(columns="p"))
case("series.bad-axis", lambda: s.drop("p", axis=1))
case("series.range", lambda: pd.Series([1, 2, 3]).drop(1).index)

for n, gone in ((3, [1]), (5, [1, 3]), (6, [1, 3, 5]), (5, [1, 2, 3]), (5, [0]), (5, [4]), (5, [2]), (5, [0, 1, 2, 3, 4])):
    case("range-%d-without-%s" % (n, "-".join(map(str, gone))), lambda n=n, gone=gone: pd.Series(range(n)).drop(gone).index)
case("range-step-without-last", lambda: pd.Series([0, 1, 2, 3], index=pd.RangeIndex(0, 10, 3)).drop(9).index)
case("range-step-without-inner", lambda: pd.Series([0, 1, 2, 3], index=pd.RangeIndex(0, 10, 3)).drop(3).index)
case("range-one-without-it", lambda: pd.Series([0], index=pd.RangeIndex(1, 2)).drop(1).index)
case("frame.range-columns", lambda: pd.DataFrame([[1, 2, 3]]).drop(columns=1).columns)

case("melt", lambda: w.melt(id_vars="id"))
case("melt.dtypes", lambda: dtypes(w.melt(id_vars="id")))
case("melt.function", lambda: pd.melt(w, id_vars=["id"], value_vars=["y"], var_name="k", value_name="v"))
case("melt.no-id", lambda: w.melt())
case("melt.no-id.dtypes", lambda: dtypes(w.melt()))
case("melt.value-vars-order", lambda: pd.DataFrame({"x": [1], "y": [2], "z": [3]}).melt(id_vars="z", value_vars=["y", "x"]))
case("melt.value-vars-overlap", lambda: pd.DataFrame({"x": [1], "y": [2], "z": [3]}).melt(id_vars="z", value_vars=["z", "x"]))
case("melt.keep-index", lambda: pd.DataFrame({"x": [1, 2], "y": [3, 4]}, index=[5, 6]).melt(ignore_index=False))
case("melt.int-labels", lambda: pd.DataFrame({0: [1], 1: [2]}).melt())
case("melt.int-labels.dtypes", lambda: dtypes(pd.DataFrame({0: [1], 1: [2]}).melt()))
case("melt.bool-int", lambda: dtypes(pd.DataFrame({"x": [True], "y": [2]}).melt()))
case("melt.str-id-missing", lambda: pd.DataFrame({"i": ["a", None], "y": [2, 3], "z": [4, 5]}).melt(id_vars="i"))
case("melt.only-ids", lambda: pd.DataFrame({"x": [1, 2]}).melt(id_vars="x"))
case("melt.only-ids.dtypes", lambda: dtypes(pd.DataFrame({"x": [1, 2]}).melt(id_vars="x")))
case("melt.missing", lambda: w.melt(id_vars="q"))
case("melt.missing-both", lambda: w.melt(id_vars="q", value_vars=["x", "r"]))
case("melt.value-name-taken", lambda: pd.DataFrame({"value": [1], "x": [2]}).melt(id_vars="value"))
case("melt.duplicate-output", lambda: w.melt(id_vars="id", var_name="id"))
case("melt.duplicate-ids", lambda: w.melt(id_vars=["id", "id"]))
case("melt.var-name-list", lambda: w.melt(var_name=["k"]))
case("melt.original-kept", lambda: (w.melt(id_vars="id"), w)[1])
