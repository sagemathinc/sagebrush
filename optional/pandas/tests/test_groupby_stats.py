# groupby std, var and median: pandas' Welford update per group (var in float32 arithmetic for a float32 column), ddof,
# skipna; the median as the middle value or the mean of the two middle ones; with exact values.
import numpy as np
import pandas as pd
from _cases import case, dtypes

k = pd.Series([0, 0, 1, 1, 1, 2])
x = pd.Series([1.5, 2.5, np.nan, 4.0, 7.0, 3.0])
n = pd.Series([1, 2, 3, 4, 5, 6])
b = pd.Series([True, False, True, True, False, True])
rng = np.random.RandomState(1)
big = pd.Series(rng.standard_normal(1000) * 1e3 + 1e6)
bigk = pd.Series(np.arange(1000) % 7)
sorted_k = pd.Series(np.arange(1000) // 150)
f32 = pd.Series(rng.standard_normal(600).astype(np.float32) * np.float32(3.5))
f32k = pd.Series(np.arange(600) % 5)

case("std", lambda: x.groupby(k).std())
case("var", lambda: x.groupby(k).var())
case("median", lambda: x.groupby(k).median())
case("std.exact", lambda: x.groupby(k).std().tolist())
case("std-ddof0", lambda: x.groupby(k).std(ddof=0))
case("var-ddof2", lambda: x.groupby(k).var(ddof=2))
case("std-skipna-false", lambda: x.groupby(k).std(skipna=False))
case("median-skipna-false", lambda: x.groupby(k).median(skipna=False))
case("int-std", lambda: n.groupby(k).std())
case("int-median", lambda: n.groupby(k).median())
case("int-median-odd", lambda: n.groupby(pd.Series([0, 0, 0, 1, 1, 1])).median())
case("bool-std", lambda: b.groupby(k).std())
case("bool-median", lambda: b.groupby(k).median())
case("uint8-median", lambda: n.astype("uint8").groupby(k).median())
case("float32-std", lambda: x.astype("float32").groupby(k).std())
case("float32-std.exact", lambda: x.astype("float32").groupby(k).std().tolist())
case("float32-var", lambda: x.astype("float32").groupby(k).var())
case("float32-median", lambda: x.astype("float32").groupby(k).median())
case("float32-big-std.exact", lambda: f32.groupby(f32k).std().tolist())
case("float32-big-var.exact", lambda: f32.groupby(f32k).var().tolist())
case("float32-big-median.exact", lambda: f32.groupby(f32k).median().tolist())
case("big-std.exact", lambda: big.groupby(bigk).std().tolist())
case("big-var.exact", lambda: big.groupby(bigk).var().tolist())
case("big-median.exact", lambda: big.groupby(bigk).median().tolist())
case("sorted-std.exact", lambda: big.groupby(sorted_k).std().tolist())
case("median-even.exact", lambda: pd.Series([0.1, 0.2, 0.3, 0.7]).groupby(pd.Series([0, 0, 1, 1])).median().tolist())
case("inf", lambda: pd.Series([np.inf, 1.0, -np.inf, np.inf]).groupby(pd.Series([0, 0, 1, 1])).std().tolist())
case("single-value", lambda: pd.Series([5.0]).groupby(pd.Series([0])).std())
case("str-std", lambda: pd.Series(list("abcdef")).groupby(k).std())
case("str-median", lambda: pd.Series(list("abcdef")).groupby(k).median())
case("frame-std", lambda: pd.DataFrame({"k": k, "x": x, "s": list("abcdef")}).groupby("k").std())
case("frame-std-numeric-only", lambda: pd.DataFrame({"k": k, "x": x, "s": list("abcdef")}).groupby("k").std(numeric_only=True))
case("frame-median", lambda: pd.DataFrame({"k": k, "x": x, "n": n}).groupby("k").median())
case("frame-median.dtypes", lambda: dtypes(pd.DataFrame({"k": k, "x": x, "n": n}).groupby("k").median()))
case("frame-var-float32", lambda: dtypes(pd.DataFrame({"k": k, "x": x.astype("float32")}).groupby("k").var()))
case("as-index-false", lambda: pd.DataFrame({"k": k, "x": x}).groupby("k", as_index=False).median())
case("agg-std", lambda: x.groupby(k).agg("std"))
case("agg-list", lambda: x.groupby(k).agg(["mean", "std", "median"]))
case("agg-named", lambda: pd.DataFrame({"k": k, "x": x}).groupby("k").agg(spread=("x", "std"), mid=("x", "median")))
case("agg-dict", lambda: pd.DataFrame({"k": k, "x": x, "n": n}).groupby("k").agg({"x": "var", "n": "median"}))

# A float32 column's std and median run in float64 and come back float32 only when every group's value, cast,
# stays within 5e-4, absolute (pandas decides over the frame's float32 block at once; agg with a dict, column by column).
f4 = lambda *v: pd.Series(np.array(v, dtype=np.float32))
k4 = pd.Series([1, 1, 2, 2])
case("f32-std-fits.dtype", lambda: f4(0.0, 30001.0, 3.0, 5.0).groupby(k4).std().dtype)
case("f32-std-wide.dtype", lambda: f4(0.0, 30005.0, 3.0, 5.0).groupby(k4).std().dtype)
case("f32-std-wide.exact", lambda: f4(0.0, 30005.0, 3.0, 5.0).groupby(k4).std().tolist())
case("f32-std-wide-nan.dtype", lambda: f4(np.nan, 1.0, 0.0, 50001.0).groupby(k4).std().dtype)
case("f32-var-wide.dtype", lambda: f4(0.0, 30005.0, 3.0, 5.0).groupby(k4).var().dtype)
case("f32-median-half.dtype", lambda: f4(16777216.0, 16777218.0, 1.0, 2.0).groupby(k4).median().dtype)
case("f32-median-half.exact", lambda: f4(16777216.0, 16777218.0, 1.0, 2.0).groupby(k4).median().tolist())
case("f32-median-fits.dtype", lambda: f4(10000.0, 13001.0, 1.0, 2.0).groupby(k4).median().dtype)
w4 = pd.DataFrame({"k": [1, 1, 2, 2], "a": f4(1.0, 2.0, 3.0, 5.0), "b": f4(0.0, 30005.0, 3.0, 5.0)})
case("f32-block-std.dtypes", lambda: w4.groupby("k").std().dtypes.tolist())
case("f32-block-median.dtypes", lambda: w4.groupby("k").median().dtypes.tolist())
case("f32-block-agg-str.dtypes", lambda: w4.groupby("k").agg("std").dtypes.tolist())
case("f32-block-subset.dtypes", lambda: w4.groupby("k")[["a"]].std().dtypes.tolist())
case("f32-block-agg-dict.dtypes", lambda: w4.groupby("k").agg({"a": "std", "b": "std"}).dtypes.tolist())
case("f32-block-var.dtypes", lambda: w4.groupby("k").var().dtypes.tolist())
case("f32-series-of-block.dtype", lambda: w4.groupby("k")["a"].std().dtype)

# Wide values with a missing value in every 11th row: the square root of the variance rounded once (as np.sqrt).
rng23 = np.random.RandomState(23)
g23 = pd.Series(rng23.randint(0, 9, 3000))
h23 = pd.Series(rng23.standard_normal(3000) * 10.0 ** rng23.randint(-2, 6, 3000) + 1e4)
h23[::11] = np.nan
case("wide-std.exact", lambda: h23.groupby(g23).std().tolist())
case("wide-f32-std", lambda: h23.astype("float32").groupby(g23).std())
