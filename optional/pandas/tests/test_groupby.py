# groupby with one key: size, count, sum, mean, min, max and agg, as pandas 3.1 computes them (Kahan sums, integer
# sums kept in the column's dtype where they fit, missing keys dropped unless dropna=False, groups sorted unless
# sort=False), with iteration and get_group; exact float values are printed too.
import numpy as np
import pandas as pd
from _cases import case, dtypes

df = pd.DataFrame({"k": ["b", "a", "b", None, "a", "c"], "j": [1, 1, 2, 2, 1, 1], "x": [1.5, 2.0, np.nan, 4.0, 5.0, 6.0],
                   "n": [1, 2, 3, 4, 5, 6], "s": ["p", "q", "r", "s", "t", "u"], "ok": [True, False, True, True, False, True]})
g = df.groupby("k")
k3 = pd.Series(["a", "a", "b"])
rng = np.random.RandomState(5)
big = pd.DataFrame({"g": rng.randint(0, 7, 2000), "v": rng.standard_normal(2000) * 1e3 + 1e-3})
big.loc[big.index[::9], "v"] = np.nan

case("mean", lambda: g.mean())
case("mean-numeric-only", lambda: g.mean(numeric_only=True))
case("mean-numeric-only.dtypes", lambda: dtypes(g.mean(numeric_only=True)))
case("sum", lambda: g.sum())
case("sum.dtypes", lambda: dtypes(g.sum()))
case("sum-numeric-only", lambda: g.sum(numeric_only=True))
case("count", lambda: g.count())
case("size", lambda: g.size())
case("min", lambda: g.min())
case("max", lambda: g.max())
case("select-mean", lambda: g["x"].mean())
case("select-list-sum", lambda: g[["x", "n"]].sum())
case("select-attribute", lambda: g.n.sum())
case("select-size", lambda: g["n"].size())
case("dropna-false", lambda: df.groupby("k", dropna=False)["n"].sum())
case("dropna-false.index", lambda: df.groupby("k", dropna=False)["n"].sum().index)
case("sort-false", lambda: df.groupby("k", sort=False)["n"].sum())
case("as-index-false", lambda: df.groupby("k", as_index=False)["n"].sum())
case("as-index-false-frame", lambda: df.groupby("k", as_index=False)[["n", "x"]].mean())
case("as-index-false-size", lambda: df.groupby("k", as_index=False).size())
case("int-key", lambda: df.groupby("j")["x"].mean())
case("int-key-frame", lambda: df.groupby("j").sum())
case("bool-key", lambda: df.groupby("ok")["n"].sum())
case("float-key", lambda: df.groupby("x")["n"].sum())
case("key-unsorted-int", lambda: pd.Series([1, 2, 3]).groupby(pd.Series([3, 1, 3])).sum())
case("key-nan-float", lambda: pd.Series([1, 2, 3]).groupby(pd.Series([1.0, np.nan, 1.0])).sum())
case("key-datetime", lambda: pd.Series([1, 2, 3]).groupby(pd.Series(pd.to_datetime(["2020-01-02", "2020-01-01", "2020-01-02"]))).sum())
case("key-int-label", lambda: pd.DataFrame({0: ["a", "a", "b"], 1: [1, 2, 3]}).groupby(0).sum())
case("key-index-name", lambda: pd.DataFrame({"n": [1, 2, 3]}, index=pd.Index(["a", "a", "b"], name="ix")).groupby("ix").sum())
case("key-level", lambda: df.set_index("k").groupby(level=0)["n"].sum())
case("key-series", lambda: df.groupby(df["j"])["n"].sum())
case("key-list", lambda: pd.Series([1, 2, 3]).groupby(["a", "a", "b"]).sum())
case("key-one-label-list", lambda: df.groupby(["k"])["n"].sum())
case("series-groupby", lambda: df["n"].groupby(df["k"]).sum())
case("series-groupby-named", lambda: pd.Series([1, 2, 3], name="v").groupby(pd.Series(["a", "a", "b"], name="g")).sum())
case("agg-str", lambda: g["n"].agg("sum"))
case("agg-list", lambda: g["n"].agg(["sum", "mean"]))
case("agg-dup-names", lambda: g["n"].agg(["sum", "sum"]))
case("agg-dict", lambda: g.agg({"n": "sum", "x": "mean"}))
case("agg-named", lambda: g.agg(total=("n", "sum"), avg=("x", "mean")))
case("agg-named-series", lambda: g["n"].agg(tot="sum", mx="max"))
case("agg-func", lambda: g["n"].agg(lambda v: v.max() - v.min()))
case("agg-func-mean", lambda: g["n"].agg(lambda v: v.mean()))
case("agg-func-type", lambda: g["n"].agg(lambda v: type(v).__name__))
case("agg-np-sum", lambda: g["n"].agg(np.sum))
case("agg-frame-str", lambda: g[["n", "x"]].agg("mean"))
case("agg-frame-func", lambda: g[["n", "x"]].agg(lambda v: v.max()))
case("agg-lambda-list", lambda: g["n"].agg([lambda v: v.sum()]))
case("aggregate", lambda: g["n"].aggregate("max"))
case("agg-unknown", lambda: g["n"].agg("nope"))
case("agg-dict-missing", lambda: g.agg({"zz": "sum"}))
case("str-sum", lambda: g["s"].sum())
case("str-max", lambda: g["s"].max())
case("str-mean", lambda: g["s"].mean())
case("str-min-missing", lambda: pd.Series(["z", None, "y"]).groupby(k3).min())
