# copy(), keys(), items(), len(), head, tail, sample, isna/notna.
import numpy as np
import pandas as pd
from _cases import case, dtypes, setattr_columns, setattr_index, setattr_name

df = pd.DataFrame({"i": [1, 2], "f": [1.5, np.nan], "b": [True, False], "s": ["a", "b"]})
d = pd.DataFrame({"a": [1, 2], "b": [3, 4]})
s = pd.Series([10, 20, 30], index=["a", "b", "c"], name="v")

case("frame.dtypes", lambda: df.dtypes)
case("frame.shape", lambda: df.shape)
case("frame.size", lambda: df.size)
case("frame.ndim", lambda: df.ndim)
case("frame.empty", lambda: (df.empty, pd.DataFrame().empty, pd.DataFrame(columns=["a"]).empty))
case("frame.columns", lambda: df.columns)
case("frame.index", lambda: df.index)
case("frame.keys", lambda: d.keys())
case("frame.items", lambda: [(k, type(v).__name__, v.tolist()) for k, v in d.items()])
case("frame.iter", lambda: list(d))
case("frame.len", lambda: len(d))
case("frame.contains", lambda: ("a" in d, "z" in d))
case("frame.attr", lambda: d.a)
case("frame.attr-missing", lambda: d.zz)
case("frame.bool", lambda: bool(d))
case("frame.T", lambda: df.T)
case("frame.T-dtypes", lambda: df.T.dtypes)
case("frame.T-int", lambda: dtypes(df[["i"]].T))
case("frame.T-str", lambda: dtypes(df[["s"]].T))
case("frame.T-int-float", lambda: df[["i", "f"]].T)
case("frame.set-columns", lambda: (lambda e: (setattr_columns(e, ["p", "q"]), e)[1])(d.copy()))
case("frame.set-columns-bad", lambda: setattr_columns(d.copy(), ["p"]))
case("frame.set-index", lambda: (lambda e: (setattr_index(e, ["p", "q"]), e)[1])(d.copy()))
case("frame.set-index-bad", lambda: setattr_index(d.copy(), ["p"]))
case("frame.head", lambda: pd.DataFrame({"a": range(10)}).head())
