// An ideal compared with an element (Sage mode): I == f is I == R.ideal(f)
// for f in I's ring R (or a scalar of its base ring), built by R's own
// ideal() and compared as ideals, so it admits no work R.ideal(f) == I
// would not: the same answers, and the same refusals with the same
// messages, univariate and multivariate.  An element of another ring is
// unequal before any conversion.  The answers are Sage 10.10's
// (sage-tests/test_ideal_element_eq has the full table).
import test from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const cli = join(__dirname, "..", "src", "cli.js");
const dir = mkdtempSync(join(tmpdir(), "sb-ideq-"));

function sage(code: string) {
  const f = join(dir, "t" + Math.random().toString(36).slice(2) + ".sage");
  writeFileSync(f, code);
  return spawnSync(process.execPath, [cli, "--sage", f], { encoding: "utf8" });
}

// (I == f and I == R.ideal(f) side by side, or the error each raises)
const both = [
  "def both(I, f):",
  "    def one(g):",
  "        try:",
  "            return repr(g())",
  "        except Exception as e:",
  "            return '%s: %s' % (type(e).__name__, e)",
  "    a, b = one(lambda: I == f), one(lambda: I == I.ring().ideal(f))",
  "    print(a == b, a)",
].join("\n");

test("I == f answers as I == R.ideal(f), univariate and multivariate", () => {
  const r = sage([
    both,
    "R.<t> = QQ[]; P.<u> = ZZ[]; S.<x,y> = QQ[]; G.<c,d> = GF(7)[]",
    "both(R.ideal(2*t), t); both(R.ideal(t^2), t); both(R.ideal(1), 3); both(R.ideal(0), 0); both(R.ideal(0), t)",
    "both(P.ideal(2*u), u); both(P.ideal(-u), u); both(P.ideal(2), -2); both(P.ideal(2), 4)",
    "both(S.ideal(x), 2*x); both(S.ideal(x, x^2), x); both(S.ideal(x, y), x); both(G.ideal(3*c), c)",
  ].join("\n"));
  assert.equal(r.stderr, "");
  assert.equal(r.stdout, [
    "True True", "True False", "True True", "True True", "True False",
    "True False", "True True", "True True", "True False",
    "True True", "True True", "True False", "True True", "",
  ].join("\n"));
});

test("I == f refuses as I == R.ideal(f) does, with the same message", () => {
  const r = sage([
    both,
    // (Groebner bases over ZZ are not implemented: an error, never a guess;
    // Sage answers False here)
    "A.<a,b> = ZZ[]; both(A.ideal(2*a), a)",
    // (Zmod(6): content 1 on both sides and neither leading coefficient a
    // unit: not supported yet, refused, both orders)
    "Z.<z> = Zmod(6)[]; both(Z.ideal(2*z + 3), 3*z + 2); both(Z.ideal(3*z + 2), 2*z + 3)",
  ].join("\n"));
  assert.equal(r.stderr, "");
  const lines = r.stdout.trim().split("\n");
  assert.equal(lines.length, 3);
  assert.match(lines[0], /^True NotImplementedError: ideal equality for an ideal over ZZ \(Groebner bases over ZZ are not implemented/);
  for (const l of lines.slice(1)) {
    assert.equal(l, "True NotImplementedError: equality of ideals of a polynomial ring over Zmod(6) generated by polynomials of content 1 without a unit leading coefficient is not supported yet");
  }
});

test("Zmod(n)[t]: the cheap sufficient checks first, with no factoring (CORR-SAGE102-R1-1)", () => {
  const r = sage([
    both,
    "R.<t> = Zmod(2^130)[]; I = R.ideal(2*t)",
    "print(I == I, I == 2*t, I == R.ideal(-2*t), I == -2*t, 2*t == I, R.ideal(2*t) == R.ideal(6*t), R.ideal(2*t) == 6*t + 2)",
  ].join("\n"));
  assert.equal(r.stderr, "");
  assert.equal(r.stdout, "True True True True True True False\n");
});

test("Zmod(n)[t]: the work is charged to ff.work before it starts, exact at the limit (LIMIT-SAGE102-ZMOD-1, -R3-1)", () => {
  // (S.WORK set here as the limits file would set it: _zmod_ideal_eq reads it
  // per comparison; the spies count the divisions and the gcds that run)
  const run = (W: number, setup: string, expr: string) => sage([
    "import math, _sage_frac as F, _sage_ffsub as S",
    "calls = {'div': 0, 'gcd': 0}; od = F._divmod_unit_lc; og = math.gcd",
    "def sd(*a):\n    calls['div'] += 1\n    return od(*a)",
    "def sg(*a):\n    calls['gcd'] += 1\n    return og(*a)",
    "F._divmod_unit_lc = sd",
    setup,
    "S.WORK = " + W,
    "math.gcd = sg",
    "try:\n    r = " + expr + "\nexcept NotImplementedError as e:\n    r = 'refused: ' + str(e)",
    "math.gcd = og",
    "print(r, calls['div'], calls['gcd'])",
  ].join("\n"));
  const work = "refused: equality of ideals of a polynomial ring over Zmod(%s) is not supported yet (work)";
  // the unit-leading branch: (a) = (a (1 + 2t)), a = t^4999 + 1 over Zmod(4),
  // w = 2, bits 3, la = 5000, lb = 5001: w (la + lb) for the lists (lengths
  // differ: no comparison), bits w (2 la + lb + 2) for the gcds, w (2 la + 3
  // + 12) for the division and unit test: 20002 + 90018 + 20030
  const big = "R.<t> = Zmod(4)[]; a = t^4999 + 1; b = a * (1 + 2*t)";
  assert.equal(run(130050, big, "R.ideal(a) == R.ideal(b)").stdout, "True 1 15004\n");
  assert.match(run(130049, big, "R.ideal(a) == R.ideal(b)").stdout, new RegExp("^" + work.replace("%s", "4").replace(/[()]/g, "\\$&") + " 0 \\d+\n$"));
  // through the content (2t vs 2t + 2: decided over Zmod(2), one budget)
  const small = "R.<t> = Zmod(4)[]";
  assert.equal(run(164, small, "R.ideal(2*t) == R.ideal(2*t + 2)").stdout, "False 1 17\n");
  assert.match(run(163, small, "R.ideal(2*t) == R.ideal(2*t + 2)").stdout, / 0 \d+\n$/);
  // content 1 and no unit coefficient (R3-1): the gcd scan is admitted
  // whole first, 24 + 48 cops, and step 5 rescans nothing; at one short no
  // gcd runs at all
  const six = "R.<t> = Zmod(6)[]";
  assert.equal(run(72, six, "R.ideal(2*t + 3) == R.ideal(3*t + 2)").stdout,
    "refused: equality of ideals of a polynomial ring over Zmod(6) generated by polynomials of content 1 without a unit leading coefficient is not supported yet 0 8\n");
  assert.equal(run(71, six, "R.ideal(2*t + 3) == R.ideal(3*t + 2)").stdout, work.replace("%s", "6") + " 0 0\n");
  // lengths 2 and 1 (R4-2): 2 lg + lh + 2 = 7 gcds, all admitted at 6 + 42
  // = 48 cops (then the division's charge refuses), none at 47; the whole
  // comparison, (2t + 3) against the unit 5, is admitted at 82 (False)
  assert.equal(run(82, six, "R.ideal(2*t + 3) == R.ideal(R(5))").stdout, "False 1 8\n");
  assert.equal(run(81, six, "R.ideal(2*t + 3) == R.ideal(R(5))").stdout, work.replace("%s", "6") + " 0 7\n");
  assert.equal(run(48, six, "R.ideal(2*t + 3) == R.ideal(R(5))").stdout, work.replace("%s", "6") + " 0 7\n");
  assert.equal(run(47, six, "R.ideal(2*t + 3) == R.ideal(R(5))").stdout, work.replace("%s", "6") + " 0 0\n");
});

test("Zmod(n)[t]: long equal, opposite and neither generators, charged before any coefficient is read (LIMIT-SAGE102-R3-2, -R4-1)", () => {
  // (the stored coefficients are read in place, canonical: no copy or
  // reduction before the charge; a counting element shows the reads.  With
  // equal lengths the first charge is 3 w (lg + lh): the equal scan, the
  // opposite scan and the integer lists, each reading every coefficient at
  // worst; one short, nothing is read)
  const r = sage([
    "import _sage_frac as F",
    "reads = [0]",
    "class C:\n    def __init__(self, v):\n        self.v = v\n    def __int__(self):\n        reads[0] += 1\n        return self.v",
    "L = 50000",
    "g = [C(1 + k % 3) for k in range(L)]",
    // (neither: both scans run to the last pair, as 2 is its own opposite
    // modulo 4, and then the lists are made: 6 L reads)
    "g2 = [C(2) for _ in range(L - 1)] + [C(1)]",
    "h2 = [C(2) for _ in range(L - 1)] + [C(2)]",
    "for g_, h, name in ((g, list(g), 'equal'), (g, [C((-x.v) % 4) for x in g], 'opposite'), (g2, h2, 'neither')):",
    "    for W in (600000, 599999):",
    "        reads[0] = 0",
    "        try:\n            r = F._zmod_ideal_eq(g_, h, 4, [W])\n        except NotImplementedError as e:\n            r = 'refused'",
    "        print(name, W, r, reads[0])",
  ].join("\n"));
  assert.equal(r.stderr, "");
  // (the equal comparison reads both lists once; the opposite one first
  // meets a difference in the equal scan; neither reads all three times
  // and is then refused by the next charge, the gcds')
  assert.equal(r.stdout, [
    "equal 600000 True 100000", "equal 599999 refused 0",
    "opposite 600000 True 100002", "opposite 599999 refused 0",
    "neither 600000 refused 300000", "neither 599999 refused 0", "",
  ].join("\n"));
});

test("Zmod(n)[t]: exact ideal equality, units and zero divisors (CORR-SAGE102-1)", () => {
  const r = sage([
    both,
    // (astra's vectors, as Sage 10.10: sage-tests/test_ideal_zmod_eq has the table)
    "R.<t> = Zmod(4)[]; both(R.ideal(t), t + 1); both(R.ideal(t), 2*t); both(R.ideal(1), 1 + 2*t)",
    "S.<s> = Zmod(6)[]; both(S.ideal(s), s + 1); both(S.ideal(2*s), 4*s); both(S.ideal(2), 3)",
    // (deliberately not as Sage, which says False: t + 2t^2 = t (1 + 2t)
    // and 1 + 2t is a unit, (1 + 2t)^2 = 1, so the ideals are equal)
    "both(R.ideal(t), t + 2*t^2); print((t + 2*t^2) * (1 + 2*t) == t, (1 + 2*t)^2 == 1)",
  ].join("\n"));
  assert.equal(r.stderr, "");
  assert.equal(r.stdout, [
    "True False", "True False", "True True",
    "True False", "True True", "True False",
    "True True", "True True", "",
  ].join("\n"));
});

test("another ring's element is unequal before any conversion; a large generator compares by its coefficients", () => {
  const r = sage([
    "R.<t> = QQ[]; S = PolynomialRing(QQ, 't,w')",
    // (R(f) of this one, an element of QQ[t,w] in R's variable, is refused
    // by the dense-conversion memory guard, 2^20 coefficients; I == f does not
    // convert it: unequal, as in Sage)
    "f = S.gen(0)^(2^20)",
    "print(R.ideal(t) == f)",
    "try:\n    R(f)\nexcept MemoryError as e:\n    print('R(f):', str(e).splitlines()[1])",
    // (associates of degree 4000: one pass over the coefficients, no division)
    "g = R([QQ(k + 1) / (k + 2) for k in range(4001)])",
    "print(R.ideal(3*g) == g, R.ideal(3*g) == g + 1, R.ideal(g) == t*g)",
  ].join("\n"));
  assert.equal(r.stderr, "");
  assert.equal(r.stdout, [
    "False",
    "R(f): Converting this polynomial of degree 1048576 to a dense one needs about 8.4 MB, but Sagebrush allows about 8.3 MB for this conversion here.",
    "True False False", "",
  ].join("\n"));
});
