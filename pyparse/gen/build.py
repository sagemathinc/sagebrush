HEADER = "// @generated by pyparse/gen/build.py from CPython v3.14.4 ({src}); do not edit.\n"


# ---------------------------------------------------------------- tokens

def read_tokens():
    names, exact = [], {}
    for line in open(os.path.join(VENDOR, "Tokens")):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        names.append(parts[0])
        if len(parts) > 1:
            exact[parts[1][1:-1]] = len(names) - 1
    return names, exact


def gen_tokens(names, exact):
    out = [HEADER.format(src="Grammar/Tokens")]
    for i, n in enumerate(names):
        out.append(f"export const {n} = {i};")
    out.append(f"export const N_TOKENS = {len(names)};")
    out.append(f"export const TOKEN_NAMES: string[] = {names!r};".replace("'", '"'))
    out.append("export const EXACT_TOKENS: Record<string, number> = {")
    for s, t in exact.items():
        out.append(f"  {s!r}: {t},".replace("'\\\\'", '"\\\\"'))
    out.append("};")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- AST

def gen_ast():
    mod = asdl.parse(os.path.join(VENDOR, "Python.asdl"))
    out = [HEADER.format(src="Parser/Python.asdl")]
    out.append("// Nodes are plain objects {_type, ...fields, ...attributes}, like CPython's ast module.")
    out.append("export type Node = any;")
    fields, attrs, enums = {}, {}, []

    def ctor(name, flds, attributes, prefix="_PyAST_"):
        params = [f.name for f in flds] + [a.name for a in attributes]
        fields[name] = [f.name for f in flds]
        attrs[name] = [a.name for a in attributes]
        seqs = {f.name for f in flds if f.seq}
        body = ", ".join([f"_type: {name!r}".replace("'", '"')] + [f"{p}: {p} ?? []" if p in seqs else f"{p}" for p in params])
        sig = ", ".join(f"{p}: any" for p in params + ["_arena"])
        out.append(f"export function {prefix}{name}({sig}): Node {{ return {{ {body} }}; }}")

    for dfn in mod.dfns:
        t = dfn.value
        if isinstance(t, asdl.Sum):
            if all(not c.fields for c in t.types):  # simple enum
                for c in t.types:
                    enums.append(c.name)
                    fields[c.name], attrs[c.name] = [], []
                    out.append(f'export const {c.name}: Node = Object.freeze({{ _type: "{c.name}" }});')
            else:
                for c in t.types:
                    ctor(c.name, c.fields, t.attributes)
        else:
            ctor(dfn.name, t.fields, t.attributes)
    out.append("export const FIELDS: Record<string, string[]> = " + repr(fields).replace("'", '"') + ";")
    out.append("export const ATTRIBUTES: Record<string, string[]> = " + repr(attrs).replace("'", '"') + ";")
    out.append("export const ENUMS: string[] = " + repr(enums).replace("'", '"') + ";")
    return "\n".join(out) + "\n", enums


# ---------------------------------------------------------------- actions

JS_RESERVED = {"default", "in", "function", "var", "let", "new", "delete", "class", "this",
               "switch", "case", "do", "typeof", "void", "with", "yield", "enum", "export",
               "import", "package", "private", "protected", "public", "static", "super",
               "interface", "instanceof", "catch", "finally", "throw", "try", "debugger",
               "const", "extends", "implements", "arguments", "eval", "null", "true", "false"}


def js_name(name):
    return name + "_" if name in JS_RESERVED else name


CAST = re.compile(r"\(\s*(?:const\s+)?(?:asdl_\w+|\w+_ty|void|int|char|Token|PyObject|KeywordOrStarred|"
                  r"NameDefaultPair|SlashWithDefault|StarEtc|CmpopExprPair|KeyValuePair|KeyPatternPair|"
                  r"AugOperator|ResultTokenWithMetadata|Py_ssize_t)\s*\**\s*\)(?=\s*[\w(])")


STRING_LIT = re.compile(r'"(?:[^"\\]|\\.)*"' + r"|'(?:[^'\\]|\\.)*'")


def normalize(a):
    """Undo pegen's token re-spacing outside string literals: 'a -> v . x ( y , z )'."""
    parts, last = [], 0
    for m in STRING_LIT.finditer(a):
        parts.append(("code", a[last:m.start()]))
        parts.append(("str", m.group(0)))
        last = m.end()
    parts.append(("code", a[last:]))
    out = []
    for kind, text in parts:
        if kind == "code":
            text = re.sub(r"\s*(->|\.|\(|\)|\[|\]|,)\s*", r"\1", text)
            text = re.sub(r",", ", ", text)
            text = re.sub(r"\s+", " ", text)
        out.append(text)
    return "".join(out).strip()


def translate_action(action, varnames):
    """C action expression from python.gram -> TypeScript expression."""
    a = normalize(action)
    a = CAST.sub("", a)
    a = re.sub(r"\bp->arena\b", "null", a)
    a = re.sub(r"->v\.\w+\.", ".", a)                         # e->v.Name.id -> e.id
    a = re.sub(r"(\w+)->kind\s*==\s*(\w+)_kind", r'(\1._type === "\2")', a)  # node kind tests
    a = a.replace("->", ".")                                     # b->kind (AugOperator), t->lineno, ...
    a = re.sub(r"\bNULL\b", "null", a)
    a = re.sub(r"\bEXTRA\b", "...EXTRA", a)
    # CHECK(type, x), CHECK_NULL_ALLOWED(type, x), CHECK_VERSION(type, v, msg, x): drop the C type.
    a = re.sub(r"\b(CHECK|CHECK_NULL_ALLOWED|CHECK_VERSION)\(\s*[\w\s\*]+?\s*,\s*", r"\1(p, ", a)
    # Macros that use p implicitly.
    a = re.sub(r"\b(RAISE_(?!ERROR_KNOWN_LOCATION)[A-Z_]+)\(", r"\1(p, ", a)
    a = re.sub(r"\bPyErr_Occurred\(\)", "p.errorOccurred()", a)
    a = re.sub(r"\b(PyPegen_(?:first|last)_item)\(\s*([^,()]+?)\s*,\s*\w+\s*\)", r"\1(\2)", a)
    for v in varnames:
        if v != js_name(v):
            a = re.sub(rf"\b{v}\b", js_name(v), a)
    return a


# ---------------------------------------------------------------- parser

class Call:
    def __init__(self, var, code, kind=None, force_true=False):
        self.var, self.code, self.kind, self.force_true = var, code, kind, force_true


class TSCallMaker(GrammarVisitor):
    def __init__(self, gen, exact, tok_names):
        self.gen, self.exact, self.tok_names = gen, exact, set(tok_names)
        self.cache = {}

    def visit_NameLeaf(self, node):
        name = node.value
        if name in ("NAME", "NUMBER", "STRING"):
            return Call(f"{name.lower()}_var", f"p.{name.lower()}_token()", kind=name)
        if name == "SOFT_KEYWORD":
            return Call("soft_keyword_var", "p.soft_keyword_token()", kind="SOFT_KEYWORD")
        if name in self.tok_names:
            return Call(f"{name.lower()}_var", f"p.expect(T.{name})", kind="TOKEN")
        return Call(f"{name}_var", f"p.{name}_rule()")

    def visit_StringLeaf(self, node):
        val = eval(node.value)
        if re.match(r"[a-zA-Z_]\w*\Z", val):
            if node.value.endswith("'"):
                return Call("_keyword", f"p.expect({self.gen.keywords[val]})", kind="TOKEN")
            return Call("_keyword", f"p.expect_soft_keyword({node.value})", kind="SOFT")
        return Call("_literal", f"p.expect({self.exact[val]})", kind="TOKEN")

    def visit_NamedItem(self, node):
        c = self.visit(node.item)
        if node.name:
            c.var = node.name
        return c

    def lookahead(self, node, positive):
        c = self.visit(node.node)
        return Call(None, f"p.lookahead({'true' if positive else 'false'}, () => {c.code})")

    def visit_PositiveLookahead(self, node):
        return self.lookahead(node, True)

    def visit_NegativeLookahead(self, node):
        return self.lookahead(node, False)

    def visit_Forced(self, node):
        if isinstance(node.node, Leaf):
            val = eval(node.node.value)
            return Call("_literal", f"p.expect_forced_token({self.exact[val]}, {val!r})", kind="TOKEN")
        c = self.visit(node.node.rhs)
        return Call("_literal", f"p.expect_forced_result({c.code}, {str(node.node.rhs)!r})")

    def visit_Opt(self, node):
        c = self.visit(node.node)
        return Call("_opt_var", c.code, force_true=True)

    def artificial(self, node, prefix, fn):
        key = f"{prefix}_{node}"
        if key not in self.cache:
            self.cache[key] = fn()
        name = self.cache[key]
        return Call(f"{name}_var", f"p.{name}_rule()")

    def visit_Rhs(self, node):
        if node.can_be_inlined:
            return self.visit(node.alts[0].items[0])
        return self.artificial(node, "rhs", lambda: self.gen.artificial_rule_from_rhs(node))

    def visit_Repeat0(self, node):
        return self.artificial(node, "repeat0", lambda: self.gen.artificial_rule_from_repeat(node.node, False))

    def visit_Repeat1(self, node):
        return self.artificial(node, "repeat1", lambda: self.gen.artificial_rule_from_repeat(node.node, True))

    def visit_Gather(self, node):
        return self.artificial(node, "gather", lambda: self.gen.artificial_rule_from_gather(node))

    def visit_Group(self, node):
        return self.visit(node.rhs)

    def visit_Cut(self, node):
        return Call("_cut_var", "true")


class TSParserGenerator(ParserGenerator, GrammarVisitor):
    def __init__(self, grammar, tok_names, exact, file):
        super().__init__(grammar, set(tok_names), file)
        self.callmakervisitor = TSCallMaker(self, exact, tok_names)
        self.tok_names = tok_names
        self.rule_ids = {}
        self.helpers_used = set()

    def generate(self, filename):
        self.collect_rules()
        self.print(HEADER.format(src="Grammar/python.gram").rstrip())
        self.print('import * as T from "./tokens.gen";')
        self.print('import * as AST from "./ast.gen";')
        self.print('import { BaseParser } from "./pegen";')
        self.print('import * as H from "./helpers";')
        self.print("/* eslint-disable */")
        self.print("// Every C name used by the grammar's actions, in scope.")
        self.print("const { " + ", ".join(sorted(self.enums)) + " } = AST;")
        names = sorted(set(re.findall(r"\b(_PyAST_\w+)", self.grammar_text)))
        self.print("const { " + ", ".join(names) + " } = AST;")
        self.helper_marker = "/*__HELPERS__*/"
        self.print(self.helper_marker)
        kw = {k: v for k, v in self.keywords.items()}
        self.print(f"export const KEYWORDS: Record<string, number> = {kw!r};".replace("'", '"'))
        self.print(f"export const SOFT_KEYWORDS: string[] = {sorted(self.soft_keywords)!r};".replace("'", '"'))
        for i, name in enumerate(self.all_rules, 1000):
            self.rule_ids[name] = i
        self.print("export class GeneratedParser extends BaseParser {")
        with self.indent():
            self.print("keywords = KEYWORDS;")
            self.print("soft_keywords = SOFT_KEYWORDS;")
            for name, rule in list(self.all_rules.items()):
                self.print()
                self.visit(rule)
        self.print("}")

    # -- rules

    def visit_Rule(self, node):
        is_loop, is_gather = node.is_loop(), node.is_gather()
        rhs = node.flatten()
        for line in str(node).splitlines():
            self.print(f"// {line}")
        rid = self.rule_ids[node.name]
        if node.left_recursive and node.leader:
            self.print(f"{node.name}_rule(): any {{")
            with self.indent():
                self.print("const p = this;")
                self.print(f"const memo = p.memoized({rid});")
                self.print("if (memo !== undefined) return memo;")
                self.print("const _mark = p.mark;")
                self.print("let _resmark = p.mark;")
                self.print("let _res: any = null;")
                self.print("while (true) {")
                with self.indent():
                    self.print(f"p.update_memo(_mark, {rid}, _res);")
                    self.print("p.mark = _mark;")
                    self.print(f"const _raw = this.{node.name}_raw();")
                    self.print("if (_raw === null || _raw === undefined || p.mark <= _resmark) break;")
                    self.print("_resmark = p.mark;")
                    self.print("_res = _raw;")
                self.print("}")
                self.print("p.mark = _resmark;")
                self.print("return _res;")
            self.print("}")
            self.print(f"{node.name}_raw(): any {{")
        else:
            self.print(f"{node.name}_rule(): any {{")
        with self.indent():
            self.print("const p = this;")
            without_invalid = node.name.endswith("without_invalid")
            if without_invalid:
                self.print("const _prev_call_invalid = p.call_invalid_rules;")
                self.print("p.call_invalid_rules = false;")
                self.print("try {")
            memoize = node.memo and not node.left_recursive
            if memoize:
                self.print(f"const memo = p.memoized({rid});")
                self.print("if (memo !== undefined) return memo;")
            self.print("let _mark = p.mark;")
            if memoize:
                self.print("const _start_mark = p.mark;")
            uses_extra = any(alt.action and "EXTRA" in alt.action for alt in rhs.alts)
            if uses_extra:
                self.print("p.fill_if_needed();")
                self.print("const _start_lineno = p.tokens[_mark].lineno, _start_col_offset = p.tokens[_mark].col_offset;")
            if is_loop:
                self.print("const _children: any[] = [];")
                self.visit(rhs, is_loop=True, is_gather=is_gather, uses_extra=uses_extra)
                if node.name.startswith("_loop1"):
                    self.print("if (_children.length === 0) return null;")
                if memoize:
                    self.print(f"p.insert_memo(_start_mark, {rid}, _children);")
                self.print("return _children;")
            else:
                self.print("let _res: any = null;")
                self.print("done: {")
                with self.indent():
                    self.visit(rhs, is_loop=False, is_gather=is_gather, uses_extra=uses_extra)
                    self.print("_res = null;")
                self.print("}")
                if memoize:
                    self.print(f"p.insert_memo(_mark, {rid}, _res);")
                self.print("return _res;")
            if without_invalid:
                self.print("} finally { p.call_invalid_rules = _prev_call_invalid; }")
        self.print("}")

    def visit_Rhs(self, node, is_loop, is_gather, uses_extra):
        for alt in node.alts:
            self.visit(alt, is_loop=is_loop, is_gather=is_gather, uses_extra=uses_extra)

    def visit_Alt(self, node, is_loop, is_gather, uses_extra):
        if len(node.items) == 1 and str(node.items[0]).startswith("invalid_"):
            self.print(f"if (p.call_invalid_rules) {{ // {node}")
        else:
            self.print(f"{{ // {node}")
        with self.indent():
            with self.local_variable_context():
                calls = []
                for item in node.items:
                    c = self.callmakervisitor.visit(item)
                    name = item.name if item.name else c.var
                    if name is not None:
                        name = self.dedupe(name)
                    calls.append((name, c))
                vars_ = [n for n, _ in calls if n]
                if vars_:
                    self.print("let " + ", ".join(f"{js_name(v)}: any" + (" = false" if v == "_cut_var" else "")
                                                  for v in vars_) + ";")
                conds = []
                for name, c in calls:
                    expr = c.code if name is None else f"({js_name(name)} = {c.code})"
                    if c.force_true:
                        expr = f"({expr}, true)"
                    conds.append(expr)
                cond = " && ".join(conds) if conds else "true"
                self.print(f"{'while' if is_loop else 'if'} ({cond}) {{")
                with self.indent():
                    if node.action and "EXTRA" in node.action:
                        self.print("const _tok = p.get_last_nonnwhitespace_token();")
                        self.print("const EXTRA = [_start_lineno, _start_col_offset, _tok.end_lineno, _tok.end_col_offset, null] as const;")
                    if node.action:
                        action = translate_action(node.action, vars_)
                        code_only = STRING_LIT.sub('""', action)
                        for ident in re.findall(r"\b(Py_None|Py_True|Py_False|Py_Ellipsis|PyExc_\w+)\b", code_only):
                            self.helpers_used.add(ident)
                        for ident in re.findall(r"(?<![.\w])([A-Za-z_]\w*)\s*\(", code_only):
                            if not ident.startswith("_PyAST_") and ident not in vars_:
                                self.helpers_used.add(ident)
                        for ident in re.findall(r"(?<![.\w])([A-Z][A-Z_]+[A-Z])(?![\w(])", code_only):
                            self.helpers_used.add(ident)
                    elif len(vars_) > 1:
                        if is_gather:
                            action = f"_PyPegen_seq_insert_in_front(p, {js_name(vars_[0])}, {js_name(vars_[1])})"
                        else:
                            action = f"_PyPegen_dummy_name(p, {', '.join(js_name(v) for v in vars_)})"
                    else:
                        action = js_name(vars_[0]) if vars_ else "_PyPegen_dummy_name(p)"
                    if is_loop:
                        self.print(f"_children.push({action});")
                        self.print("_mark = p.mark;")
                    else:
                        self.print(f"_res = {action};")
                        self.print("break done;")
                self.print("}")
                self.print("p.mark = _mark;")
                if "_cut_var" in vars_:
                    self.print("if (_cut_var) return null;")
        self.print("}")


def gen_parser(names, exact, enums):
    from pegen.grammar_parser import GeneratedParser as GrammarParser
    from pegen.tokenizer import Tokenizer
    import tokenize
    path = os.path.join(VENDOR, "python.gram")
    with open(path) as f:
        grammar = GrammarParser(Tokenizer(tokenize.generate_tokens(f.readline))).start()
    import io
    out = io.StringIO()
    gen = TSParserGenerator(grammar, names, exact, out)
    gen.grammar_text = open(path).read()
    gen.enums = enums
    gen.generate(path)
    helpers = sorted(h for h in gen.helpers_used if h not in set(enums) and h not in ("EXTRA",))
    return out.getvalue().replace(gen.helper_marker, "const { " + ", ".join(helpers) + " } = H;"), helpers


def main():
    names, exact = read_tokens()
    open(os.path.join(SRC, "tokens.gen.ts"), "w").write(gen_tokens(names, exact))
    ast_ts, enums = gen_ast()
    open(os.path.join(SRC, "ast.gen.ts"), "w").write(ast_ts)
    parser_ts, helpers = gen_parser(names, exact, enums)
    print(f"{len(helpers)} helper names used by actions:", " ".join(helpers))
    open(os.path.join(SRC, "parser.gen.ts"), "w").write(parser_ts)
    for f in ["tokens.gen.ts", "ast.gen.ts", "parser.gen.ts"]:
        p = os.path.join(SRC, f)
        print(f"{f}: {sum(1 for _ in open(p))} lines, {os.path.getsize(p) // 1024} KB")


if __name__ == "__main__":
    main()
