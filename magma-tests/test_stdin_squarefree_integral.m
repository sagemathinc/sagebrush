R<y> := PolynomialRing(Integers());
f := 3*x^2 + 2*x + 1;
Integral(f);
Integral(x^3/7);
Integral(-x/2 + 3);
Integral(P!5);
Integral(P!0);
Parent(Integral(P!5));
Normalize(f);
Normalize(-3*x^2/7 + 1);
Normalize(P!0);
Normalise(2*x + 4);
Normalize(-2*y + 4);
Normalize(R!(-5));
Normalize(R!0);
Parent(Normalize(-2*y));
SquarefreeFactorization((x - 1)^2*(x + 2)/3);
SquarefreeFactorization((x^2 + 1)*(x - 3)*(x + 5)^3*(x^2 - 2)^3*(2*x + 1)^2);
SquarefreeFactorization(-(x^2 + 1)*(x - 3));
SquarefreeFactorization(x^4);
SquarefreeFactorization(P!(-5));
SquarefreeFactorization(-6*(y + 1)^2*(y^2 - 3));
SquarefreeFactorization(360*y^3*(y - 1));
SquarefreeFactorization(12*(y + 1)^2);
SquarefreeFactorization((2*y + 1)^2*(3*y - 1));
SquarefreeFactorization(2^61*3*y);
SquarefreeFactorization(R!(-8));
SquarefreeFactorization(R!1);
