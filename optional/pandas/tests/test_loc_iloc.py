# .loc and .iloc, getting: scalars, lists, slices and masks, on rows and
# columns (plan-pandas-m1-r1 §0).
import numpy as np
import pandas as pd
from _cases import case

s = pd.Series([10, 20, 30], index=["a", "b", "c"])
df = pd.DataFrame({"x": [1, 2, 3], "y": [1.5, 2.5, 3.5], "z": ["p", "q", "r"]})
dl = pd.DataFrame({"v": [1, 2, 3, 4]}, index=["b", "a", "d", "c"])
ds = pd.DataFrame({"v": [1, 2, 3, 4]}, index=[10, 20, 30, 40])

case("s.iloc-out", lambda: s.iloc[5])
case("s.iloc-neg", lambda: s.iloc[-1])
case("s.iloc-list", lambda: s.iloc[[0, 2]])
case("s.iloc-list-out", lambda: s.iloc[[0, 5]])
case("s.iloc-str", lambda: s.iloc["a"])
case("s.iloc-slice", lambda: s.iloc[1:])
case("s.iloc-mask", lambda: s.iloc[[True, False, True]])
case("s.iloc-mask-series", lambda: s.iloc[s > 15])
case("s.loc-slice-open", lambda: s.loc["b":])
case("s.loc-list-missing", lambda: s.loc[["a", "z"]])
case("s.loc-int-missing", lambda: s.loc[0])
case("s.loc-mask", lambda: s.loc[s > 15])

case("df.loc-row", lambda: df.loc[1])
case("df.loc-cell", lambda: df.loc[1, "y"])
case("df.loc-column", lambda: df.loc[:, "y"])
case("df.loc-slice-list", lambda: df.loc[0:1, ["x", "z"]])
case("df.loc-row-list", lambda: df.loc[1, ["x", "y"]])
case("df.loc-missing", lambda: df.loc[5])
case("df.loc-mask", lambda: df.loc[[True, False, True]])
case("df.loc-mask-col", lambda: df.loc[df.x > 1, "z"])
case("df.loc-col-missing", lambda: df.loc[0, "w"])
case("df.iloc-row", lambda: df.iloc[0])
case("df.iloc-row-types", lambda: [type(v).__name__ for v in df.iloc[0].tolist()])
case("df.iloc-cell", lambda: df.iloc[0, 2])
case("df.iloc-column", lambda: df.iloc[:, 1])
case("df.iloc-lists", lambda: df.iloc[[0, 2], [0, 1]])
case("df.iloc-out", lambda: df.iloc[5])
case("df.iloc-slices", lambda: df.iloc[0:2, 0:2])
case("df.iloc-neg", lambda: df.iloc[-1, -1])
case("df.iloc-col-out", lambda: df.iloc[0, 5])
case("df.iloc-too-many", lambda: df.iloc[0, 0, 0])
case("df.row-int-float", lambda: df[["x", "y"]].loc[0])
case("df.row-int-bool", lambda: pd.DataFrame({"i": [1], "b": [True]}).loc[0])
case("df.row-str", lambda: df[["z"]].loc[0])
case("lbl.slice-unsorted-present", lambda: dl.loc["a":"d"])
case("lbl.slice-unsorted-missing", lambda: dl.loc["a":"e"])
case("lbl.slice-sorted-missing", lambda: ds.loc[15:35])
case("lbl.slice-sorted-open", lambda: ds.loc[:25])
case("lbl.slice-reversed", lambda: ds.loc[30:10])

