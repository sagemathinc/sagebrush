# Series arithmetic: + - * / // % ** with a scalar, a list or array, or another Series (aligned on the sorted union of
# their labels), with NumPy 2's dtype rules (a Python number is a weak scalar), pandas' division by zero (inf, -inf,
# NaN; % NaN), bools (+ is or, * is and), str (+ concatenates, * repeats), unary -, + and abs, and the named methods
# with fill_value.
import operator
import numpy as np
import pandas as pd
from _cases import case


def t(name, f):
    case(name, f)


i = pd.Series([1, -2, 3], name="i")
f = pd.Series([1.5, np.nan, -0.0], name="f")
b = pd.Series([True, False, True], name="b")
s = pd.Series(["a", "b", None], name="s")
z = pd.Series([0, 2, 0])
ops = [("add", operator.add), ("sub", operator.sub), ("mul", operator.mul), ("truediv", operator.truediv),
       ("floordiv", operator.floordiv), ("mod", operator.mod), ("pow", operator.pow)]
for n, op in ops:
    t("i-%s-2" % n, lambda op=op: op(i, 2))
    t("i-%s-2.5" % n, lambda op=op: op(i, 2.5))
    t("2-%s-i" % n, lambda op=op: op(2, i))
    t("i-%s-z" % n, lambda op=op: op(i, z))
    t("f-%s-0" % n, lambda op=op: op(f, 0))
    t("b-%s-b" % n, lambda op=op: op(b, b))
    t("b-%s-1" % n, lambda op=op: op(b, 1))
t("i-pow-neg", lambda: i ** -1)
t("i-pow-big", lambda: pd.Series([2]) ** 70)
t("i-mul-overflow", lambda: pd.Series([2 ** 62]) * 4)
t("s-add-s", lambda: s + s)
t("s-add-str", lambda: s + "x")
t("str-add-s", lambda: "x" + s)
t("s-mul-2", lambda: s * 2)
t("s-sub", lambda: s - s)
t("s-add-1", lambda: s + 1)
t("neg-i", lambda: -i)
t("neg-f", lambda: -f)
t("neg-b", lambda: -b)
t("abs-i", lambda: abs(i))
t("pos-i", lambda: +i)
t("abs-f", lambda: abs(f))
t("name-same", lambda: (i + i).name)
t("name-diff", lambda: (i + f).name)
t("align-diff", lambda: pd.Series([1, 2], index=["a", "b"]) + pd.Series([10, 20], index=["b", "c"]))
t("align-order", lambda: pd.Series([1, 2], index=["b", "a"]) + pd.Series([10, 20], index=["a", "b"]))
t("align-unsorted", lambda: pd.Series([1, 2], index=["z", "a"]) + pd.Series([10], index=["q"]))
t("len-mismatch-list", lambda: i + [1, 2])
t("list", lambda: i + [1, 2, 3])
t("ndarray", lambda: i + np.array([1.5, 2.5, 3.5]))
t("ndarray-int32", lambda: i + np.array([1, 2, 3], dtype=np.int32))
t("np-scalar", lambda: i * np.float32(2.0))
t("np-int8", lambda: i + np.int8(1))
t("u8", lambda: pd.Series([200, 100]).astype("uint8") + 100)
t("u8-neg", lambda: pd.Series([200, 100]).astype("uint8") - 201)
t("u8-u8", lambda: pd.Series([200]).astype("uint8") + pd.Series([100]).astype("uint8"))
t("i8-big", lambda: pd.Series([1]).astype("int8") + 1000)
t("i32-f", lambda: pd.Series([1]).astype("int32") * 1.5)
t("f32-py", lambda: (pd.Series([0.1, 1.0], dtype="float32") * 0.1).tolist())
t("f32-py.dtype", lambda: (pd.Series([0.1, 1.0], dtype="float32") * 0.1).dtype)
t("f32-int", lambda: (pd.Series([0.1, 1.0], dtype="float32") + 16777217).tolist())
t("f32-f64", lambda: (pd.Series([0.1], dtype="float32") + pd.Series([0.1])).dtype)
t("none", lambda: i + None)
t("nan", lambda: i + np.nan)
t("divmod", lambda: divmod(i, 2))
t("mod-neg", lambda: pd.Series([-7, 7]) % 3)
t("fmod-neg", lambda: pd.Series([-7.5, 7.5]) % 2)
t("floordiv-f", lambda: pd.Series([-7.5, 7.5, 1.0]) // 2)
t("floordiv-f0", lambda: pd.Series([-7.5, 0.0, 1.0]) // 0)
t("mod-f0", lambda: pd.Series([-7.5, 0.0, 1.0]) % 0)
t("i-mod-0", lambda: pd.Series([5, -5, 0]) % 0)
t("i-floordiv-0", lambda: pd.Series([5, -5, 0]) // 0)
t("i-truediv-0", lambda: pd.Series([5, -5, 0]) / 0)
t("method-add", lambda: i.add(1))
t("method-radd", lambda: i.radd(1))
t("method-fill", lambda: f.add(pd.Series([1.0, 2.0, np.nan]), fill_value=0))
t("bool-int-mul", lambda: b * 3)
t("bool-float", lambda: b + 0.5)
t("bool-true", lambda: b + True)
t("f32-int-mul", lambda: (pd.Series([0.1, 3.0], dtype="float32") * 2).tolist())
t("f32-int-mul.dtype", lambda: (pd.Series([0.1, 3.0], dtype="float32") * 2).dtype)
t("f32-div-py", lambda: (pd.Series([1.0, 3.0], dtype="float32") / 3).tolist())
t("f32-sub-py", lambda: (pd.Series([1.0], dtype="float32") - 0.1).tolist())
t("f32-np-float64", lambda: (pd.Series([1.0], dtype="float32") * np.float64(0.1)).dtype)
t("f32-f32", lambda: (pd.Series([0.1], dtype="float32") * pd.Series([0.1], dtype="float32")).tolist())
t("int-pow-float.exact", lambda: (pd.Series([2, 3, 10]) ** 0.5).tolist())
t("float-pow.exact", lambda: (pd.Series([1.1, 2.5, 0.3]) ** 3.7).tolist())
t("chain", lambda: (pd.Series([1.0, 2.0]) * 2 + 1) / 4)
t("abs-method", lambda: pd.Series([-1, 2]).abs())
t("sub-fill", lambda: pd.Series([1.0, np.nan, 3.0]).sub(pd.Series([np.nan, np.nan, 1.0]), fill_value=10))
t("rsub", lambda: i.rsub(10))
t("rtruediv", lambda: i.rtruediv(1))
t("divide-alias", lambda: i.divide(4))
t("scalar-fill", lambda: f.add(1, fill_value=0))
# (a negative zero divisor: / is numpy's signed infinity; // follows pandas' mask_zero_div_zero by both signs)
nz = pd.Series([3.0, -3.0, np.inf, 7.5, 0.0])
t("div-neg-zero", lambda: (nz / -0.0).tolist())
t("floordiv-neg-zero", lambda: (nz // -0.0).tolist())
t("rdiv-neg-zero-element", lambda: (2.0 / pd.Series([1.0, -0.0, 0.0])).tolist())
t("rfloordiv-neg-zero-element", lambda: (2.0 // pd.Series([1.0, -0.0, 0.0])).tolist())
t("mod-neg-zero", lambda: (nz % -0.0).tolist())
t("int-div-neg-zero", lambda: (pd.Series([3, -3, 0]) / -0.0).tolist())
t("int-floordiv-neg-zero", lambda: (pd.Series([3, -3, 0]) // -0.0).tolist())
t("float32-div-neg-zero", lambda: (pd.Series([1.0, -1.0], dtype="float32") / -0.0).tolist())
t("float32-floordiv-zero", lambda: pd.Series([1.0, -1.0, 0.0], dtype="float32") // 0)
t("float32-floordiv-zero.dtype", lambda: (pd.Series([1.0, -1.0, 0.0], dtype="float32") // 0).dtype)
t("float32-div-zero.dtype", lambda: (pd.Series([1.0], dtype="float32") / 0).dtype)
t("float32-mod-zero.dtype", lambda: (pd.Series([1.0], dtype="float32") % 0).dtype)
t("float32-floordiv-two.dtype", lambda: (pd.Series([1.0], dtype="float32") // 2).dtype)
t("divmod-zero", lambda: divmod(pd.Series([5, -5, 0, 7]), pd.Series([0, 0, 0, 2])))
t("divmod-float32-zero.dtypes", lambda: [r.dtype for r in divmod(pd.Series([5.0, 1.0], dtype="float32"), 0)])
# (fill_value keeps each column's dtype)
t("float32-fill.exact", lambda: pd.Series([0.1, np.nan], dtype="float32").add(pd.Series([np.nan, 0.4], dtype="float32"), fill_value=0).tolist())
t("float32-fill.dtype", lambda: pd.Series([0.1, np.nan], dtype="float32").add(pd.Series([np.nan, 0.4], dtype="float32"), fill_value=0).dtype)
t("int8-fill", lambda: pd.Series([1, 2]).astype("int8").add(pd.Series([3, 4]).astype("int8"), fill_value=0))
t("int16-fill", lambda: pd.Series([1, 2]).astype("int16").mul(pd.Series([3, 4]).astype("int16"), fill_value=1))
t("uint8-fill", lambda: pd.Series([200, 2]).astype("uint8").add(pd.Series([100, 4]).astype("uint8"), fill_value=0))
t("int-fill-aligned", lambda: pd.Series([1, 2], index=["a", "b"]).add(pd.Series([10], index=["b"]), fill_value=0))
# (float32 Series with other labels align as float32, NaN where a side has none, then compute in float32)
a32 = pd.Series([0.1, 0.2], dtype="float32")
b32 = pd.Series([0.3], index=[1], dtype="float32")
t("float32-misaligned-add.exact", lambda: (a32 + b32).tolist())
t("float32-misaligned-add.dtype", lambda: (a32 + b32).dtype)
t("float32-misaligned-fill.exact", lambda: a32.add(b32, fill_value=0.1).tolist())
t("float32-misaligned-mul-fill.exact", lambda: a32.mul(b32, fill_value=3).tolist())
t("float32-misaligned-float64", lambda: (a32 + pd.Series([0.3], index=[1])).dtype)
t("int8-misaligned-fill", lambda: pd.Series([1, 2]).astype("int8").sub(pd.Series([5], index=[1]).astype("int8"), fill_value=1))
