def rc(text, **kw):
    df = pd.read_csv(io.StringIO(text), **kw)
    return "\n%r\n%s\n%r\n%s" % (df, [(str(k), str(v)) for k, v in df.dtypes.items()], df.index,
                                  [[repr(x) for x in df[c].tolist()] for c in df.columns])


