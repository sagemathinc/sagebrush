"""Generate src/unames.gen.ts: Unicode character names for \\N{...} escapes,
from this Python's unicodedata.  Names of the form PREFIX-<hex code point>
and Hangul syllables are algorithmic and not stored.  Loaded lazily."""
import os, re, sys, unicodedata
out_path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "unames.gen.ts")
names, prefixes = [], set()
for cp in range(0x110000):
    n = unicodedata.name(chr(cp), None)
    if n is None:
        continue
    m = re.fullmatch(r"(.*)-([0-9A-F]{4,6})", n)
    if m and int(m.group(2), 16) == cp:
        prefixes.add(m.group(1) + "-")
        continue
    if n.startswith("HANGUL SYLLABLE "):
        continue
    names.append(f"{n};{cp:x}")
data = "\n".join(names)
with open(out_path, "w") as f:
    f.write(f"// @generated by pyparse/gen/unames.py from unicodedata {unicodedata.unidata_version}; do not edit.\n")
    f.write(f"export const ALGORITHMIC_PREFIXES: string[] = {sorted(prefixes)!r};\n".replace("'", '"'))
    f.write("export const DATA = " + repr(data).replace('"', '\\"').replace("'", '"') + ";\n")
print(f"{len(names)} names, prefixes {sorted(prefixes)}, {os.path.getsize(out_path)//1024} KB")
