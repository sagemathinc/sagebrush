"""Generate src/zeta_rs_cheb.rs: Chebyshev expansions of the Riemann-Siegel coefficients C_0..C_4.

    python3 -I engine/primes/gen/zeta_rs_cheb.py > engine/primes/src/zeta_rs_cheb.rs

In the Riemann-Siegel formula the remainder after the main sum is
(-1)^(m-1) (t / 2 pi)^(-1/4) sum_k C_k(p) (t / 2 pi)^(-k/2), with p the fractional part of
sqrt(t / 2 pi).  The C_k are combinations of the derivatives of
Psi(p) = cos(2 pi (p^2 - p - 1/16)) / cos(2 pi p) (H. M. Edwards, Riemann's Zeta Function, 1974,
section 7.4; W. Gabcke, Neue Herleitung und explizite Restabschaetzung der Riemann-Siegel-Formel,
Goettingen 1979):

    C_0 = Psi
    C_1 = -Psi'''/(96 pi^2)
    C_2 = Psi''/(64 pi^2) + Psi^(6)/(18432 pi^4)
    C_3 = -Psi'/(64 pi^2) - Psi^(5)/(3840 pi^4) - Psi^(9)/(5308416 pi^6)
    C_4 = Psi/(128 pi^2) + 19 Psi^(4)/(24576 pi^4) + 11 Psi^(8)/(5898240 pi^6) + Psi^(12)/(2038431744 pi^8)

Each C_k is entire, so one Chebyshev expansion in x = 2p - 1 on [-1, 1] gives it to about 2^-60.  The
coefficients interpolate C_k at first-kind Chebyshev nodes, with the derivatives of Psi from mpmath at 100
digits; the script checks each expansion at 401 points before writing it.
"""
import mpmath

mpmath.mp.dps = 100
TOL = mpmath.mpf(2) ** -60
PI = mpmath.pi


def psi(p):
    return mpmath.cos(2 * PI * (p * p - p - mpmath.mpf(1) / 16)) / mpmath.cos(2 * PI * p)


def cs(p):
    """C_0(p)..C_4(p)."""
    d = [a * mpmath.factorial(n) for n, a in enumerate(mpmath.taylor(psi, p, 12))]
    return [
        d[0],
        -d[3] / (96 * PI**2),
        d[2] / (64 * PI**2) + d[6] / (18432 * PI**4),
        -d[1] / (64 * PI**2) - d[5] / (3840 * PI**4) - d[9] / (5308416 * PI**6),
        d[0] / (128 * PI**2) + 19 * d[4] / (24576 * PI**4) + 11 * d[8] / (5898240 * PI**6)
        + d[12] / (2038431744 * PI**8),
    ]


def cheb(vals, n):
    c = []
    for j in range(n):
        s = sum(vals[k] * mpmath.cos(PI * j * (k + mpmath.mpf(1) / 2) / n) for k in range(n))
        c.append(2 * s / n)
    c[0] /= 2
    return c


def clenshaw(c, t):
    b1 = b2 = mpmath.mpf(0)
    for cj in reversed(c[1:]):
        b1, b2 = 2 * t * b1 - b2 + cj, b1
    return t * b1 - b2 + c[0]


N = 64
nodes = [mpmath.cos(PI * (k + mpmath.mpf(1) / 2) / N) for k in range(N)]
at_nodes = [cs((x + 1) / 2) for x in nodes]
checks = [mpmath.mpf(2) * k / 400 - 1 for k in range(401)]
# (p = 1/4 and 3/4, x = -1/2 and 1/2, are removable singularities of Psi: check beside them)
checks = [x + mpmath.mpf(10) ** -30 if abs(abs(x) - mpmath.mpf(1) / 2) < mpmath.mpf(10) ** -40 else x for x in checks]
at_checks = [cs((x + 1) / 2) for x in checks]
out = []
for k in range(5):
    c = cheb([v[k] for v in at_nodes], N)
    worst = max(abs(clenshaw(c, x) - v[k]) for x, v in zip(checks, at_checks))
    assert worst < TOL, (k, worst)
    while abs(c[-1]) < mpmath.mpf(2) ** -66:
        c.pop()
    out.append((c, worst))

print("// Generated by engine/primes/gen/zeta_rs_cheb.py from mpmath %s at 100 digits; do not edit." % mpmath.__version__)
print("// Chebyshev expansions of the Riemann-Siegel coefficients: C_k(p) = sum c_j T_j(2p - 1) on 0 <= p <= 1.")
print("// Each interpolates C_k at %d Chebyshev nodes and is within 2^-60 of it at 401 points of [0, 1]." % N)
print("pub(crate) const RS_CHEB: [&[f64]; 5] = [")
for k, (c, worst) in enumerate(out):
    print("    // C_%d: %d terms, worst %s" % (k, len(c), mpmath.nstr(worst, 3)))
    print("    &[")
    for cj in c:
        # (C_0, C_2 and C_4 are even about p = 1/2 and C_1, C_3 odd: the other coefficients are 0 but for the
        #  numerical derivatives' noise, about 10^-100)
        print("        %r," % (float(cj) if abs(cj) > mpmath.mpf(2) ** -200 else 0.0))
    print("    ],")
print("];")
