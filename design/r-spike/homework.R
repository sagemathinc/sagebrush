data <- mtcars
summary(data$mpg)
table(data$cyl)
tapply(data$mpg, data$cyl, mean)
t.test(mpg ~ am, data = data)
fit <- lm(mpg ~ wt + hp, data = data)
summary(fit)
predict(fit, data.frame(wt = 3, hp = 120))
