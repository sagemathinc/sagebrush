# The parts of os that only some programs use, loaded the first time one of them is (os's attribute getters,
# src/runtime/modules.ts), never at startup: os.PathLike and os.walk are CPython 3.14's Lib/os.py, copied unchanged
# (PSF License; see cdn/LICENSE-CPython.txt); os.scandir and os.DirEntry are Sagebrush's, over os.listdir and os.stat
# (this runtime has no directory handles), with CPython's interface: a DirEntry's name and path, is_dir, is_file,
# is_symlink, stat and inode, each stat cached as CPython's are; scandir an iterator and a context manager.
import abc
import sys
from os import fspath, path, listdir, stat as _stat, lstat as _lstat
from _collections_abc import _check_methods
from types import GenericAlias
import stat as st


_walk_symlinks_as_files = object()

def walk(top, topdown=True, onerror=None, followlinks=False):
    """Directory tree generator.

    For each directory in the directory tree rooted at top (including top
    itself, but excluding '.' and '..'), yields a 3-tuple

        dirpath, dirnames, filenames

    dirpath is a string, the path to the directory.  dirnames is a list of
    the names of the subdirectories in dirpath (including symlinks to directories,
    and excluding '.' and '..').
    filenames is a list of the names of the non-directory files in dirpath.
    Note that the names in the lists are just names, with no path components.
    To get a full path (which begins with top) to a file or directory in
    dirpath, do os.path.join(dirpath, name).

    If optional arg 'topdown' is true or not specified, the triple for a
    directory is generated before the triples for any of its subdirectories
    (directories are generated top down).  If topdown is false, the triple
    for a directory is generated after the triples for all of its
    subdirectories (directories are generated bottom up).

    When topdown is true, the caller can modify the dirnames list in-place
    (e.g., via del or slice assignment), and walk will only recurse into the
    subdirectories whose names remain in dirnames; this can be used to prune the
    search, or to impose a specific order of visiting.  Modifying dirnames when
    topdown is false has no effect on the behavior of os.walk(), since the
    directories in dirnames have already been generated by the time dirnames
    itself is generated. No matter the value of topdown, the list of
    subdirectories is retrieved before the tuples for the directory and its
    subdirectories are generated.

    By default errors from the os.scandir() call are ignored.  If
    optional arg 'onerror' is specified, it should be a function; it
    will be called with one argument, an OSError instance.  It can
    report the error to continue with the walk, or raise the exception
    to abort the walk.  Note that the filename is available as the
    filename attribute of the exception object.

    By default, os.walk does not follow symbolic links to subdirectories on
    systems that support them.  In order to get this functionality, set the
    optional argument 'followlinks' to true.

    Caution:  if you pass a relative pathname for top, don't change the
    current working directory between resumptions of walk.  walk never
    changes the current directory, and assumes that the client doesn't
    either.

    Example:

    import os
    from os.path import join, getsize
    for root, dirs, files in os.walk('python/Lib/xml'):
        print(root, "consumes ")
        print(sum(getsize(join(root, name)) for name in files), end=" ")
        print("bytes in", len(files), "non-directory files")
        if '__pycache__' in dirs:
            dirs.remove('__pycache__')  # don't visit __pycache__ directories

    """
    sys.audit("os.walk", top, topdown, onerror, followlinks)

    stack = [fspath(top)]
    islink, join = path.islink, path.join
    while stack:
        top = stack.pop()
        if isinstance(top, tuple):
            yield top
            continue

        dirs = []
        nondirs = []
        walk_dirs = []

        # We may not have read permission for top, in which case we can't
        # get a list of the files the directory contains.
        # We suppress the exception here, rather than blow up for a
        # minor reason when (say) a thousand readable directories are still
        # left to visit.
        try:
            with scandir(top) as entries:
                for entry in entries:
                    try:
                        if followlinks is _walk_symlinks_as_files:
                            is_dir = entry.is_dir(follow_symlinks=False) and not entry.is_junction()
                        else:
                            is_dir = entry.is_dir()
                    except OSError:
                        # If is_dir() raises an OSError, consider the entry not to
                        # be a directory, same behaviour as os.path.isdir().
                        is_dir = False

                    if is_dir:
                        dirs.append(entry.name)
                    else:
                        nondirs.append(entry.name)

                    if not topdown and is_dir:
                        # Bottom-up: traverse into sub-directory, but exclude
                        # symlinks to directories if followlinks is False
                        if followlinks:
                            walk_into = True
                        else:
                            try:
                                is_symlink = entry.is_symlink()
                            except OSError:
                                # If is_symlink() raises an OSError, consider the
                                # entry not to be a symbolic link, same behaviour
                                # as os.path.islink().
                                is_symlink = False
                            walk_into = not is_symlink

                        if walk_into:
                            walk_dirs.append(entry.path)
        except OSError as error:
            if onerror is not None:
                onerror(error)
            continue

        if topdown:
            # Yield before sub-directory traversal if going top down
            yield top, dirs, nondirs
            # Traverse into sub-directories
            for dirname in reversed(dirs):
                new_path = join(top, dirname)
                # bpo-23605: os.path.islink() is used instead of caching
                # entry.is_symlink() result during the loop on os.scandir() because
                # the caller can replace the directory entry during the "yield"
                # above.
                if followlinks or not islink(new_path):
                    stack.append(new_path)
        else:
            # Yield after sub-directory traversal if going bottom up
            stack.append((top, dirs, nondirs))
            # Traverse into sub-directories
            for new_path in reversed(walk_dirs):
                stack.append(new_path)



class PathLike(abc.ABC):

    """Abstract base class for implementing the file system path protocol."""

    __slots__ = ()

    @abc.abstractmethod
    def __fspath__(self):
        """Return the file system path representation of the object."""
        raise NotImplementedError

    @classmethod
    def __subclasshook__(cls, subclass):
        if cls is PathLike:
            return _check_methods(subclass, '__fspath__')
        return NotImplemented

    __class_getitem__ = classmethod(GenericAlias)


class DirEntry:
    """os.DirEntry: an entry of os.scandir's directory (made by scandir only, as CPython's)."""

    __slots__ = ("name", "path", "_stat", "_lstat")

    def __init__(self, *args, **kwargs):
        raise TypeError("cannot create 'posix.DirEntry' instances")

    @classmethod
    def _make(cls, dirpath, name):
        e = object.__new__(cls)
        e.name = name
        e.path = path.join(dirpath, name)
        e._stat = None
        e._lstat = None
        return e

    def stat(self, *, follow_symlinks=True):
        if follow_symlinks:
            if self._stat is None:
                self._stat = _stat(self.path)
            return self._stat
        if self._lstat is None:
            self._lstat = _lstat(self.path)
        return self._lstat

    def _test(self, kind, follow_symlinks):
        try:
            return kind(self.stat(follow_symlinks=follow_symlinks).st_mode)
        except FileNotFoundError:
            return False

    def is_dir(self, *, follow_symlinks=True):
        return self._test(st.S_ISDIR, follow_symlinks)

    def is_file(self, *, follow_symlinks=True):
        return self._test(st.S_ISREG, follow_symlinks)

    def is_symlink(self):
        return self._test(st.S_ISLNK, False)

    def is_junction(self):
        return False

    def inode(self):
        return self.stat(follow_symlinks=False).st_ino

    def __fspath__(self):
        return self.path

    def __repr__(self):
        return f"<DirEntry {self.name!r}>"

    __class_getitem__ = classmethod(GenericAlias)


DirEntry.__module__ = "posix"


class _ScandirIterator:
    __slots__ = ("_entries", "_closed")

    def __init__(self, entries):
        self._entries = iter(entries)
        self._closed = False

    def __iter__(self):
        return self

    def __next__(self):
        if self._closed:
            raise StopIteration
        return next(self._entries)

    def close(self):
        self._closed = True

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self.close()
        return False


_ScandirIterator.__module__ = "posix"
_ScandirIterator.__qualname__ = _ScandirIterator.__name__ = "ScandirIterator"


def scandir(path="."):
    """os.scandir: an iterator of DirEntry objects for the directory `path`."""
    if path is None:
        path = "."
    p = fspath(path)
    names = listdir(p)
    if isinstance(p, bytes):
        names = [n.encode("utf-8", "surrogateescape") if isinstance(n, str) else n for n in names]
    return _ScandirIterator([DirEntry._make(p, n) for n in names])


def fsencode(filename):
    """Encode filename (an os.PathLike, bytes, or str) to the filesystem encoding (UTF-8) with 'surrogateescape';
    return bytes unchanged (CPython's os.fsencode, its POSIX case)."""
    filename = fspath(filename)
    if isinstance(filename, str):
        return filename.encode("utf-8", "surrogateescape")
    return filename


def fsdecode(filename):
    """Decode filename (an os.PathLike, bytes, or str) from the filesystem encoding (UTF-8) with 'surrogateescape';
    return str unchanged (CPython's os.fsdecode, its POSIX case)."""
    filename = fspath(filename)
    if isinstance(filename, bytes):
        return filename.decode("utf-8", "surrogateescape")
    return filename
