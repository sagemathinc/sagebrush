"""Generate src/li_cheb.rs: Chebyshev expansions of f(L) = L e^{-L} Ei(L) on [2, 45].

    python3 -I engine/primes/gen/li_cheb.py > engine/primes/src/li_cheb.rs

li(x) = (x / L) f(L) with L = log x.  In this form a rounding of L moves li by
about one part in L^2 of that rounding, instead of L times it in Ei(L).
f is analytic for Re L > 0 and close to 1 on [2, 45], so a few Chebyshev
terms on each of five intervals give it to about 2^-60.  The coefficients are
the Chebyshev interpolation coefficients at the first-kind nodes, computed
with mpmath at 60 digits; the script checks each expansion at 2001 points of
its interval before writing it.
"""
import mpmath

mpmath.mp.dps = 60
INTERVALS = [(2, 4), (4, 8), (8, 16), (16, 32), (32, 45)]
TOL = mpmath.mpf(2) ** -62


def f(L):
    return L * mpmath.exp(-L) * mpmath.ei(L)


def cheb(a, b, n):
    """The coefficients c_0..c_{n-1} of the degree n-1 interpolant at Chebyshev nodes."""
    a, b = mpmath.mpf(a), mpmath.mpf(b)
    nodes = [mpmath.cos(mpmath.pi * (k + mpmath.mpf(1) / 2) / n) for k in range(n)]
    vals = [f((b - a) / 2 * t + (b + a) / 2) for t in nodes]
    c = []
    for j in range(n):
        s = sum(vals[k] * mpmath.cos(mpmath.pi * j * (k + mpmath.mpf(1) / 2) / n) for k in range(n))
        c.append(2 * s / n)
    c[0] /= 2
    return c


def clenshaw(c, t):
    b1 = b2 = mpmath.mpf(0)
    for cj in reversed(c[1:]):
        b1, b2 = 2 * t * b1 - b2 + cj, b1
    return t * b1 - b2 + c[0]


out = []
for a, b in INTERVALS:
    n = 8
    while True:
        c = cheb(a, b, n)
        worst = max(abs(clenshaw(c, mpmath.mpf(2) * k / 2000 - 1)
                        - f((mpmath.mpf(b) - a) / 2 * (mpmath.mpf(2) * k / 2000 - 1) + (mpmath.mpf(b) + a) / 2))
                    for k in range(2001))
        if worst < TOL:
            break
        n += 2
    # (trailing coefficients below 2^-64 change nothing in a double sum)
    while abs(c[-1]) < mpmath.mpf(2) ** -64:
        c.pop()
    out.append((a, b, c, worst))

print("// Generated by engine/primes/gen/li_cheb.py from mpmath %s at 60 digits; do not edit." % mpmath.__version__)
print("// Chebyshev expansions of f(L) = L e^{-L} Ei(L): on [a, b], f(L) = sum c_j T_j(t),")
print("// t = (2L - a - b) / (b - a).  Each interpolates f at Chebyshev nodes and is within")
print("// 2^-62 of f at 2001 points of its interval.")
print("pub(crate) const LI_CHEB: [(f64, f64, &[f64]); %d] = [" % len(out))
for a, b, c, worst in out:
    print("    // [%s, %s]: %d terms, worst %s" % (a, b, len(c), mpmath.nstr(worst, 3)))
    print("    (%s.0, %s.0, &[" % (a, b))
    for cj in c:
        print("        %r," % float(cj))
    print("    ]),")
print("];")
