"""How Python mode's catalog examples run (catalog/SCHEMA.md, Examples:
the entries are catalog/python/*.json), and a summary for each other public
function of the libraries Sagebrush provides, which has no entry yet
(lib/_python_docsearch.py lists them in the index).

Examples run one after another, each in a fresh namespace that has
PRELUDE's imports, and show what a Python prompt would: the value of a last
line that is an expression (its repr), after what the code prints.
scripts/catalog-run.py runs them on every runtime and compares the outputs.
"""

import io as _io
import sys as _sys

# what every example may use without importing it
PRELUDE = "import numpy as np\nimport math, cmath, itertools, functools, collections, random, bisect, heapq\nfrom fractions import Fraction"


# the most an example may print (catalog/SCHEMA.md: examples are short); past
# it the example fails, rather than holding all it prints
LIMIT = 1 << 20


class _Capped(_io.StringIO):
    def write(self, s):
        if self.tell() + len(s) > LIMIT:
            raise RuntimeError("the example printed more than %d characters" % LIMIT)
        return super().write(s)


def run(code, ns=None):
    """What the example prints at a Python prompt: its output, then the repr
    of its last line when that is an expression (and not None)."""
    if ns is None:
        ns = {}
        exec(PRELUDE, ns)
    lines = code.split("\n")
    last = lines[-1]
    try:
        compile(last, "<example>", "eval")
        is_expr = not last.startswith((" ", "\t"))
    except SyntaxError:
        is_expr = False
    body = "\n".join(lines[:-1] if is_expr else lines)
    buf = _Capped()
    old = _sys.stdout
    _sys.stdout = buf
    try:
        if body.strip():
            exec(compile(body, "<example>", "exec"), ns)
        if is_expr:
            v = eval(compile(last, "<example>", "eval"), ns)
            if v is not None:
                print(repr(v))
    except Exception as err:
        # (what it printed, then the traceback's last line: catalog/SCHEMA.md)
        print("%s: %s" % (type(err).__name__, err))
    finally:
        _sys.stdout = old
    return buf.getvalue()


