//! Hilbert modular forms of weight 2 over any real quadratic field F =
//! Q(sqrt d) (engine/hmf: definite.rs, defnew.rs) in the JSON ABI, for
//! lib/_sage_hmf.py. The field is given by the squarefree d > 1 ("d").
//! Elements of O_F = Z[w] (w = (1 + sqrt d)/2 if d = 1 mod 4, sqrt d
//! otherwise) are pairs [a, b] of integers meaning a + b w, and ideals are
//! given by generators [[a, b], ...]. The newspaces of the last few (field,
//! level) pairs are kept, so that a session's calls at one level build the
//! class set and the spaces once. The hmfq_weight_* calls take a weight
//! [k1, k2] != [2, 2] ("weight": k1 at sqrt d -> -sqrt d, k2 at sqrt d ->
//! +sqrt d; engine/hmf: defweight.rs, defweightnew.rs) and give polynomials
//! over O_F as lists of coefficients [a, b] (strings), constant term first.

use sagebrush_hmf::defnew::Newspaces;
use sagebrush_hmf::defweightnew::{WeightNewspaces, WeightOrbits};
use sagebrush_hmf::gpoly::QPoly;
use sagebrush_hmf::weight::Weight;
use sagebrush_hmf::quatalg::{MaximalOrder, QuatAlg};
use sagebrush_hmf::rqf::{QElt, QIdeal, QPrime, QuadField};
use serde_json::{json, Value};
use std::cell::RefCell;
use std::rc::Rc;

const CACHE: usize = 4;

/// The largest discriminant handled: class sets beyond it would exceed the
/// limits of classes.rs anyway (its mass bound refuses them early).
const MAX_DISC: i64 = 1 << 20;

type Key = (i64, (i128, i128, i128));

thread_local! {
    static NEWSPACES: RefCell<Vec<(Key, Rc<Newspaces>)>> = RefCell::new(vec![]);
    static WEIGHT_NEWSPACES: RefCell<Vec<((Key, Weight), Rc<WeightNewspaces>)>> = RefCell::new(vec![]);
}

fn field(v: &Value) -> Result<QuadField, String> {
    let d = v.get("d").and_then(Value::as_i64).ok_or("missing integer argument 'd': F = Q(sqrt d), d > 1 squarefree")?;
    // the discriminant is d or 4 d >= d: refuse before any arithmetic on d
    // (daybreak HARD-3AE-1)
    if d > MAX_DISC {
        return Err(format!("d = {} gives a discriminant above 2^20 (unsupported)", d));
    }
    let f = QuadField::new(d)?;
    if f.disc > MAX_DISC {
        return Err(format!("the discriminant {} of F is above 2^20 (unsupported)", f.disc));
    }
    Ok(f)
}

fn elt(v: &Value) -> Result<QElt, String> {
    let a = v.get(0).and_then(Value::as_i64);
    let b = v.get(1).and_then(Value::as_i64);
    match (a, b, v.as_array().map(|x| x.len())) {
        (Some(a), Some(b), Some(2)) => Ok(QElt::new(a, b)),
        _ => Err("an element of O_F is a pair [a, b] of integers (a + b w)".into()),
    }
}

fn ideal(f: &QuadField, v: &Value, k: &str) -> Result<QIdeal, String> {
    let gens = v.get(k).and_then(Value::as_array).ok_or_else(|| format!("missing argument '{}': generators [[a, b], ...]", k))?;
    if gens.is_empty() || gens.len() > 64 {
        return Err("an ideal is given by 1 to 64 generators".into());
    }
    let gens: Vec<QElt> = gens.iter().map(elt).collect::<Result<_, _>>()?;
    f.ideal(&gens)
}

/// A prime for a Hecke operator: its norm is limited (the lattice searches
/// grow with it, within their work budget).
fn prime(f: &QuadField, v: &Value, k: &str) -> Result<QPrime, String> {
    let i = ideal(f, v, k)?;
    match f.factor(&i)?.as_slice() {
        [(p, 1)] if p.norm() <= 1_000_000 => Ok(*p),
        [(p, 1)] => Err(format!("the norm {} of the prime must be at most 10^6", p.norm())),
        _ => Err("not a prime ideal".into()),
    }
}

fn hnf_json(i: &QIdeal) -> Value {
    let (a, b, c) = i.hnf();
    json!([a.to_string(), b.to_string(), c.to_string()])
}

fn prime_json(p: &QPrime) -> Value {
    let (a, b, c) = p.ideal().hnf();
    // the ideal is Z a + Z (b + c w), generated by a and b + c w
    json!({ "p": p.p(), "norm": p.norm().to_string(), "hnf": hnf_json(&p.ideal()),
            "gens": [[a.to_string(), "0"], [b.to_string(), c.to_string()]] })
}

fn ideal_json(f: &QuadField, i: &QIdeal) -> Result<Value, String> {
    let (a, b, c) = i.hnf();
    Ok(json!({ "norm": i.norm().to_string(), "hnf": hnf_json(i),
               "gens": [[a.to_string(), "0"], [b.to_string(), c.to_string()]],
               "factors": f.factor(i)?.iter().map(|(p, e)| json!([prime_json(p), e])).collect::<Vec<_>>() }))
}

fn newspaces(f: &QuadField, n: &QIdeal) -> Result<Rc<Newspaces>, String> {
    let key = (f.d, n.hnf());
    if let Some(x) = NEWSPACES.with(|c| c.borrow().iter().find(|(h, _)| *h == key).map(|(_, x)| x.clone())) {
        return Ok(x);
    }
    let o = MaximalOrder::new(&QuatAlg::unramified(*f)?)?;
    let x = Rc::new(Newspaces::new(&o, n)?);
    NEWSPACES.with(|c| {
        let mut c = c.borrow_mut();
        if c.len() >= CACHE {
            c.remove(0);
        }
        c.push((key, x.clone()));
    });
    Ok(x)
}

/// The weight [k1, k2] in "weight", other than [2, 2] (as hmf.rs).
fn weight(v: &Value) -> Result<Weight, String> {
    let k = v.get("weight").and_then(Value::as_array).ok_or("missing argument 'weight': [k1, k2]")?;
    let k: Vec<u32> = k.iter().map(|x| x.as_u64().filter(|&x| x <= 1000).map(|x| x as u32).ok_or("weights are integers")).collect::<Result<_, _>>()?;
    match k.as_slice() {
        [2, 2] => Err("weight [2, 2] is the hmfq_* space without a weight".into()),
        &[a, b] => Weight::new(a, b),
        _ => Err("a weight is [k1, k2]".into()),
    }
}

fn weight_newspaces(f: &QuadField, n: &QIdeal, w: Weight) -> Result<Rc<WeightNewspaces>, String> {
    let key = ((f.d, n.hnf()), w);
    if let Some(x) = WEIGHT_NEWSPACES.with(|c| c.borrow().iter().find(|(h, _)| *h == key).map(|(_, x)| x.clone())) {
        return Ok(x);
    }
    let o = MaximalOrder::new(&QuatAlg::unramified(*f)?)?;
    let x = Rc::new(WeightNewspaces::new(&o, n, w)?);
    WEIGHT_NEWSPACES.with(|c| {
        let mut c = c.borrow_mut();
        if c.len() >= CACHE {
            c.remove(0);
        }
        c.push((key, x.clone()));
    });
    Ok(x)
}

fn qpoly_json(f: &QPoly) -> Value {
    json!(f.iter().map(|c| json!([c.a.to_string(), c.b.to_string()])).collect::<Vec<_>>())
}

fn bound(v: &Value, max: u64) -> Result<i64, String> {
    let b = v.get("bound").and_then(Value::as_u64).ok_or("missing integer argument 'bound'")?;
    if b > max {
        return Err(format!("bound must be at most {}", max));
    }
    Ok(b as i64)
}

/// The largest n for hmfq_squarefree (the Sage wrapper refuses larger
/// discriminants before calling).
const MAX_SQUAREFREE: u64 = 1 << 62;

/// An index argument (an orbit number), as a usize without truncation on
/// 32-bit targets (daybreak API-3AE-5).
fn index(v: &Value, k: &str) -> Result<usize, String> {
    let x = v.get(k).and_then(Value::as_u64).ok_or_else(|| format!("missing integer argument '{}'", k))?;
    usize::try_from(x).map_err(|_| format!("{} {} out of range", k, x))
}

pub fn dispatch(name: &str, v: &Value) -> Result<Value, String> {
    // n = m^2 d with d squarefree, for the Sage wrapper's discriminants, by
    // the bounded factorization of field.rs (HARD-3AE-1)
    if name == "hmfq_squarefree" {
        let n = v.get("n").and_then(Value::as_u64).filter(|&n| n >= 1 && n <= MAX_SQUAREFREE).ok_or("missing argument 'n': an integer 1 <= n <= 2^62")?;
        let (mut d, mut m) = (1u64, 1u64);
        for (p, e) in sagebrush_hmf::field::factor_u64(n)? {
            for _ in 0..e / 2 {
                m *= p;
            }
            if e % 2 == 1 {
                d *= p;
            }
        }
        return Ok(json!({ "d": d, "m": m }));
    }
    let f = field(v)?;
    match name {
        // the field: discriminant, w^2 = t w + n, class numbers, fundamental unit
        "hmfq_field" => {
            let cg = f.class_group();
            Ok(json!({ "disc": f.disc, "t": f.t, "n": f.n, "h": cg.h(), "narrow_h": cg.narrow_h(),
                       "eps": [cg.eps.a.to_string(), cg.eps.b.to_string()], "eps_norm": cg.eps_norm }))
        }
        // the ideal generated by "gens": its Hermite normal form, norm and factorization
        "hmfq_ideal" => ideal_json(&f, &ideal(&f, v, "gens")?),
        // the primes of norm <= bound, sorted by norm
        "hmfq_primes" => Ok(json!(f.primes_of_bounded_norm(bound(v, 100_000)?)?.iter().map(prime_json).collect::<Vec<_>>())),
        "hmfq_dimension" => {
            let ns = newspaces(&f, &ideal(&f, v, "level")?)?;
            let cg = ns.top().classes().class_group();
            Ok(json!({ "dim": ns.top().dimension(), "cusp_dim": ns.top().cusp_dimension(),
                       "classes": ns.top().classes().len(), "h": cg.h(), "narrow_h": cg.narrow_h() }))
        }
        // T_P (U_P if P divides the level) on M_2^B(N), rows sparse
        "hmfq_hecke_matrix" => {
            let ns = newspaces(&f, &ideal(&f, v, "level")?)?;
            let t = ns.hecke(&ns.level, &prime(&f, v, "p")?)?;
            Ok(json!(t.rows.iter().map(|r| r.iter().map(|&(j, n)| json!([j, n])).collect::<Vec<_>>()).collect::<Vec<_>>()))
        }
        "hmfq_new_dimension" => Ok(json!(newspaces(&f, &ideal(&f, v, "level")?)?.new_dimension()?)),
        "hmfq_newform_orbits" => {
            let ns = newspaces(&f, &ideal(&f, v, "level")?)?;
            let o = ns.newform_orbits()?;
            Ok(json!({ "op": o.op.iter().map(|(p, c)| json!([prime_json(p), c])).collect::<Vec<_>>(),
                       "orbits": o.orbits.iter().map(|g| g.iter().map(|c| c.to_string()).collect::<Vec<_>>()).collect::<Vec<_>>() }))
        }
        // the Hecke eigenvalues of the k-th orbit at the primes of norm <=
        // bound: polynomials in a root of the orbit's polynomial, num / den
        "hmfq_newform_eigenvalues" => {
            let ns = newspaces(&f, &ideal(&f, v, "level")?)?;
            let k = index(v, "orbit")?;
            let b = bound(v, 10_000)?;
            let o = ns.newform_orbits()?;
            if k >= o.orbits.len() {
                return Err(format!("orbit {} out of range: there are {}", k, o.orbits.len()));
            }
            let e = ns.orbit_eigenspace(&o, k)?;
            let mut aps = vec![];
            for p in f.primes_of_bounded_norm(b)? {
                let a = ns.eigenvalue(&e, &p)?;
                aps.push(json!([prime_json(&p), a.num.iter().map(|c| c.to_string()).collect::<Vec<_>>(), a.den.to_string()]));
            }
            Ok(json!({ "g": e.g.iter().map(|c| c.to_string()).collect::<Vec<_>>(), "aplist": aps }))
        }
        // weight [k1, k2] != [2, 2]: S_k(N) and its new subspace
        "hmfq_weight_dimension" => {
            let ns = weight_newspaces(&f, &ideal(&f, v, "level")?, weight(v)?)?;
            Ok(json!({ "dim": ns.top().dimension(), "new_dim": ns.new_dimension()? }))
        }
        // the characteristic polynomial over O_F of T_P (U_P if P | N) on S_k(N)
        "hmfq_weight_hecke_charpoly" => {
            let ns = weight_newspaces(&f, &ideal(&f, v, "level")?, weight(v)?)?;
            Ok(qpoly_json(&ns.hecke_charpoly(&prime(&f, v, "p")?)?))
        }
        // the Galois orbits over F of the newforms: the separating operator
        // and its characteristic polynomial over O_F on each orbit
        "hmfq_weight_newform_orbits" => {
            let ns = weight_newspaces(&f, &ideal(&f, v, "level")?, weight(v)?)?;
            let o = ns.newform_orbits()?;
            Ok(json!({ "op": o.op.iter().map(|(p, c)| json!([prime_json(p), c])).collect::<Vec<_>>(),
                       "orbits": o.orbits.iter().map(qpoly_json).collect::<Vec<_>>() }))
        }
        // for the k-th orbit and the primes of norm <= bound: the
        // characteristic polynomial over O_F of a_P on the orbit, and h with
        // a_P = h(theta)/g'(theta)
        "hmfq_weight_newform_eigenvalues" => {
            let ns = weight_newspaces(&f, &ideal(&f, v, "level")?, weight(v)?)?;
            let k = index(v, "orbit")?;
            let b = bound(v, 10_000)?;
            let o = ns.newform_orbits()?;
            if k >= o.orbits.len() {
                return Err(format!("orbit {} out of range: there are {}", k, o.orbits.len()));
            }
            let one = WeightOrbits { op: o.op.clone(), orbits: vec![o.orbits[k].clone()] };
            let primes = f.primes_of_bounded_norm(b)?;
            let (cps, hs) = ns.orbit_data(&one, &primes)?;
            Ok(json!({ "g": qpoly_json(&o.orbits[k]),
                       "aplist": primes.iter().zip(cps[0].iter().zip(&hs[0])).map(|(p, (c, h))| json!([prime_json(p), qpoly_json(c), qpoly_json(h)])).collect::<Vec<_>>() }))
        }
        _ => Err(format!("unknown function {}", name)),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn call(s: &str) -> Result<Value, String> {
        let v: Value = serde_json::from_str(s).unwrap();
        dispatch(v["fn"].as_str().unwrap(), &v)
    }

    #[test]
    fn hmfq_calls() {
        let r = call(r#"{"fn":"hmfq_dimension","d":106,"level":[[1,0]]}"#).unwrap();
        assert_eq!((r["dim"].as_u64(), r["cusp_dim"].as_u64()), (Some(52), Some(50)));
        let r = call(r#"{"fn":"hmfq_new_dimension","d":10,"level":[[5,0],[0,1]]}"#).unwrap();
        assert_eq!(r.as_u64(), Some(4));
        let r = call(r#"{"fn":"hmfq_newform_eigenvalues","d":10,"level":[[5,0],[0,1]],"orbit":0,"bound":5}"#).unwrap();
        assert_eq!(r["g"].as_array().unwrap().len(), 5);
        // refusals
        assert!(call(r#"{"fn":"hmfq_dimension","d":4,"level":[[1,0]]}"#).is_err());
        assert!(call(r#"{"fn":"hmfq_dimension","d":10001,"level":[[1,0]]}"#).is_err());
        assert!(call(r#"{"fn":"hmfq_hecke_matrix","d":10,"level":[[1,0]],"p":[[6,0]]}"#).is_err());
        assert!(call(r#"{"fn":"hmfq_ideal","d":10,"gens":[]}"#).is_err());
        assert!(call(r#"{"fn":"hmfq_ideal","d":10,"gens":[[0,0]]}"#).is_err());
        assert!(call(r#"{"fn":"hmfq_ideal","d":10,"gens":[[1,2,3]]}"#).is_err());
        assert!(call(r#"{"fn":"hmfq_newform_eigenvalues","d":10,"level":[[5,0],[0,1]],"orbit":7,"bound":5}"#).is_err());
        assert!(call(r#"{"fn":"hmfq_primes","d":10,"bound":1000000}"#).is_err());
    }

    #[test]
    fn hmfq_limits() {
        // HARD-3AE-1: d is checked before any arithmetic, and squarefree
        // parts come from the bounded factorization
        let t = std::time::Instant::now();
        assert!(call(r#"{"fn":"hmfq_field","d":9223372036854775807}"#).unwrap_err().contains("above 2^20"));
        assert!(call(r#"{"fn":"hmfq_field","d":1048583}"#).unwrap_err().contains("above 2^20"));
        let r = call(r#"{"fn":"hmfq_squarefree","n":20000060000045}"#).unwrap();
        assert_eq!((r["d"].as_u64(), r["m"].as_u64()), (Some(5), Some(2000003)));
        let r = call(r#"{"fn":"hmfq_squarefree","n":4611686014132420609}"#).unwrap();
        assert_eq!((r["d"].as_u64(), r["m"].as_u64()), (Some(1), Some(2147483647)));
        assert!(call(r#"{"fn":"hmfq_squarefree","n":0}"#).is_err());
        assert!(call(r#"{"fn":"hmfq_squarefree","n":4611686018427387905}"#).is_err());
        // HARD-3AE-2: the report's ideal
        let r = call(r#"{"fn":"hmfq_ideal","d":5,"gens":[[1073741789,0]]}"#).unwrap();
        assert_eq!(r["factors"].as_array().unwrap().len(), 2);
        // HARD-3AE-3 and HARD-3AE-4: refused before any space is built
        assert!(call(r#"{"fn":"hmfq_dimension","d":5,"level":[[16384,0]]}"#).unwrap_err().contains("unsupported"));
        assert!(call(r#"{"fn":"hmfq_dimension","d":5,"level":[[363660,0],[230736,2508]]}"#).unwrap_err().contains("unsupported"));
        assert!(t.elapsed().as_secs_f64() < 2.0, "{:?}", t.elapsed());
        // API-3AE-5: an orbit number is not truncated
        assert!(call(r#"{"fn":"hmfq_newform_eigenvalues","d":10,"level":[[5,0],[0,1]],"orbit":4294967296,"bound":5}"#).is_err());
    }

    #[test]
    fn hmfq_weight_calls() {
        // Q(sqrt 3), level 2 (norm 4), weight (3, 3): dimension 1, T at (7) is -94
        let r = call(r#"{"fn":"hmfq_weight_dimension","d":3,"level":[[2,0]],"weight":[3,3]}"#).unwrap();
        assert_eq!((r["dim"].as_u64(), r["new_dim"].as_u64()), (Some(1), Some(1)));
        let r = call(r#"{"fn":"hmfq_weight_hecke_charpoly","d":3,"level":[[2,0]],"weight":[3,3],"p":[[7,0]]}"#).unwrap();
        assert_eq!(r, serde_json::json!([["94", "0"], ["1", "0"]]));
        let r = call(r#"{"fn":"hmfq_weight_newform_eigenvalues","d":3,"level":[[2,0]],"weight":[3,3],"orbit":0,"bound":7}"#).unwrap();
        assert_eq!(r["g"].as_array().unwrap().len(), 2);
        // refusals
        assert!(call(r#"{"fn":"hmfq_weight_dimension","d":3,"level":[[2,0]],"weight":[2,2]}"#).is_err());
        assert!(call(r#"{"fn":"hmfq_weight_dimension","d":3,"level":[[2,0]],"weight":[2,3]}"#).is_err());
        assert!(call(r#"{"fn":"hmfq_weight_dimension","d":3,"level":[[2,0]],"weight":[2,300]}"#).is_err());
        assert!(call(r#"{"fn":"hmfq_weight_dimension","d":3,"level":[[2,0]]}"#).is_err());
        assert!(call(r#"{"fn":"hmfq_weight_newform_eigenvalues","d":3,"level":[[2,0]],"weight":[3,3],"orbit":1,"bound":7}"#).is_err());
    }
}
