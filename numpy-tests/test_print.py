print(repr(np.zeros((0,))), repr(np.zeros((0, 3))), repr(np.zeros((2, 0), dtype=int)), repr(np.array([], dtype=np.int32)), str(np.zeros(0)))
np.set_printoptions(precision=3)
print(repr(np.array([np.pi, np.e])), np.array([1 / 3]))
np.set_printoptions(precision=8, suppress=True)
print(repr(np.array([1e-10, 1.0])), repr(np.array([1e-5, 123.5])))
