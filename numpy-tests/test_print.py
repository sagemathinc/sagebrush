print(repr(np.arange(24.0).reshape(2, 3, 4) / 7))
print(repr(np.array([1e-10, 1.0, 1e10])), repr(np.array([1.5e-5, 2.0])), repr(np.array([1e8, 1])), repr(np.array([123456789.0, 1.5])))
print(repr(np.array([0.1, 1e-4])), repr(np.array([-1e-20, 0, 1e20])), repr(np.array([1e300, -1e-300])), repr(np.array([5e-324, 1.0])))
print(repr(np.array([np.nan, np.inf, -np.inf])), repr(np.array([1.0, np.nan])), repr(np.array([-1.5, np.inf])), repr(np.array([1e-9, np.nan])))
print(repr(np.array([-0.0, 0.0])), repr(np.array([0.0])), repr(np.array([-1.0])), repr(np.array([123.456, -0.001])))
