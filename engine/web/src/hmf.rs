//! Hilbert modular forms over Q(sqrt 5) (engine/hmf) in the JSON ABI, for
//! lib/_sage_hmf.py. Elements of O_F = Z[w], w^2 = w + 1, are pairs [a, b]
//! meaning a + b w; ideals are given by generators [[a, b], ...]. Spaces are
//! kept for the last few levels, so that a session's calls at one level
//! build it once.

use sagebrush_hmf::field::{primes_of_bounded_norm, Elt, Hnf, Ideal, Prime};
use sagebrush_hmf::newspace::{aplists, HeckeOp, Newspaces};
use sagebrush_hmf::Space;
use serde_json::{json, Value};
use std::cell::RefCell;
use std::rc::Rc;

const CACHE: usize = 4;

thread_local! {
    static SPACES: RefCell<Vec<(Hnf, Rc<Space>)>> = RefCell::new(vec![]);
    static NEWSPACES: RefCell<Vec<(Hnf, Rc<Newspaces>)>> = RefCell::new(vec![]);
}

fn elt(v: &Value) -> Result<Elt, String> {
    let a = v.get(0).and_then(Value::as_i64);
    let b = v.get(1).and_then(Value::as_i64);
    match (a, b) {
        (Some(a), Some(b)) => Ok(Elt::new(a, b)),
        _ => Err("an element of O_F is a pair [a, b] of integers (a + b w)".into()),
    }
}

fn ideal(v: &Value, k: &str) -> Result<Ideal, String> {
    let gens = v.get(k).and_then(Value::as_array).ok_or_else(|| format!("missing argument '{}': generators [[a, b], ...]", k))?;
    let gens: Vec<Elt> = gens.iter().map(elt).collect::<Result<_, _>>()?;
    Ideal::from_gens(&gens)
}

/// A prime for a Hecke operator: Theta(p) costs about N(p)/60 lattice
/// searches, so N(p) is limited.
fn prime(v: &Value, k: &str) -> Result<Prime, String> {
    let i = ideal(v, k)?;
    match i.factors.as_slice() {
        [(p, 1)] if p.norm <= 10_000_000 => Ok(*p),
        [(p, 1)] => Err(format!("the norm {} of the prime must be at most 10^7", p.norm)),
        _ => Err(format!("({}) is not a prime ideal", i.gen)),
    }
}

fn e(x: Elt) -> Value {
    json!([x.a, x.b])
}

fn prime_json(p: &Prime) -> Value {
    json!({ "p": p.p, "norm": p.norm, "gen": e(p.gen) })
}

fn ideal_json(i: &Ideal) -> Value {
    json!({ "gen": e(i.gen), "norm": i.norm(), "hnf": [i.hnf.a, i.hnf.b, i.hnf.c],
            "factors": i.factors.iter().map(|(p, k)| json!([prime_json(p), k])).collect::<Vec<_>>() })
}

fn cached<T>(cache: &'static std::thread::LocalKey<RefCell<Vec<(Hnf, Rc<T>)>>>, n: &Ideal, make: impl FnOnce() -> Result<T, String>) -> Result<Rc<T>, String> {
    if let Some(x) = cache.with(|c| c.borrow().iter().find(|(h, _)| *h == n.hnf).map(|(_, x)| x.clone())) {
        return Ok(x);
    }
    let x = Rc::new(make()?);
    cache.with(|c| {
        let mut c = c.borrow_mut();
        if c.len() >= CACHE {
            c.remove(0);
        }
        c.push((n.hnf, x.clone()));
    });
    Ok(x)
}

fn space(n: &Ideal) -> Result<Rc<Space>, String> {
    cached(&SPACES, n, || Space::from_ideal(n.clone()))
}

fn newspaces(n: &Ideal) -> Result<Rc<Newspaces>, String> {
    cached(&NEWSPACES, n, || Newspaces::new(n.clone()))
}

fn rows_json(rows: &[Vec<(u32, u32)>]) -> Value {
    json!(rows.iter().map(|r| r.iter().map(|&(j, n)| json!([j, n])).collect::<Vec<_>>()).collect::<Vec<_>>())
}

fn op_json(op: &HeckeOp) -> Value {
    json!(op.iter().map(|(p, c)| json!([prime_json(p), c])).collect::<Vec<_>>())
}

pub fn dispatch(f: &str, v: &Value) -> Result<Value, String> {
    match f {
        // the ideal generated by "gens", factored, with its totally positive generator
        "hmf_ideal" => Ok(ideal_json(&ideal(v, "gens")?)),
        // the primes of norm <= bound, sorted by norm
        "hmf_primes" => {
            let b = v.get("bound").and_then(Value::as_u64).ok_or("missing integer argument 'bound'")?;
            if b > 10_000_000 {
                return Err("bound must be at most 10^7".into());
            }
            Ok(json!(primes_of_bounded_norm(b).iter().map(prime_json).collect::<Vec<_>>()))
        }
        "hmf_dimension" => {
            let s = space(&ideal(v, "level")?)?;
            Ok(json!({ "dim": s.dimension(), "cusp_dim": s.cusp_dimension() }))
        }
        "hmf_hecke_matrix" => {
            let s = space(&ideal(v, "level")?)?;
            Ok(rows_json(&s.hecke_matrix(&prime(v, "p")?)?.rows))
        }
        "hmf_hecke_rows" => {
            let s = space(&ideal(v, "level")?)?;
            let rows: Vec<usize> = v.get("rows").and_then(Value::as_array).ok_or("missing argument 'rows'")?.iter().map(|x| x.as_u64().map(|x| x as usize).ok_or("rows are indices")).collect::<Result<_, _>>()?;
            Ok(rows_json(&s.hecke_rows(&prime(v, "p")?, &rows)?))
        }
        "hmf_degeneracy" => {
            let s = space(&ideal(v, "level")?)?;
            let d = s.degeneracy(&prime(v, "p")?)?;
            Ok(json!({ "lower": ideal_json(&d.lower.level), "lower_dim": d.lower.dimension(), "map": d.map }))
        }
        "hmf_new_dimension" => Ok(json!(newspaces(&ideal(v, "level")?)?.new_dimension())),
        "hmf_newform_orbits" => {
            let ns = newspaces(&ideal(v, "level")?)?;
            let o = ns.newform_orbits()?;
            Ok(json!({ "op": op_json(&o.op),
                       "orbits": o.orbits.iter().map(|g| g.iter().map(|c| c.to_string()).collect::<Vec<_>>()).collect::<Vec<_>>() }))
        }
        "hmf_rational_newforms" => {
            let ns = newspaces(&ideal(v, "level")?)?;
            let bound = v.get("bound").and_then(Value::as_u64).unwrap_or(100);
            if bound > 1_000_000 {
                return Err("bound must be at most 10^6".into());
            }
            let o = ns.newform_orbits()?;
            let forms = ns.rational_newforms_of(&o)?;
            let lists = aplists(ns.top(), &forms, bound)?;
            Ok(json!({ "op": op_json(&o.op),
                       "forms": forms.iter().zip(&lists).map(|(f, l)| json!({
                           "op_eigenvalue": f.op_eigenvalue,
                           "aplist": l.iter().map(|(p, a)| json!([prime_json(p), a])).collect::<Vec<_>>() })).collect::<Vec<_>>() }))
        }
        _ => Err(format!("unknown function {}", f)),
    }
}

#[cfg(test)]
mod tests {
    use crate::call;

    #[test]
    fn hmf_calls() {
        let r = call(r#"{"fn":"hmf_dimension","level":[[-2,5]]}"#);
        assert_eq!(r, r#"{"ok":{"cusp_dim":1,"dim":2}}"#);
        let r = call(r#"{"fn":"hmf_hecke_matrix","level":[[-2,5]],"p":[[2,0]]}"#);
        assert!(r.starts_with(r#"{"ok":[["#), "{}", r);
        let r = call(r#"{"fn":"hmf_rational_newforms","level":[[-2,5]],"bound":12}"#);
        assert!(r.contains(r#""op_eigenvalue""#), "{}", r);
        let r = call(r#"{"fn":"hmf_hecke_matrix","level":[[-2,5]],"p":[[6,0]]}"#);
        assert!(r.contains("not a prime ideal"), "{}", r);
        let r = call(r#"{"fn":"hmf_ideal","gens":[[0,0]]}"#);
        assert!(r.contains("error"), "{}", r);
    }
}
