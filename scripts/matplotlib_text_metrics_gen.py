r"""Writes lib/matplotlib/_text_metrics.py: how wide and tall matplotlib's Agg renderer measures text in its default
font (DejaVu Sans), for tight_layout (lib/matplotlib/_tight_layout.py).

The units of text are the printable ASCII characters, the minus sign, and the ligatures matplotlib 3.11 draws
(ffi, ffl, ff, fi, fl, taken longest first). For each, at each of the named font sizes (xx-small to xx-large of the
default 10 pt) and 100 dpi: the advance Agg gives it (FreeType's autohinted advance, in 1/64 pixel) and its ink's top
and bottom (the hinted control box, 1/64 pixel); and the kerning Agg puts between two of them (1/64 pixel, measured for
every pair: its rounding isn't a formula of the font's values alone). Also the font's own kerning values between two
characters (font units, for other sizes) and its typographic ascent, descent and line gap (OS/2), which matplotlib 3.11
uses as each line's least height. And, at each size, the mathtext $\mathdefault{10^{k}}$ that a log axis labels its
ticks with, for k from -30 to 30 (as its mathtext renderer lays it out).

Run with a CPython that has matplotlib 3.11 and fontTools (the metrics are FreeType's, as matplotlib's wheels build it):
    python scripts/matplotlib_text_metrics_gen.py > lib/matplotlib/_text_metrics.py
"""
import matplotlib

matplotlib.use("agg")
from fontTools.ttLib import TTFont  # noqa: E402
from matplotlib.backends.backend_agg import get_hinting_flag  # noqa: E402
from matplotlib.font_manager import FontProperties, findfont, get_font  # noqa: E402

DPI = 100
SIZES = [5.79, 6.94, 8.33, 10.0, 12.0, 14.4, 17.28]  # font_scalings of 10 pt, as FontProperties.get_size_in_points
CHARS = "".join(chr(c) for c in range(32, 127)) + "−"
LIGATURES = ["ffi", "ffl", "ff", "fi", "fl"]
UNITS = list(CHARS) + LIGATURES


def units(s):
    out, i = [], 0
    while i < len(s):
        lig = next((L for L in LIGATURES if s.startswith(L, i)), None)
        out.append(lig or s[i])
        i += len(lig) if lig else 1
    return out


path = findfont(FontProperties())
tt = TTFont(path)
cmap = tt.getBestCmap()
kern = {}
for t in tt["kern"].kernTables:
    kern.update(t.kernTable)
names = {cmap[ord(c)]: c for c in CHARS}
flags = get_hinting_flag()

sizes = []
for size in SIZES:
    size = FontProperties(size=size).get_size_in_points()
    font = get_font(path)
    font.clear()
    font.set_size(size, DPI)

    def width(s):
        font.set_text(s, 0, flags=flags)
        return font.get_width_height()[0]

    rows = []
    for u in UNITS:
        font.set_text(u, 0, flags=flags)
        w, h = font.get_width_height()
        d = font.get_descent()
        rows.append((w, h - d, d))
    kerned = {}
    for i, a in enumerate(UNITS):
        for j, b in enumerate(UNITS):
            if units(a + b) != [a, b]:
                continue
            k = width(a + b) - rows[i][0] - rows[j][0]
            if k:
                kerned[(a, b)] = k
    sizes.append((size, rows, kerned))

import matplotlib.pyplot as plt  # noqa: E402

renderer = plt.figure().canvas.get_renderer()
powers = []
for size in SIZES:
    fp = FontProperties(size=size)
    row = []
    for k in range(-30, 31):
        w, h, d = renderer.get_text_width_height_descent(r"$\mathdefault{10^{%d}}$" % k, fp, ismath=True)
        v = [w * 64, (h - d) * 64, d * 64]
        assert all(x == int(x) for x in v), (size, k, v)
        row.append(tuple(int(x) for x in v))
    powers.append((fp.get_size_in_points(), row))

pairs = sorted((names[a] + names[b], v) for (a, b), v in kern.items() if a in names and b in names and v)

def kern_formula(a, b, size):
    """The kerning Agg puts between two characters, as near as a formula of the font's value comes (the table keeps
    only where Agg's differs)."""
    return round(kern_units.get(a + b, 0) * size * DPI / 72 * 64 / tt["head"].unitsPerEm)


kern_units = dict(pairs)
compact = lambda xs: "[" + ",".join(str(x) for x in xs) + "]"
print('r"""Text metrics of matplotlib\'s default font, DejaVu Sans, as its Agg renderer measures them (generated by')
print("scripts/matplotlib_text_metrics_gen.py: do not edit). UNITS: what text is measured in, its characters and the")
print("ligatures LIGATURES (longest first). SIZES: for each font size in points at %d dpi, each unit's advance in pixels," % DPI)
print("its ascent and descent in 1/64 pixel, and the kerning (1/64 pixel) between the two units where Agg's isn't")
print("round(KERN * pixels per em * 64 / UPM). KERN: the font's kerning between two characters, in font units; UPM,")
print("TYPO_ASCENT, TYPO_DESCENT, TYPO_LINEGAP: its units per em and OS/2 typographic ascent, descent and line gap.")
print("POWERS: for each size, the ascent and descent (1/64 pixel) and each width (pixels) of mathtext's")
print('$\\mathdefault{10^{k}}$ for k from -30 to 30."""')
print()
print("DPI = %d" % DPI)
print("UPM = %d" % tt["head"].unitsPerEm)
print("TYPO_ASCENT = %d" % tt["OS/2"].sTypoAscender)
print("TYPO_DESCENT = %d" % tt["OS/2"].sTypoDescender)
print("TYPO_LINEGAP = %d" % tt["OS/2"].sTypoLineGap)
print("LIGATURES = %r" % (LIGATURES,))
print("UNITS = list(%r) + LIGATURES" % CHARS)
print("SIZES = {")
for size, rows, kerned in sizes:
    assert all(r[0] % 64 == 0 for r in rows), size
    differs = {}
    for a in UNITS:
        for b in UNITS:
            if units(a + b) != [a, b]:
                continue
            got = kerned.get((a, b), 0)
            if got != kern_formula(a, b, size):
                differs[(a, b)] = got
    print("    %r: (%s," % (size, compact(r[0] // 64 for r in rows)))
    print("        %s," % compact(r[1] for r in rows))
    print("        %s," % compact(r[2] for r in rows))
    print("        %r)," % (dict(sorted(differs.items())),))
print("}")
print("KERN = {")
for i in range(0, len(pairs), 8):
    print("    " + " ".join("%r: %d," % p for p in pairs[i:i + 8]))
print("}")
print("POWERS = {")
for size, row in powers:
    (a, d), = {(r[1], r[2]) for r in row}
    assert all(r[0] % 64 == 0 for r in row)
    print("    %r: (%d, %d, %s)," % (size, a, d, compact(r[0] // 64 for r in row)))
print("}")
