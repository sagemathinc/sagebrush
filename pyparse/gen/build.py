"""Generate the TypeScript Python parser from CPython's own sources.

    python3 gen/build.py

Inputs (vendor/cpython, from CPython v3.14.4):
  Tokens       -> src/tokens.gen.ts   token numbers and operator tables
  Python.asdl  -> src/ast.gen.ts      AST node constructors (_PyAST_*)
  python.gram  -> src/parser.gen.ts   the PEG parser, with CPython's own
                                      actions translated from C to TypeScript

The generator mirrors pegen's C back end (Tools/peg_generator/pegen/
c_generator.py): same rule functions, memoization, left recursion, the
`invalid_*` rules gated on a second pass, and default actions.
"""

