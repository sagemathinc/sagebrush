//! Hilbert modular forms of weight 2 over any real quadratic field F =
//! Q(sqrt d) (engine/hmf: definite.rs, defnew.rs) in the JSON ABI, for
//! lib/_sage_hmf.py. The field is given by the squarefree d > 1 ("d").
//! Elements of O_F = Z[w] (w = (1 + sqrt d)/2 if d = 1 mod 4, sqrt d
//! otherwise) are pairs [a, b] of integers meaning a + b w, and ideals are
//! given by generators [[a, b], ...]. The newspaces of the last few (field,
//! level) pairs are kept, so that a session's calls at one level build the
//! class set and the spaces once.

use sagebrush_hmf::defnew::Newspaces;
use sagebrush_hmf::quatalg::{MaximalOrder, QuatAlg};
use sagebrush_hmf::rqf::{QElt, QIdeal, QPrime, QuadField};
use serde_json::{json, Value};
use std::cell::RefCell;
use std::rc::Rc;

const CACHE: usize = 4;

/// The largest discriminant handled: class sets beyond it would exceed the
/// limits of classes.rs anyway (its mass bound refuses them early).
const MAX_DISC: i64 = 1 << 20;

type Key = (i64, (i128, i128, i128));

thread_local! {
    static NEWSPACES: RefCell<Vec<(Key, Rc<Newspaces>)>> = RefCell::new(vec![]);
}

fn field(v: &Value) -> Result<QuadField, String> {
    let d = v.get("d").and_then(Value::as_i64).ok_or("missing integer argument 'd': F = Q(sqrt d), d > 1 squarefree")?;
    let f = QuadField::new(d)?;
    if f.disc > MAX_DISC {
        return Err(format!("the discriminant {} of F is above 2^20 (unsupported)", f.disc));
    }
    Ok(f)
}

fn elt(v: &Value) -> Result<QElt, String> {
    let a = v.get(0).and_then(Value::as_i64);
    let b = v.get(1).and_then(Value::as_i64);
    match (a, b, v.as_array().map(|x| x.len())) {
        (Some(a), Some(b), Some(2)) => Ok(QElt::new(a, b)),
        _ => Err("an element of O_F is a pair [a, b] of integers (a + b w)".into()),
    }
}

fn ideal(f: &QuadField, v: &Value, k: &str) -> Result<QIdeal, String> {
    let gens = v.get(k).and_then(Value::as_array).ok_or_else(|| format!("missing argument '{}': generators [[a, b], ...]", k))?;
    if gens.is_empty() || gens.len() > 64 {
        return Err("an ideal is given by 1 to 64 generators".into());
    }
    let gens: Vec<QElt> = gens.iter().map(elt).collect::<Result<_, _>>()?;
    f.ideal(&gens)
}

/// A prime for a Hecke operator: its norm is limited (the lattice searches
/// grow with it, within their work budget).
fn prime(f: &QuadField, v: &Value, k: &str) -> Result<QPrime, String> {
    let i = ideal(f, v, k)?;
    match f.factor(&i)?.as_slice() {
        [(p, 1)] if p.norm <= 1_000_000 => Ok(*p),
        [(p, 1)] => Err(format!("the norm {} of the prime must be at most 10^6", p.norm)),
        _ => Err("not a prime ideal".into()),
    }
}

fn hnf_json(i: &QIdeal) -> Value {
    let (a, b, c) = i.hnf();
    json!([a.to_string(), b.to_string(), c.to_string()])
}

fn prime_json(p: &QPrime) -> Value {
    let (a, b, c) = p.ideal.hnf();
    // the ideal is Z a + Z (b + c w), generated by a and b + c w
    json!({ "p": p.p, "norm": p.norm.to_string(), "hnf": hnf_json(&p.ideal),
            "gens": [[a.to_string(), "0"], [b.to_string(), c.to_string()]] })
}

fn ideal_json(f: &QuadField, i: &QIdeal) -> Result<Value, String> {
    let (a, b, c) = i.hnf();
    Ok(json!({ "norm": i.norm().to_string(), "hnf": hnf_json(i),
               "gens": [[a.to_string(), "0"], [b.to_string(), c.to_string()]],
               "factors": f.factor(i)?.iter().map(|(p, e)| json!([prime_json(p), e])).collect::<Vec<_>>() }))
}

fn newspaces(f: &QuadField, n: &QIdeal) -> Result<Rc<Newspaces>, String> {
    let key = (f.d, n.hnf());
    if let Some(x) = NEWSPACES.with(|c| c.borrow().iter().find(|(h, _)| *h == key).map(|(_, x)| x.clone())) {
        return Ok(x);
    }
    let o = MaximalOrder::new(&QuatAlg::unramified(*f)?)?;
    let x = Rc::new(Newspaces::new(&o, n)?);
    NEWSPACES.with(|c| {
        let mut c = c.borrow_mut();
        if c.len() >= CACHE {
            c.remove(0);
        }
        c.push((key, x.clone()));
    });
    Ok(x)
}

fn bound(v: &Value, max: u64) -> Result<i64, String> {
    let b = v.get("bound").and_then(Value::as_u64).ok_or("missing integer argument 'bound'")?;
    if b > max {
        return Err(format!("bound must be at most {}", max));
    }
    Ok(b as i64)
}

pub fn dispatch(name: &str, v: &Value) -> Result<Value, String> {
    let f = field(v)?;
    match name {
        // the field: discriminant, w^2 = t w + n, class numbers, fundamental unit
        "hmfq_field" => {
            let cg = f.class_group();
            Ok(json!({ "disc": f.disc, "t": f.t, "n": f.n, "h": cg.h(), "narrow_h": cg.narrow_h(),
                       "eps": [cg.eps.a.to_string(), cg.eps.b.to_string()], "eps_norm": cg.eps_norm }))
        }
        // the ideal generated by "gens": its Hermite normal form, norm and factorization
        "hmfq_ideal" => ideal_json(&f, &ideal(&f, v, "gens")?),
        // the primes of norm <= bound, sorted by norm
        "hmfq_primes" => Ok(json!(f.primes_of_bounded_norm(bound(v, 100_000)?)?.iter().map(prime_json).collect::<Vec<_>>())),
        "hmfq_dimension" => {
            let ns = newspaces(&f, &ideal(&f, v, "level")?)?;
            let cg = ns.top().classes().class_group();
            Ok(json!({ "dim": ns.top().dimension(), "cusp_dim": ns.top().cusp_dimension(),
                       "classes": ns.top().classes().len(), "h": cg.h(), "narrow_h": cg.narrow_h() }))
        }
        // T_P (U_P if P divides the level) on M_2^B(N), rows sparse
        "hmfq_hecke_matrix" => {
            let ns = newspaces(&f, &ideal(&f, v, "level")?)?;
            let t = ns.hecke(&ns.level, &prime(&f, v, "p")?)?;
            Ok(json!(t.rows.iter().map(|r| r.iter().map(|&(j, n)| json!([j, n])).collect::<Vec<_>>()).collect::<Vec<_>>()))
        }
        "hmfq_new_dimension" => Ok(json!(newspaces(&f, &ideal(&f, v, "level")?)?.new_dimension()?)),
        "hmfq_newform_orbits" => {
            let ns = newspaces(&f, &ideal(&f, v, "level")?)?;
            let o = ns.newform_orbits()?;
            Ok(json!({ "op": o.op.iter().map(|(p, c)| json!([prime_json(p), c])).collect::<Vec<_>>(),
                       "orbits": o.orbits.iter().map(|g| g.iter().map(|c| c.to_string()).collect::<Vec<_>>()).collect::<Vec<_>>() }))
        }
        // the Hecke eigenvalues of the k-th orbit at the primes of norm <=
        // bound: polynomials in a root of the orbit's polynomial, num / den
        "hmfq_newform_eigenvalues" => {
            let ns = newspaces(&f, &ideal(&f, v, "level")?)?;
            let k = v.get("orbit").and_then(Value::as_u64).ok_or("missing integer argument 'orbit'")? as usize;
            let b = bound(v, 10_000)?;
            let o = ns.newform_orbits()?;
            if k >= o.orbits.len() {
                return Err(format!("orbit {} out of range: there are {}", k, o.orbits.len()));
            }
            let e = ns.orbit_eigenspace(&o, k)?;
            let mut aps = vec![];
            for p in f.primes_of_bounded_norm(b)? {
                let a = ns.eigenvalue(&e, &p)?;
                aps.push(json!([prime_json(&p), a.num.iter().map(|c| c.to_string()).collect::<Vec<_>>(), a.den.to_string()]));
            }
            Ok(json!({ "g": e.g.iter().map(|c| c.to_string()).collect::<Vec<_>>(), "aplist": aps }))
        }
        _ => Err(format!("unknown function {}", name)),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn call(s: &str) -> Result<Value, String> {
        let v: Value = serde_json::from_str(s).unwrap();
        dispatch(v["fn"].as_str().unwrap(), &v)
    }

    #[test]
    fn hmfq_calls() {
        let r = call(r#"{"fn":"hmfq_dimension","d":106,"level":[[1,0]]}"#).unwrap();
        assert_eq!((r["dim"].as_u64(), r["cusp_dim"].as_u64()), (Some(52), Some(50)));
        let r = call(r#"{"fn":"hmfq_new_dimension","d":10,"level":[[5,0],[0,1]]}"#).unwrap();
        assert_eq!(r.as_u64(), Some(4));
        let r = call(r#"{"fn":"hmfq_newform_eigenvalues","d":10,"level":[[5,0],[0,1]],"orbit":0,"bound":5}"#).unwrap();
        assert_eq!(r["g"].as_array().unwrap().len(), 5);
        // refusals
        assert!(call(r#"{"fn":"hmfq_dimension","d":4,"level":[[1,0]]}"#).is_err());
        assert!(call(r#"{"fn":"hmfq_dimension","d":10001,"level":[[1,0]]}"#).is_err());
        assert!(call(r#"{"fn":"hmfq_hecke_matrix","d":10,"level":[[1,0]],"p":[[6,0]]}"#).is_err());
        assert!(call(r#"{"fn":"hmfq_ideal","d":10,"gens":[]}"#).is_err());
        assert!(call(r#"{"fn":"hmfq_ideal","d":10,"gens":[[0,0]]}"#).is_err());
        assert!(call(r#"{"fn":"hmfq_ideal","d":10,"gens":[[1,2,3]]}"#).is_err());
        assert!(call(r#"{"fn":"hmfq_newform_eigenvalues","d":10,"level":[[5,0],[0,1]],"orbit":7,"bound":5}"#).is_err());
        assert!(call(r#"{"fn":"hmfq_primes","d":10,"bound":1000000}"#).is_err());
    }
}
