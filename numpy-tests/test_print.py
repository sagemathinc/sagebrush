print(repr(np.array([1 + 1j, 2.5 - 3j, -1j])), repr(np.array([1e-5 + 1j, 1])), np.array([1j, 2]), repr(np.array([np.nan + 1j])))
print(repr(np.array([1, 2], dtype=np.int16)), repr(np.arange(30, dtype=np.int32)), repr(np.array([[1.5, 2], [3, 4]], dtype=np.float32)))
print(repr(np.arange(20, dtype=np.uint8).reshape(4, 5)), repr(np.ones(25, dtype=np.int8)))
