# describe: count, mean, std (ddof=1), min, numpy's linear percentiles and max of numeric columns (float64); count,
# unique, top and freq of the others; a frame's columns side by side. The exact values are printed too.
import numpy as np
import pandas as pd
from _cases import case, dtypes

df = pd.DataFrame({"name": ["cat", "ant", None, "ant"], "legs": [4, 6, 4, 8], "w": [4.5, np.nan, 1.0, 2.0],
                   "ok": [True, False, True, True]})
rng = np.random.RandomState(0)
big = pd.Series(rng.standard_normal(1000) * 3.7 + 0.1)
gaps = pd.Series([0.1 * k if k % 7 else np.nan for k in range(300)])

case("frame", lambda: df.describe())
case("frame.exact", lambda: df.describe().to_numpy().tolist())
case("frame.index", lambda: df.describe().index)
case("frame.all", lambda: df.describe(include="all"))
case("frame.all.dtypes", lambda: dtypes(df.describe(include="all")))
case("frame.object", lambda: df.describe(include="object"))
case("frame.str", lambda: df.describe(include=["str"]))
case("frame.number", lambda: df.describe(include=[np.number]))
case("frame.exclude-number", lambda: df.describe(exclude=[np.number]))
case("frame.include-bool", lambda: df.describe(include="bool"))
case("frame.include-float", lambda: df.describe(include=["float64"]))
case("frame.bool-only", lambda: df[["ok"]].describe())
case("frame.str-only", lambda: df[["name"]].describe())
case("frame.str-only.dtypes", lambda: dtypes(df[["name"]].describe()))
case("frame.ints-only-categorical", lambda: dtypes(pd.DataFrame({"o": pd.Series([1, 1, 2], dtype=object)}).describe()))
case("frame.percentiles", lambda: df.describe(percentiles=[0.1, 0.5, 0.9]))
case("frame.percentiles-no-median", lambda: df.describe(percentiles=[0.1]))
case("frame.percentiles-fine", lambda: df.describe(percentiles=[0.333, 0.0001]))
case("frame.percentiles-mixed", lambda: df.describe(percentiles=[0.25, 0.333, 0.75]).index)
case("frame.percentiles-ends", lambda: df.describe(percentiles=[0, 1]).index)
case("frame.percentiles-empty", lambda: df.describe(percentiles=[]).index)
case("frame.percentiles-out", lambda: df.describe(percentiles=[1.5]))
case("frame.percentiles-dup", lambda: df.describe(percentiles=[0.5, 0.5]))
case("frame.no-columns", lambda: pd.DataFrame().describe())
case("frame.no-match", lambda: pd.DataFrame({"s": ["a"]}).describe(include=[np.number]))
case("frame.all-and-exclude", lambda: df.describe(include="all", exclude=["bool"]))
case("frame.uint8", lambda: df.astype({"legs": "uint8"}).describe())
case("series.int", lambda: df["legs"].describe())
case("series.float", lambda: df["w"].describe())
case("series.float.exact", lambda: df["w"].describe().tolist())
case("series.str", lambda: df["name"].describe())
case("series.bool", lambda: df["ok"].describe())
case("series.str-ties", lambda: pd.Series(["b", "a", "a", "b"]).describe())
case("series.object", lambda: pd.Series([1, "a", "a"], dtype=object).describe())
case("series.object-ints", lambda: pd.Series([1, 1, 2], dtype=object).describe())
case("series.empty", lambda: pd.Series([], dtype=float).describe())
case("series.empty-object", lambda: pd.Series([], dtype=object).describe())
case("series.all-missing", lambda: pd.Series([np.nan, np.nan]).describe())
case("series.all-missing-str", lambda: pd.Series([None, None], dtype="str").describe())
case("series.one", lambda: pd.Series([3.0]).describe())
case("series.negative-zero", lambda: pd.Series([-0.0, 0.0, 1.0]).describe().tolist())
case("series.big.exact", lambda: big.describe().tolist())
case("series.big-ints.exact", lambda: pd.Series(rng.randint(-1000, 1000, 1000)).describe().tolist())
case("series.gaps.exact", lambda: gaps.describe().tolist())
case("series.gaps-percentiles.exact", lambda: gaps.describe(percentiles=[0.01, 0.1, 0.333, 0.99]).tolist())
case("series.include-warns", lambda: df["w"].describe(include="all").tolist())
case("original-kept", lambda: (df.describe(), df)[1])
