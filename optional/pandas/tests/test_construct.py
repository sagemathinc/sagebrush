# Constructors: Series, DataFrame, Index and RangeIndex (plan-pandas-m1-r1 §0).
import numpy as np
import pandas as pd
from _cases import case, dtypes

case("series.list", lambda: pd.Series([1, 2, 3]))
case("series.floats-none", lambda: pd.Series([1.5, None, 3]))
case("series.str-none", lambda: pd.Series(["a", None, "ccc"]))
case("series.bool-name", lambda: pd.Series([True, False], name="x"))
case("series.mixed", lambda: pd.Series(["a", 1]))
case("series.empty-float", lambda: pd.Series([], dtype=float))
case("series.empty", lambda: pd.Series())
case("series.dict", lambda: pd.Series({"a": 1, "b": 2}))
case("series.dict-index", lambda: pd.Series({"a": 1, "b": 2}, index=["b", "c"]))
case("series.scalar-index", lambda: pd.Series(5, index=["a", "b"]))
case("series.scalar", lambda: pd.Series(5))
case("series.length-mismatch", lambda: pd.Series([1, 2, 3], index=["a", "b"]))
case("series.ndarray", lambda: pd.Series(np.arange(3)))
case("series.ndarray-float", lambda: pd.Series(np.linspace(0, 1, 3), index=["p", "q", "r"]))
case("series.from-series", lambda: pd.Series(pd.Series([1, 2], name="s")))
case("series.from-series-index", lambda: pd.Series(pd.Series([1, 2], index=["a", "b"]), index=["b", "z"]))
case("series.range", lambda: pd.Series(range(4)))
case("series.tuple", lambda: pd.Series((1.5, 2.5)))
case("series.dtype-float", lambda: pd.Series([1, 2], dtype="float64"))
case("series.dtype-str", lambda: pd.Series([1, 2], dtype=str))
case("series.dtype-object", lambda: pd.Series(["a", None], dtype="object"))
case("series.dtype-int-bad", lambda: pd.Series([1.5, None], dtype="int64"))
case("series.int64-numpy-scalars", lambda: pd.Series([np.int64(3), np.int64(4)]))
case("series.int-float", lambda: pd.Series([1, 2.5]))
case("series.bool-int", lambda: pd.Series([True, 1]))
case("series.bool-none", lambda: pd.Series([True, None]))
case("series.only-none", lambda: pd.Series([None, None]))
case("series.nan-str", lambda: pd.Series(["a", float("nan")]))
case("series.ndarray-copied", lambda: (lambda a: (pd.Series(a), a.__setitem__(0, 99))[0])(np.array([1, 2])))

case("frame.dict", lambda: pd.DataFrame({"x": [1, 2, 3], "y": [1.5, 2.5, 3.5], "z": ["p", "q", "r"]}))
case("frame.dict-unequal", lambda: pd.DataFrame({"a": [1, 2], "b": [1]}))
case("frame.dict-index-mismatch", lambda: pd.DataFrame({"a": [1, 2]}, index=["x", "y", "z"]))
case("frame.dict-scalars", lambda: pd.DataFrame({"a": 1, "b": 2}))
case("frame.dict-scalar-list", lambda: pd.DataFrame({"a": 1, "b": [1, 2]}))
case("frame.dict-scalars-index", lambda: pd.DataFrame({"a": 1}, index=[0, 1]))
case("frame.dict-columns", lambda: pd.DataFrame({"a": [1, 2], "b": [3, 4]}, columns=["b", "c"]))
case("frame.dict-columns-dtypes", lambda: dtypes(pd.DataFrame({"a": [1, 2], "b": [3, 4]}, columns=["b", "c"])))
case("frame.lists", lambda: pd.DataFrame([[1, 2], [3, 4]]))
case("frame.lists-columns", lambda: pd.DataFrame([[1, "a"], [3, "b"]], columns=["n", "s"]))
case("frame.lists-columns-mismatch", lambda: pd.DataFrame([[1, 2], [3, 4]], columns=["a"]))
case("frame.dicts", lambda: pd.DataFrame([{"a": 1, "b": 2}, {"b": 3, "c": 4}]))
case("frame.dicts-columns", lambda: pd.DataFrame([{"a": 1}], columns=["a", "b"]))
case("frame.ndarray", lambda: pd.DataFrame(np.arange(6).reshape(2, 3)))
case("frame.ndarray-labels", lambda: pd.DataFrame(np.arange(6.0).reshape(2, 3), columns=list("xyz"), index=["r", "s"]))
case("frame.series", lambda: pd.DataFrame(pd.Series([1, 2], name="q")))
case("frame.series-noname", lambda: pd.DataFrame(pd.Series([1, 2])))
case("frame.dict-of-series-aligned", lambda: pd.DataFrame({"a": pd.Series([1, 2], index=["x", "y"]), "b": pd.Series([3, 4], index=["y", "z"])}))
case("frame.dict-of-series-list", lambda: pd.DataFrame({"a": pd.Series([1, 2], index=["x", "y"]), "b": [3, 4]}))
case("frame.dict-of-dicts", lambda: pd.DataFrame({"a": {"x": 1, "y": 2}}))
case("frame.empty", lambda: pd.DataFrame())
case("frame.empty-columns", lambda: pd.DataFrame(columns=["a", "b"]))
case("frame.empty-columns-dtypes", lambda: dtypes(pd.DataFrame(columns=["a", "b"])))
case("frame.dtype", lambda: pd.DataFrame({"a": [1, 2]}, dtype=float))
case("frame.lists-dtype", lambda: pd.DataFrame([[1, 2]], dtype="float64"))
case("frame.tuples", lambda: pd.DataFrame([(1, 2), (3, 4)]))
case("frame.flat-list", lambda: pd.DataFrame([1, 2, 3]))
case("frame.mixed-labels", lambda: pd.DataFrame({1: [1], "a": [2]}).columns)
case("frame.from-frame", lambda: pd.DataFrame(pd.DataFrame({"a": [1]})))
case("frame.ndarray-copied", lambda: (lambda a: (pd.DataFrame(a), a.__setitem__((0, 0), 99))[0])(np.zeros((2, 2))))

case("index.ints", lambda: pd.Index([1, 2]))
case("index.strs", lambda: pd.Index(["a", "b"]))
case("index.floats", lambda: pd.Index([1.5, 2]))
case("index.mixed", lambda: pd.Index([1, "a"]))
case("index.named", lambda: pd.Index(["a", "b"], name="nm"))
case("range.stop", lambda: pd.RangeIndex(5))
case("range.step-name", lambda: pd.RangeIndex(0, 10, 2, name="r"))
case("range.zero-step", lambda: pd.RangeIndex(0, 10, 0))
case("range.len", lambda: len(pd.RangeIndex(1, 10, 3)))
case("range.list", lambda: list(pd.RangeIndex(1, 10, 3)))

for i, (v, d) in enumerate([
        ([1.5, None], "int64"), ([1.5], "int64"), ([float("nan"), 1.0], "int64"), ([None], "int64"),
        ([1.0, 2.0], "int64"), (["1", "2"], "int64"), (["x"], "int64"), ([True, False], "int64"),
        ([2 ** 70], "int64"), (["x"], "float64"), (["1.5"], "float64"), ([True], "float64"),
        ([None, "a"], "float64"), ([1, 0], bool), (["a"], bool), ([None], bool), ([1.5, 0.0], bool),
        ([1, None], str), ([1.5, True], str)]):
    case("series.cast-%d-%s" % (i, d if isinstance(d, str) else d.__name__),
         lambda v=v, d=d: pd.Series(v, dtype=d).tolist())
